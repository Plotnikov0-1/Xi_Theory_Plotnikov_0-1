USABLE_W = A4[0] - 4 * cm


def P(text, st=S_BODY):
    return Paragraph(text, st)


def note(text):
    """Выделенная вставка-пояснение."""
    t = Table([[Paragraph(text, S_NOTE)]], colWidths=[USABLE_W])
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), BG),
        ("LEFTPADDING", (0, 0), (-1, -1), 10),
        ("RIGHTPADDING", (0, 0), (-1, -1), 10),
        ("TOPPADDING", (0, 0), (-1, -1), 8),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
        ("LINEBEFORE", (0, 0), (0, -1), 3, CLAY),
    ]))
    return t


def figure(name, caption, max_w=USABLE_W, max_h=12 * cm):
    """Картинка из figures/ с подписью, вписанная в страницу."""
    path = os.path.join(FIG, name)
    iw, ih = ImageReader(path).getSize()
    scale = min(max_w / iw, max_h / ih)
    img = Image(path, width=iw * scale, height=ih * scale)
    img.hAlign = "CENTER"
    return [img, P(caption, S_CAP)]


