#!/usr/bin/env python3
"""
Старший канон DIALOG QMT — строгий математико-физический отчёт.
Только математика и физика; формулы выведены по шагам с пояснениями.
Запуск:  python make_canon_report.py  →  report/DIALOG_QMT_Canon.pdf
"""

from __future__ import annotations

import os

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER, TA_JUSTIFY
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.units import cm
from reportlab.lib.utils import ImageReader
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.platypus import (
    Image, KeepTogether, PageBreak, Paragraph, SimpleDocTemplate, Spacer,
    Table, TableStyle,
)

ROOT = os.path.dirname(os.path.abspath(__file__))
FIG = os.path.join(ROOT, "figures")
OUT = os.path.join(ROOT, "report")
os.makedirs(OUT, exist_ok=True)

DV = "/usr/share/fonts/truetype/dejavu"
pdfmetrics.registerFont(TTFont("DV", f"{DV}/DejaVuSans.ttf"))
pdfmetrics.registerFont(TTFont("DV-Bold", f"{DV}/DejaVuSans-Bold.ttf"))
pdfmetrics.registerFont(TTFont("DV-Mono", f"{DV}/DejaVuSansMono.ttf"))

CLAY = colors.HexColor("#c46849")
INK = colors.HexColor("#222220")
GRAY = colors.HexColor("#5e5d59")
BG = colors.HexColor("#f3ead9")
EQBG = colors.HexColor("#eef2f6")
TEAL = colors.HexColor("#2f6f6d")


def st(name, **kw):
    base = dict(fontName="DV", textColor=INK, fontSize=10.5, leading=15.5)
    base.update(kw)
    return ParagraphStyle(name, **base)


S_TITLE = st("t", fontName="DV-Bold", fontSize=24, leading=28, textColor=CLAY, alignment=TA_CENTER)
S_SUB = st("s", fontSize=12.5, leading=17, textColor=GRAY, alignment=TA_CENTER)
S_H1 = st("h1", fontName="DV-Bold", fontSize=16, leading=21, textColor=CLAY, spaceBefore=16, spaceAfter=5)
S_H2 = st("h2", fontName="DV-Bold", fontSize=12.5, leading=17, textColor=TEAL, spaceBefore=11, spaceAfter=3)
S_BODY = st("b", alignment=TA_JUSTIFY, spaceAfter=5)
S_EQ = st("eq", fontName="DV-Mono", fontSize=11, leading=17, alignment=TA_CENTER, textColor=INK)
S_STEP = st("step", fontName="DV-Mono", fontSize=9.5, leading=14, leftIndent=14, textColor=INK)
S_NOTE = st("n", fontSize=9.7, leading=14, textColor=GRAY)
S_CAP = st("c", fontSize=9, leading=12.5, textColor=GRAY, alignment=TA_CENTER, spaceBefore=2, spaceAfter=9)

W = A4[0] - 4 * cm


def P(t, s=S_BODY):
    return Paragraph(t, s)


def eq(t):
    """Выключенная (центрированная) формула в светлой рамке."""
    tab = Table([[Paragraph(t, S_EQ)]], colWidths=[W])
    tab.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), EQBG),
        ("TOPPADDING", (0, 0), (-1, -1), 6), ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    return [Spacer(1, 3), tab, Spacer(1, 5)]


def steps(lines):
    """Цепочка вывода по шагам (моноширинный блок)."""
    return [Paragraph(ln, S_STEP) for ln in lines]


def note(t):
    tab = Table([[Paragraph(t, S_NOTE)]], colWidths=[W])
    tab.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), BG),
        ("LEFTPADDING", (0, 0), (-1, -1), 9), ("RIGHTPADDING", (0, 0), (-1, -1), 9),
        ("TOPPADDING", (0, 0), (-1, -1), 7), ("BOTTOMPADDING", (0, 0), (-1, -1), 7),
        ("LINEBEFORE", (0, 0), (0, -1), 3, CLAY),
    ]))
    return tab


def fig(name, caption, max_h=10.5 * cm):
    path = os.path.join(FIG, name)
    iw, ih = ImageReader(path).getSize()
    scale = min(W / iw, max_h / ih)
    im = Image(path, width=iw * scale, height=ih * scale)
    im.hAlign = "CENTER"
    return [Spacer(1, 4), KeepTogether([im, P(caption, S_CAP)])]


def build():
    s = []

    def A(x):
        s.extend(x) if isinstance(x, list) else s.append(x)

    # ===== Титул =====
    A(Spacer(1, 3.2 * cm))
    A(P("DIALOG QMT", S_TITLE))
    A(P("Старший канон: математика и физика памяти", S_SUB))
    A(Spacer(1, 0.4 * cm))
    A(P("Открытая квантовая система с немарковской памятью.<br/>"
        "Все формулы выведены по шагам.", S_SUB))
    A(Spacer(1, 2.2 * cm))
    A(P("О статусах утверждений", S_H2))
    A(P("Каждый результат помечен уровнем строгости: <b>Q0</b> — тождество "
        "(следует из определений); <b>Q1</b> — теорема (из аксиом); <b>Q2</b> — "
        "аналитическое следствие; <b>Q3</b> — предсказание, ожидающее эксперимента. "
        "Этот отчёт содержит только математику и физику; интерпретационный "
        "(смысловой) слой сюда не входит."))
    A(note("Предмет модели. Частица/система взаимодействует с электромагнитным "
           "резервуаром (модель Калдейры–Леггетта). Ключевая величина — "
           "<b>параметр памяти ε</b>, накопленная история взаимодействий. Гипотеза: "
           "ε — самостоятельная физическая переменная, не тождественная массе m."))
    A(PageBreak())

    # ===== 1. Фундамент =====
    A(P("1. Математический фундамент", S_H1))

    A(P("1.1. Центральное тождество масштаба (Q0)", S_H2))
    A(P("Для частицы массы m определены комптоновская длина a и частота "
        "Циттербевегунга ω:"))
    A(eq("a = ℏ / (m·c)        ω = m·c² / ℏ"))
    A(P("Их произведение получается прямой подстановкой:"))
    A(steps([
        "a · ω = [ℏ/(m c)] · [m c²/ℏ]",
        "      = (ℏ · m · c²) / (m · c · ℏ)",
        "      = c.",
    ]))
    A(P("Физический смысл: скорость передачи сигнала ограничена c на любом масштабе. "
        "Отсюда верхний обрез частот резервуара ω_c = m·c²/ℏ (для электрона "
        "ω_c ≈ 7.76·10²⁰ рад/с). Все частоты модели нормируются на ω_c."))

    A(P("1.2. Спектральная плотность резервуара (Q1)", S_H2))
    A(P("Из трёх предпосылок: (i) плотность фотонных мод 3-мерного вакуума "
        "ρ(ω) ∝ ω²; (ii) дипольная связь |g(ω)|² ∝ ω; (iii) экспоненциальный обрез "
        "exp(−ω/ω_c). Перемножая:"))
    A(eq("J(ω) = ρ(ω)·|g(ω)|²·e^(−ω/ω_c) = J₀ · ω³ · e^(−ω/ω_c)"))
    A(P("Это «суперомический» спектр (J ∝ ω³). Аналитические коэффициенты — "
        "табличные интегралы (∫₀^∞ ωⁿ e^(−ω/ω_c) dω = n!·ω_c^(n+1)):"))
    A(steps([
        "η = ∫₀^∞ J(ω) dω      = J₀ · 3! · ω_c⁴ = 6 J₀ ω_c⁴   (скорость затухания)",
        "ξ = ∫₀^∞ J(ω)/ω² dω  = J₀ · 1! · ω_c²  =  J₀ ω_c²    (дисперсия памяти)",
        "⇒ η/ξ = 6 ω_c²        (аналитически, без подгонки).",
    ]))
    A(P("Следствие суперомичности: при ω→0 система не декогерирует — сохраняется "
        "<b>немарковский</b> режим (память не стирается мгновенно)."))
    A(fig("1_spectral_density.png",
          "Рис. 1. Спектральная плотность J(ω)=J₀ω³e^(−ω/ω_c). Вертикаль — обрез ω_c.",
          max_h=7.5 * cm))

    A(P("1.3. Уравнение памяти (Накадзима–Зваанциг) (Q0)", S_H2))
    A(P("Эволюция матрицы плотности открытой системы с памятью:"))
    A(eq("d/dt ρ(t) = −(i/ℏ)[H_s, ρ] + ∫₀ᵗ K(t−s)·ρ(s) ds"))
    A(P("Ядро K(t−s) ≠ 0 при τ>0 означает: прошлое влияет на настоящее. Параметр ε "
        "накапливает эту историю. В марковском пределе K(τ)→K₀·δ(τ) уравнение "
        "сводится к стандартному уравнению Линдблада."))
    A(PageBreak())

    # ===== 2. Золотой аттрактор =====
    A(P("2. Золотой аттрактор φ−1: два независимых вывода", S_H1))
    A(P("Число φ = (1+√5)/2 ≈ 1.618 (золотое сечение) появляется в модели не как "
        "подобранная константа, а как <b>устойчивая неподвижная точка</b>. Это "
        "показано двумя разными путями, дающими одно и то же число."))

    A(P("2.1. Путь динамики (Q2)", S_H2))
    A(P("Золотое сечение удовлетворяет φ² = φ + 1. Разделив на φ:"))
    A(steps([
        "φ² = φ + 1   |  ÷ φ",
        "φ  = 1 + 1/φ",
        "1/φ = φ − 1   ⇒   X* = φ − 1 = 0.6180339887…",
    ]))

    A(P("2.2. Путь самосогласованности сборки (Q1)", S_H2))
    A(P("Пусть x = ε/E — доля реализованной памяти. Условие самосогласованности: "
        "отношение «остаток : реализовано» равно «реализовано : целое»:"))
    A(steps([
        "(E − ε)/ε = ε/E      ⇒   (1 − x)/x = x",
        "1 − x = x²           ⇒   x² + x − 1 = 0",
        "x = (−1 + √5)/2 = φ − 1 = 0.618…   (положительный корень).",
    ]))
    A(note("Два разных уравнения — φ²=φ+1 (динамика) и x²+x−1=0 "
           "(самосогласованность) — дают одно число φ−1. Это сильный аргумент: "
           "совпадение не случайно (по сути это одно и то же алгебраическое условие)."))

    A(P("2.3. φ как оператор (Q1)", S_H2))
    A(P("Рассмотрим оператор отношения T(x) = 1/(1+x). Его неподвижная точка:"))
    A(steps([
        "x = 1/(1+x)  ⇒  x + x² = 1  ⇒  x² + x − 1 = 0  ⇒  x* = φ − 1.",
        "Производная: T′(x) = −1/(1+x)².  При x*=φ−1, (1+x*)=φ:",
        "|T′(x*)| = 1/φ² ≈ 0.382 < 1   ⇒  неподвижная точка УСТОЙЧИВА.",
    ]))
    A(P("Поэтому итерация x_{n+1}=1/(1+x_n) сходится к φ−1 из любого старта; "
        "дискретно это отношения чисел Фибоначчи F_n/F_{n+1} → φ−1."))
    A(fig("17_phi_operator_kernel.png",
          "Рис. 2. Слева: T(x)=1/(1+x) сходится к φ−1 из разных стартов. "
          "Справа: ядро памяти K(t), построенное из матрицы (раздел 6).", max_h=7.5 * cm))
    A(PageBreak())

    # ===== 3. Геометрический каркас =====
    A(P("3. Геометрический каркас", S_H1))
    A(P("3.1. Минимум и пять платоновых тел (Q1, символьно)", S_H2))
    A(P("Конструкция: сфера-оболочка радиуса R=√3, центральная точка с операцией "
        "инверсии −I, и один тетраэдр-генератор. Инверсия разворачивает тетраэдр во "
        "второй (звезда), их объединение — куб, пересечение — октаэдр. Добавление "
        "точек с координатами, содержащими φ, даёт додекаэдр и икосаэдр. Все "
        "соотношения проверены символьно (точно):"))
    tbl = Table([
        ["тело", "V", "E", "F", "V−E+F", "ребро²", "R²"],
        ["тетраэдр", "4", "6", "4", "2", "8", "3"],
        ["куб", "8", "12", "6", "2", "4", "3"],
        ["октаэдр", "6", "12", "8", "2", "2", "1"],
        ["додекаэдр", "20", "30", "12", "2", "6−2√5", "3"],
        ["икосаэдр", "12", "30", "20", "2", "4", "φ+2"],
    ], colWidths=[3 * cm, 1.4 * cm, 1.4 * cm, 1.4 * cm, 2 * cm, 3 * cm, 2 * cm])
    tbl.setStyle(TableStyle([
        ("FONT", (0, 0), (-1, 0), "DV-Bold", 9.5),
        ("FONT", (0, 1), (-1, -1), "DV", 9.5),
        ("BACKGROUND", (0, 0), (-1, 0), EQBG),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#cccccc")),
        ("ALIGN", (1, 0), (-1, -1), "CENTER"),
        ("TOPPADDING", (0, 0), (-1, -1), 3), ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
    ]))
    A([Spacer(1, 3), tbl, Spacer(1, 6)])
    A(P("Формула Эйлера V−E+F=2 выполняется для всех пяти. Куб и додекаэдр лежат на "
        "<b>одной</b> сфере (R²=3). Больше пяти выпуклых правильных тел не существует "
        "(теорема Евклида). Золотое сечение φ — единственный мост из «алгебраического» "
        "мира (√2,√3) в «золотой» (φ): пятикратная симметрия запрещена кубу и "
        "появляется только в икосаэдре."))
    A(fig("8_platonic_bridge.png",
          "Рис. 3. Куб (8 вершин) вложен в додекаэдр (20) на одной сфере R²=3.",
          max_h=8 * cm))

    A(P("3.2. Группы симметрий и правила отбора (Q1)", S_H2))
    A(P("Группы вращений тел: тетраэдр T≅A₄ (порядок 12), куб/октаэдр O≅S₄ (24), "
        "додекаэдр/икосаэдр I≅A₅ (60); полная группа куба — O_h=S₄×Z₂ (48). "
        "Зеркало −I на 3 кубитах реализуется оператором X⊗X⊗X (переворот всех бит). "
        "По теореме Вигнера–Эккарта симметрия диктует, какие переходы запрещены — "
        "это и есть правила отбора (раздел 4)."))
    A(PageBreak())

    # ===== 4. Рабочая модель =====
    A(P("4. Рабочая модель: узлы, переходы, синхронизация с водородом", S_H1))
    A(P("4.1. Размещение и уровни (Q0)", S_H2))
    A(P("Восемь вершин куба нумеруются числами 1,2,3,4,6,7,8,9; центр — 5; "
        "оболочка — 0. Каждый номер n отождествляется с уровнем атома водорода:"))
    A(eq("E_n = −13.6 / n²  (эВ)"))

    A(P("4.2. Правила отбора (Q1)", S_H2))
    A(P("Вершина куба — это 3 бита. Расстояние Хэмминга h (число различных бит) "
        "классифицирует переход a↔b:"))
    A(steps([
        "h = 1 (ребро)            →  ПРЯМОЙ переход (один квант);",
        "сумма индексов = 9       →  РЕЗОНАНС (туннель Sum-9);",
        "сумма индексов = 10 (h=3)→  ЗЕРКАЛО −I (инверсия/чётность);",
        "прочее (диагональ грани) →  ЗАПРЕЩЕНО (нет канала).",
    ]))
    A(P("Из 28 пар вершин: 10 прямых + 3 резонанса + 4 зеркала = <b>17 разрешено</b>, "
        "<b>11 запрещено</b>. Это аналог дипольных правил отбора в атоме."))

    A(P("4.3. Синхронизация со спектром водорода (Q0/Q1)", S_H2))
    A(P("Каждый разрешённый переход n↔n′ даёт реальную линию по формуле Ридберга:"))
    A(eq("1/λ = R_∞ · (1/n_low² − 1/n_high²),   R_∞ = 1.097·10⁷ м⁻¹"))
    A(P("Вычисленные длины волн совпадают с реальным спектром и с числами исходной "
        "архитектуры (без подгонки):"))
    A(steps([
        "1↔2 = 121.5 нм   (Лайман α);",
        "2↔7 = 396.9 нм   (резонанс Sum-9; в архитектуре указано 397 нм);",
        "3↔7 = 1004.7 нм  (зеркало; в архитектуре указано 1005 нм).",
    ]))
    A(fig("18_working_model.png",
          "Рис. 4. Рабочая модель. Слева — куб с числами и классифицированными "
          "переходами. Справа — те же переходы как линии спектра водорода.",
          max_h=8.5 * cm))
    A(PageBreak())

    # ===== 5. Динамика =====
    A(P("5. Динамическая система и бифуркация-сборка", S_H1))
    A(P("5.1. Уравнения движения (Q2/модель)", S_H2))
    A(P("Четыре связанные величины: X — нагрузка (осциллятор), ε — память, "
        "μ — проводимость, τ — внутреннее время. Уравнения:"))
    A(eq("dX/dt = F₁(X) − γX − μX + ξε,   F₁(X)=X₀/(1+X/X₀)"))
    A(eq("dε/dt = ηX − ξε,   dμ/dt = α(μ_t − μ) − κXμ,   dτ/dt = 1/(1+X)"))

    A(P("5.2. Стационарная точка и бифуркация (Q2)", S_H2))
    A(P("При квазистатической памяти (dε/dt=0 ⇒ ε=(η/ξ)X) и условии γ=η уравнение "
        "для X сводится к dX/dt = F₁(X) − μX. Его стационарная точка:"))
    A(steps([
        "F₁(X*) = μ X*   ⇒   X₀²/(X₀+X*) = μ X*",
        "X* = X₀ · (−1 + √(1 + 4/μ)) / 2.",
        "При X₀ = φ−1 и μ = μ_crit = 0.5:  X* = (φ−1)·(−1+3)/2 = φ−1.",
    ]))
    A(P("То есть при критической проводимости μ=0.5 система садится точно на золотую "
        "точку φ−1. Якобиан в этой точке отрицателен — точка устойчива."))
    A(fig("4_bifurcation.png",
          "Рис. 5. Стационарная нагрузка X*(μ). При μ=0.5 — золотая точка φ−1.",
          max_h=7 * cm))

    A(P("5.3. Это катастрофа сборки (Q2)", S_H2))
    A(P("Переход между двумя устойчивыми режимами — каноническая катастрофа сборки "
        "(cusp) Рене Тома. Её потенциал и множество складок:"))
    A(eq("V(x) = x⁴/4 + μ₂·x²/2 + μ₁·x,    V′(x)=x³+μ₂x+μ₁=0"))
    A(eq("граница складок:  4·μ₂³ + 27·μ₁² = 0"))
    A(P("Внутри «клина» (μ₂<0) уравнение V′=0 имеет три корня — два устойчивых "
        "состояния и одно неустойчивое (бистабильность + скачок-гистерезис). "
        "Элементарных катастроф ровно семь (Том, 1972); сборка — простейшая с "
        "бистабильностью."))
    A(fig("15_cusp_catastrophe.png",
          "Рис. 6. Катастрофа сборки: клин бистабильности (слева) и петля "
          "гистерезиса (справа).", max_h=7.5 * cm))
    A(PageBreak())

    # ===== 6. Память: канон =====
    A(P("6. Память: старший канон", S_H1))
    A(P("Это ядро модели. Память входит снизу, а не добавляется задним числом."))

    A(P("6.1. Лестница сборки (Q1)", S_H2))
    A(eq("Ω₀ → S₀(ε₀≠0) → ν → E=hν → ε* = φ−1 → 0* → динамика"))
