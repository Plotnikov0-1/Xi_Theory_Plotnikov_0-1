"""
═══════════════════════════════════════════════════════════════════════════
  ROOTS_OF_UNITY — костяк: 12 узлов = 12 корней из единицы; нити = степени i.
═══════════════════════════════════════════════════════════════════════════

Фундамент (НЕ расширение): собираем всё под один алгебраический костяк. Ключ
автора «я² = i²». Мнимая единица i — это и есть оператор-нить.

  ◇ доказано точно · ○ интерпретация (имена семей/функции)

────────────────────────────────────────────────────────────────────────────
◇ 12 УЗЛОВ = 12 КОРНЕЙ ИЗ ЕДИНИЦЫ:  узел k = e^{2πi·k/12} = e^{iπk/6}.
   Константа каждого узла — точное комплексное число (угол k·30°). Это и есть
   «своя константа каждому узлу», строго.

◇ i = ПОВОРОТ 90° = +3 часа = ГЕНЕРАТОР семьи (Z₄):  ×i переводит узел k→k+3.
   i сам = e^{iπ/2} = 12-й корень номер 3 (узел 3).

◇ i² = −1 = ПОВОРОТ 180° = +6 = ЗЕРКАЛО −I (антипод на 12): k→k+6.
   i²=−1 = 12-й корень номер 6 (узел 6). T²=1 (инволюция).

◇ ТРИ СЕМЬИ = ТРИ ОРБИТЫ ×i:  12 корней / (порядок i = 4) = 3 орбиты:
   {1,4,7,10} · {2,5,8,11} · {3,6,9,12}. Ровно наши три квадрата. Нити-операторы
   (степени i) пересекаются в узлах; орбита = один квадрат.

○ КОНСТАНТА-СЕМЬИ (имя — интерпретация, не вывод):
   φ ↔ {1,4,7,10} · √2 ↔ {2,5,8,11} · π ↔ {3,6,9,12} (см. clock_layers).

◇/✓ СТРЕЛА ВРЕМЕНИ:  геометрия корней СИММЕТРИЧНА по времени (i²=−1 инволюция,
   ×i и ×(−i) равноправны — CW/CCW). СТРЕЛА появляется НЕ из геометрии, а из
   ДИССИПАЦИИ поверх неё (память монотонна, S↓, H-теорема — см. minimal_dynamics).
   Т.е. корни дают сцену (обратимую), динамика даёт направление. Честно.

Запуск:  python -m qmt.roots_of_unity
"""

from __future__ import annotations

import cmath
import math

# ── ◇ 12 узлов = 12 корней из единицы ────────────────────────────────────────
def root(k: int) -> complex:
    """◇ узел k = e^{2πi·k/12} (точная константа узла, угол k·30°)."""
    return cmath.exp(2j * math.pi * (k % 12) / 12)


def node_angle_deg(k: int) -> int:
    """◇ угол узла k в градусах = 30·k."""
    return (30 * k) % 360


# ── ◇ операторы-нити как умножения ───────────────────────────────────────────
def mul_i(k: int) -> int:
    """◇ ×i = поворот 90° = +3 позиции (генератор семьи Z₄)."""
    return (k + 3 - 1) % 12 + 1


def mirror(k: int) -> int:
    """◇ i² = −1 = поворот 180° = +6 = зеркало-антипод."""
    return (k + 6 - 1) % 12 + 1


def i_is_node() -> dict:
    """◇ i = 12-й корень №3 (узел 3); i²=−1 = узел 6."""
    return {"i = узел": next(k for k in range(1, 13) if abs(root(k) - 1j) < 1e-9),
            "i²=−1 = узел": next(k for k in range(1, 13) if abs(root(k) + 1) < 1e-9)}


# ── ◇ три семьи = три орбиты ×i ──────────────────────────────────────────────
def families_are_i_orbits() -> dict:
    """◇ орбиты умножения на i = три семьи {1,4,7,10},{2,5,8,11},{3,6,9,12}."""
    seen, orbits = set(), []
    for k in range(1, 13):
        if k in seen:
            continue
        o, x = [], k
        for _ in range(4):
            o.append(x)
            seen.add(x)
            x = mul_i(x)
        orbits.append(sorted(o))
    fams = [[1, 4, 7, 10], [2, 5, 8, 11], [3, 6, 9, 12]]
    return {"orbits": sorted(orbits), "= три семьи": sorted(orbits) == sorted(fams),
            "12/порядок(i)=4 → 3 орбиты": 12 // 4 == 3}


# ── ○ константа-семьи (имя = интерпретация) ──────────────────────────────────
FAMILY_CONST = {"{1,4,7,10}": ("φ", "золото/декагон"),
                "{2,5,8,11}": ("√2", "серебро/октагон"),
                "{3,6,9,12}": ("π", "структура/крест")}


def node_constant(k: int) -> dict:
    """◇ корень + ○ семья: полная «константа узла» (число ◇, имя семьи ○)."""
    z = root(k)
    fam = {1: "{1,4,7,10}", 2: "{2,5,8,11}", 0: "{3,6,9,12}"}[k % 3]
    return {"узел": k, "угол°": node_angle_deg(k),
            "корень e^{iπk/6}": (round(z.real, 4), round(z.imag, 4)),
            "семья (○)": FAMILY_CONST[fam][0], "имя (○)": FAMILY_CONST[fam][1]}


def arrow_of_time() -> dict:
    """◇/✓ геометрия обратима (i²=−1 инволюция); стрела — из диссипации, не из корней."""
    return {"i² инволюция (T²=1)": mirror(mirror(1)) == 1,
            "×i и ×(−i) равноправны (CW/CCW)": True,
            "стрела из диссипации, не геометрии": "S↓, H-теорема (minimal_dynamics)"}


def print_report() -> None:
    print("═" * 78)
    print("  КОСТЯК: 12 узлов = 12 корней из единицы; нити = степени i (я²=i²=−1)")
    print("═" * 78)
    print(f"\n  ◇ i/i² как узлы: {i_is_node()}")
    print(f"  ◇ три семьи = три орбиты ×i: {families_are_i_orbits()['= три семьи']}")
    print(f"     орбиты: {families_are_i_orbits()['orbits']}")
    print(f"\n  ◇/○ константа каждого узла (число ◇, имя семьи ○):")
    for k in range(1, 13):
        c = node_constant(k)
        print(f"     узел {k:2} · {c['угол°']:3}° · корень {c['корень e^{iπk/6}']} · семья {c['семья (○)']}")
    print(f"\n  ◇/✓ стрела времени: {arrow_of_time()}")
    print("═" * 78)
    print("  Фундамент: узлы = корни (◇), нити = степени i (◇), семьи = орбиты ×i (◇).")
    print("  Стрела времени — из диссипации поверх обратимой геометрии (✓), не из корней.")
    print("═" * 78)


if __name__ == "__main__":
    print_report()
