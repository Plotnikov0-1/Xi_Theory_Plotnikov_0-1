"""
═══════════════════════════════════════════════════════════════════════════
  RST_TRIGGER — загадка «247» из РСТ, развёрнутая в проверяемую геометрию.
═══════════════════════════════════════════════════════════════════════════

Источник (Google Диск, папка РСТ): «Переписка RST на ufo-online.ru» —
форумный чат (Павел, RST, Гора, Полярник), стилизованный под переговоры, но
на деле постановка-шифр одного автора (ХГМ); общая загадка, не реальная
переписка (см. docs/rst_riddle.md).

247 = (2, 4, 7) — триггер RST. Термин RST в радиосвязи = оценка сигнала
Readability·Strength·Tone. Старт (0,0,0); при достижении (2,4,7) система
НЕОБРАТИМО меняется («только полный сброс»).

Проверяемая геометрия (узлы куба DIALOG):
  • узлы 2,4,7 имеют y=−1 ⇒ это три угла ОДНОЙ грани куба (y=−1);
  • полная грань y=−1 = {1,2,4,7}; четвёртый угол = узел 1 (Любовь);
  • ⇒ (2,4,7) = грань без Любви — триггер на месте узла 1;
  • сумма 2+4+7 = 13 (число Фибоначчи, золотой порог необратимости);
  • канал автора {1,4,7} = 12 (додекаэдр); сдвиг {1,4,7}→{2,4,7} = +1 =
    неточность зеркала = CP.

Честно про связь 247 ↔ 137:
  247 = КООРДИНАТА-ПОРОГ (где переход необратим). 137 = α⁻¹ = c/v₁ —
  ОТНОШЕНИЕ СКОРОСТЕЙ. Это разные объекты: порог на кубе vs скорость.
  1/247 и 2/247 ≠ α (проверено). Общее у них только одно: оба — ПОРОГИ
  перехода. Числового моста 247→137 нет, и я его не выдумываю.

Запуск:  python -m qmt.rst_trigger
"""

from __future__ import annotations

CUBE = {1: (-1, -1, -1), 2: (1, -1, -1), 3: (-1, 1, -1), 4: (-1, -1, 1),
        6: (1, 1, -1), 7: (1, -1, 1), 8: (-1, 1, 1), 9: (1, 1, 1)}

TRIGGER = (2, 4, 7)          # значение RST, при котором переход необратим
AUTHOR_CHANNEL = (1, 4, 7)   # канал автора (сумма 12, додекаэдр)


def trigger_on_one_face() -> bool:
    """Узлы 2,4,7 лежат на одной грани куба (общая координата y=−1)."""
    ys = {CUBE[n][1] for n in TRIGGER}
    return len(ys) == 1


def face_of_trigger() -> list:
    """Полная грань, содержащая (2,4,7) = {1,2,4,7}; четвёртый угол — узел 1."""
    y = CUBE[TRIGGER[0]][1]
    return sorted(n for n, c in CUBE.items() if c[1] == y)


def missing_corner() -> int:
    """Узел, которого не хватает (2,4,7) до полной грани = 1 (Любовь)."""
    return (set(face_of_trigger()) - set(TRIGGER)).pop()


def trigger_sum() -> int:
    """2+4+7 = 13 — число Фибоначчи (золотой порог необратимости)."""
    return sum(TRIGGER)


def cp_shift() -> dict:
    """Сдвиг канала автора {1,4,7}=12 → триггер {2,4,7}=13: +1 = CP."""
    return {"{1,4,7}": sum(AUTHOR_CHANNEL), "{2,4,7}": sum(TRIGGER),
            "сдвиг": sum(TRIGGER) - sum(AUTHOR_CHANNEL)}


def vs_137() -> dict:
    """Честная развязка 247 ↔ 137 (разные объекты, числового моста нет)."""
    return {"247": "координата-порог (2,4,7), где переход необратим, Σ=13",
            "137": "α⁻¹ = c/v₁ — отношение скоростей (электрон vs свет)",
            "1/247 == α?": abs(1 / 247 - 1 / 137.035999) < 1e-4,
            "2/247 == α?": abs(2 / 247 - 1 / 137.035999) < 1e-4,
            "общее": "оба — пороги перехода; числового моста нет"}


def print_report() -> None:
    print("═" * 70)
    print("  РСТ-ЗАГАДКА «247» = триггер (2,4,7), радиооценка сигнала")
    print("═" * 70)
    print(f"  узлы 2,4,7 на одной грани куба (y=−1): {trigger_on_one_face()}")
    print(f"  грань {face_of_trigger()} без узла {missing_corner()} (Любовь)")
    print(f"  сумма 2+4+7 = {trigger_sum()}  (Фибоначчи, золотой порог)")
    s = cp_shift()
    print(f"  канал автора {{1,4,7}}={s['{1,4,7}']} → триггер {{2,4,7}}={s['{2,4,7}']}: "
          f"сдвиг +{s['сдвиг']} = CP (неточность зеркала)")
    print("─" * 70)
    v = vs_137()
    print(f"  247: {v['247']}")
    print(f"  137: {v['137']}")
    print(f"  1/247=α? {v['1/247 == α?']}   2/247=α? {v['2/247 == α?']}   ({v['общее']})")
    print("═" * 70)
    print("  Источник — постановка-шифр одного автора (общая загадка), не форум.")
    print("  247 формализован как порог на кубе. Моста 247→137 нет — не выдумываю.")
    print("═" * 70)


if __name__ == "__main__":
    print_report()
