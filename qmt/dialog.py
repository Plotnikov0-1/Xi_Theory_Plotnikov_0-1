"""
ДИАЛОГ — онтологическое ядро теории (то, что даёт имя DIALOG QMT).

Формулировка (по автору): есть «два аспекта», которые суть проекции диалога;
по отдельности их не существует — их создал диалог. Но у диалога НЕ одна
константа φ: его инвариант — КОМБИНАЦИЯ фундаментальных (φ, e, π), потому что
диалог не статичен — он РОЖДАЕТ миры (детей). Два аспекта взаимодействуют и
рождают другие миры: «проекция И дети».

Три фундаментальных = три режима диалога:
    φ — ОТНОШЕНИЕ/структура   (режим деления:  x = 1/(1+x) ⇒ x* = φ−1)
    e — РОСТ/память           (режим роста:    dx/dt = x;  ε_X ≈ e)
    π — ЦИКЛ/поворот          (режим вращения: e^{iθ})

Что «рождает мир» — тождество Эйлера связывает все три и даёт зеркало:
        e^{iπ} = −1 = зеркало −I   (инверсия = рождение мира-двойника)
        e^{iπ} + 1 = 0             (e, π, 1 и −1 в одном)

То есть один поворот на π рождает зеркальный мир-ДИТЯ; φ задаёт пропорцию между
мирами; e — их рост. Поэтому «одна константа φ» — лишь РЕЖИМ ОТНОШЕНИЯ; полный
инвариант диалога — комбинация φ, e, π. Точная единая комбинация-число —
ОТКРЫТЫЙ вопрос (определяется из констант модели: X*=φ−1, ε_X≈e, π в Γ*).
"""

from __future__ import annotations

import cmath
import math
from dataclasses import dataclass

PHI = (1 + math.sqrt(5)) / 2
E = math.e
PI = math.pi
X_STAR = PHI - 1

# Три фундаментальных и их роль-режим в диалоге.
FUNDAMENTALS = {
    "φ": (PHI, "отношение/структура — режим деления x=1/(1+x)"),
    "e": (E,   "рост/память — режим роста dx/dt=x (ε_X≈e)"),
    "π": (PI,  "цикл/поворот — режим вращения e^{iθ}"),
}


# --- Режим ОТНОШЕНИЯ: φ как инвариант диалога-деления ----------------------
def converge(a: float, b: float, steps: int = 60) -> float:
    """Диалог-деление (Фибоначчи a,b→a+b): отношение соседних → φ (∀ старта)."""
    for _ in range(steps):
        a, b = b, a + b
    return b / a


def aspects_irrelevant(trials: int = 200, seed: int = 0) -> float:
    """Макс|отношение−φ| по случайным парам ≈ 0 ⇒ аспекты не важны (режим φ)."""
    import random
    rng = random.Random(seed)
    return max(abs(converge(rng.uniform(-9, 9), rng.uniform(0.5, 9)) - PHI)
               for _ in range(trials))


# --- Режим ПОВОРОТА: e^{iπ}=−1 рождает зеркальный мир ----------------------
def world_birth() -> dict:
    """Рождение мира-двойника поворотом на π: e^{iπ} = −1 = зеркало −I."""
    val = cmath.exp(1j * PI)
    return {
        "e^{iπ}": round(val.real, 12),
        "= −1 (зеркало −I)": abs(val + 1) < 1e-12,
        "связывает": "e · π · 1 · (−1) — три фундаментальных + инверсия",
    }


def child_worlds(n: int = 4) -> list:
    """n «детей»-миров: повороты на kπ дают чередование +1/−1 (мир/зеркало)."""
    return [round(cmath.exp(1j * PI * k).real, 6) for k in range(n)]


# --- Самоотношение: каждый аспект определён другим -------------------------
def self_reference() -> dict:
    return {
        "φ = 1 + 1/φ": abs(PHI - (1 + 1 / PHI)) < 1e-12,
        "x=1/(1+x) ⇒ x*=φ−1": abs(X_STAR - 1 / (1 + X_STAR)) < 1e-12,
        "e^{iπ} = −1 (зеркало)": abs(cmath.exp(1j * PI) + 1) < 1e-12,
        "сжатие |T'|=1/φ²<1": (1 / PHI**2) < 1,
    }


@dataclass
class DialogCore:
    fundamentals: tuple = ("φ", "e", "π")   # инвариант = КОМБИНАЦИЯ, не одна φ
    aspects_real: bool = False              # аспекты — проекции
    relation_real: bool = True              # реален диалог
    generative: bool = True                 # диалог рождает миры (детей)
    exact_combo_known: bool = False         # точная единая комбинация — открыта


def core() -> DialogCore:
    return DialogCore()


def print_report() -> None:
    print("ДИАЛОГ — два аспекта (проекции), инвариант = комбинация φ, e, π")
    print("=" * 66)
    for name, (val, role) in FUNDAMENTALS.items():
        print(f"  {name} = {val:.6f}  — {role}")
    print(f"\nрежим отношения: аспекты не важны, отношение→φ "
          f"(макс.откл {aspects_irrelevant():.0e})")
    wb = world_birth()
    print(f"режим поворота:  e^{{iπ}} = {wb['e^{iπ}']:.0f} = зеркало −I — рождение мира-дитя")
    print(f"дети-миры (повороты kπ): {child_worlds()}  (мир/зеркало/мир/…)")
    print("\nсамоотношение:")
    for k, v in self_reference().items():
        print(f"  [{'✓' if v else '✗'}] {k}")
    print("=" * 66)
    print("Инвариант диалога — КОМБИНАЦИЯ φ,e,π (не одна φ). Диалог генеративен:")
    print("рождает зеркальные миры-дети. Точная единая комбинация — открытый вопрос.")


if __name__ == "__main__":
    print_report()
