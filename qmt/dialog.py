"""
ДИАЛОГ — онтологическое ядро теории (то, что даёт имя DIALOG QMT).

Формулировка (по автору): есть «два аспекта», между которыми будто бы есть
расстояние. Но они ничего не «решают» — они ВЕДУТ диалог и САМИ суть этот
диалог. По отдельности их не существует: диалог создал их как ПРОЕКЦИЮ. И у
них всего ОДНА математическая константа — отношение/расстояние между ними.

Математически: реально не «две вещи», а РЕЛЯЦИЯ (диалог). Аспекты — её
проекции, а инвариант один — золотое отношение φ.

Доказательство «аспекты не важны, важна константа»:
каждый новый член рождён диалогом двух предыдущих (a, b → a+b — Фибоначчи-шаг).
Из ЛЮБОЙ стартовой пары отношение соседних членов сходится к φ:

        s_{n+1} = s_n + s_{n-1},   s_{n+1}/s_n → φ   (∀ старта)

Эквивалентные записи диалога (каждый аспект определён другим):
        φ = 1 + 1/φ          (φ² = φ + 1)
        x = 1/(1+x) ⇒ x*=φ−1  (оператор T, см. phi_operator; |T'|=1/φ²<1)
        (a+b)/a = a/b = φ     (целое:большее = большее:меньшее)

Итог: существует диалог (отношение), а не аспекты; единственная константа — φ.
Геометрические «расстояния» модели (√3, 3/φ, зазор-туннель, два нуля) — это уже
ПРОИЗВОДНЫЕ выражения одной этой константы.
"""

from __future__ import annotations

import math
from dataclasses import dataclass

PHI = (1 + math.sqrt(5)) / 2          # единственная константа диалога
X_STAR = PHI - 1                      # = 1/φ (аттрактор, см. constants.X_STAR)


def converge(a: float, b: float, steps: int = 60) -> float:
    """Диалог из пары (a,b): Фибоначчи-шаг; вернуть отношение соседних → φ."""
    for _ in range(steps):
        a, b = b, a + b
    return b / a


def aspects_irrelevant(trials: int = 200, seed: int = 0) -> float:
    """Макс. отклонение отношения от φ по случайным стартовым парам.

    Близко к 0 ⇒ аспекты не важны, инвариант один — φ.
    """
    import random
    rng = random.Random(seed)
    worst = 0.0
    for _ in range(trials):
        a = rng.uniform(-9, 9)
        b = rng.uniform(0.5, 9)         # избегаем вырожденных
        worst = max(worst, abs(converge(a, b) - PHI))
    return worst


def self_reference() -> dict:
    """Диалог как самоотношение: каждый аспект определён другим (фикс. точка)."""
    return {
        "φ = 1 + 1/φ": abs(PHI - (1 + 1 / PHI)) < 1e-12,
        "φ² = φ + 1": abs(PHI**2 - (PHI + 1)) < 1e-12,
        "x=1/(1+x) ⇒ x*=φ−1": abs(X_STAR - 1 / (1 + X_STAR)) < 1e-12,
        "сжатие |T'|=1/φ²<1": (1 / PHI**2) < 1,
    }


@dataclass
class DialogCore:
    constant: float = PHI               # единственная константа (отношение)
    aspects_real: bool = False          # аспекты — проекции, не существуют сами
    relation_real: bool = True          # реален диалог (отношение)


def core() -> DialogCore:
    return DialogCore()


def print_report() -> None:
    print("ДИАЛОГ — два аспекта как проекции, одна константа = отношение")
    print("=" * 64)
    print(f"единственная константа диалога: φ = {PHI:.10f}  (X*=φ−1={X_STAR:.10f})")
    print(f"аспекты не важны — макс|отношение−φ| по 200 случайным парам: "
          f"{aspects_irrelevant():.1e}")
    print("\nдиалог как самоотношение (каждый аспект определён другим):")
    for k, v in self_reference().items():
        print(f"  [{'✓' if v else '✗'}] {k}")
    print("=" * 64)
    print("Реален диалог (отношение φ), а не аспекты. Геометрические расстояния")
    print("модели (√3, 3/φ, зазор-туннель, два нуля) — производные этой константы.")


if __name__ == "__main__":
    print_report()
