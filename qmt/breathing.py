"""
═══════════════════════════════════════════════════════════════════════════
  BREATHING — «Закон Дыхания» честно + фальсифицируемый выход + несовместимости.
═══════════════════════════════════════════════════════════════════════════

Разбор статьи v13 «Закон Дыхания» и версий C_eff из старых работ. Три вывода
проверены расчётом, каждый помечен ярусом.

★ ЗАКОН ДЫХАНИЯ НЕ ВЫПОЛНЯЕТСЯ СВОИМИ ЧИСЛАМИ:
    ℐ = Ω·δλ_min/γ.  В статье Ω=1.52·10¹⁴ и γ=1.523·10¹⁴ — ОБА равны ΔE₆₇/ℏ,
    значит Ω/γ≈1 и ℐ ≈ δλ_min = 0.5, а НЕ 1. «Закон ℐ≈1» сводится к зазору
    матрицы; до 1 добирают неопределённым «внешним сигналом» (свободный winт).
    ⇒ ℐ≈1 — постулат, не доказано (вопреки метке Q1).

✓ ФАЛЬСИФИЦИРУЕМЫЙ ВЫХОД (главный из всех работ):
    при sustained-накачке n=6 отношение линий I(7→3)/I(7→2) переворачивается
    с ~0.60 (равновесие, NIST) до >5.5. Реальный наблюдаемый + реальный метод
    (pump-probe пучка атомарного водорода). ЭТО делает модель проверяемой.

★ ДВЕ ВЕРСИИ C_eff НЕСОВМЕСТИМЫ:
    канон: C₆=circ(3/2,1/2,0,0,0,1/2), α=9/5, β=12/5 → след 34.2, мода 13.3;
    док-1:  спектр (−3.30, 0.055, 0.96, 5.33, 5.74, 9.75) → след 18.54 ⇒ α+β=1.59.
    Отрицательного −3.30 НЕ получить из circ (min λ=0.5>0) плюс α,β>0. ⇒ база C₆
    у док-1 ДРУГАЯ; «мягкая мода 0.055» и «зазор 0.5» — из разных матриц.

~ МЯГКИЙ КАНАЛ (механизм, база-зависим): «uᵀψ_T=0, vᵀψ_T≠0» — v открывает то,
    что скрыто от u. Но у лапласиана цикла-6 нулевая мода = сам u ⇒ правило
    требует ИМЕННО матрицы док-1, которой у нас нет. Механизм осмыслен, не проверен.

Запуск:  python -m qmt.breathing
"""

from __future__ import annotations

import math

# параметры статьи v13
OMEGA = 1.52e14        # с⁻¹, масштаб перехода S6→S7
GAMMA = 1.523e14       # с⁻¹, 1/τ_bridge = ΔE₆₇/ℏ
DELTA_LAMBDA_MIN = 0.5


# ── ★ Закон Дыхания честно ───────────────────────────────────────────────────
def breathing_invariant(Omega: float = OMEGA, gap: float = DELTA_LAMBDA_MIN,
                        gamma: float = GAMMA) -> float:
    """ℐ = Ω·δλ_min/γ (безразмерный индекс режима)."""
    return Omega * gap / gamma


def invariant_collapses_to_gap() -> bool:
    """★ Ω≈γ (оба ΔE₆₇/ℏ) ⇒ ℐ ≈ δλ_min = 0.5, НЕ 1. «Закон» тривиализуется."""
    I = breathing_invariant()
    return math.isclose(I, DELTA_LAMBDA_MIN, abs_tol=0.02) and abs(I - 1.0) > 0.4


def reaches_one_only_with_external() -> bool:
    """★ До ℐ≈1 нужен внешний сигнал (снижающий γ) — свободный, неквантованный."""
    # чтобы ℐ=1 при δλ=0.5, нужно γ_эфф = Ω·0.5 = половина текущего γ (внешний фактор ×2)
    gamma_needed = OMEGA * DELTA_LAMBDA_MIN / 1.0
    return gamma_needed < GAMMA          # требуется УМЕНЬШИТЬ γ вдвое — извне


# ── ✓ Фальсифицируемый выход ─────────────────────────────────────────────────
LINE_RATIO_EQUILIBRIUM = 0.60      # I(7→3)/I(7→2), NIST-равновесие
LINE_RATIO_PUMPED_MIN = 5.5        # предсказание при накачке n=6


def falsifiable_prediction() -> dict:
    """✓ Проверяемый экзит: I(7→3)/I(7→2) с 0.60 (NIST) → >5.5 при накачке n=6."""
    return {"наблюдаемая": "I(7→3)/I(7→2)",
            "равновесие_NIST": LINE_RATIO_EQUILIBRIUM,
            "предсказание_накачка": f">{LINE_RATIO_PUMPED_MIN}",
            "разворот_×": f">{LINE_RATIO_PUMPED_MIN/LINE_RATIO_EQUILIBRIUM:.1f}",
            "метод": "pump-probe пучка атомарного водорода",
            "статус": "Q1 — фальсифицируемо (>5.5 требует динамики модели)"}


# ── ★ Несовместимость версий C_eff ──────────────────────────────────────────
def spectrum_incompatibility() -> dict:
    """★ Спектр док-1 (след 18.54 ⇒ α+β=1.59) ≠ канон (α+β=4.2, след 34.2)."""
    doc1 = [-3.3035, 0.0548, 0.9639, 5.3332, 5.7407, 9.7488]
    tr = sum(doc1)
    ab_doc1 = (tr - 9) / 6
    return {"след_док1": round(tr, 4), "α+β_док1": round(ab_doc1, 4),
            "α+β_канон": 4.2, "совместимо": math.isclose(ab_doc1, 4.2, abs_tol=0.1),
            "отрицательная_мода_из_circ_возможна": False}


def negative_mode_impossible_from_circ() -> bool:
    """★ circ(3/2,1/2,0,0,0,1/2) имеет min λ=0.5>0; α,β>0 только поднимают ⇒
    отрицательный −3.30 из этой C₆ невозможен. База док-1 — другая матрица."""
    circ_min = min(1.5 + math.cos(2 * math.pi * k / 6) for k in range(6))
    return circ_min > 0     # 0.5>0 ⇒ никакое положительное α,β не даст отрицат.


def print_report() -> None:
    print("═" * 74)
    print("  BREATHING: закон дыхания честно · фальсиф. выход · несовместимости")
    print("═" * 74)
    I = breathing_invariant()
    print(f"\n  ★ ЗАКОН ДЫХАНИЯ ℐ=Ω·δλ/γ:")
    print(f"     Ω/γ = {OMEGA/GAMMA:.4f} (оба=ΔE₆₇/ℏ) ⇒ ℐ = {I:.4f} ≈ δλ_min=0.5, НЕ 1")
    print(f"     сводится к зазору: {invariant_collapses_to_gap()}; до 1 — внешний сигнал")

    print(f"\n  ✓ ФАЛЬСИФИЦИРУЕМЫЙ ВЫХОД (главный):")
    fp = falsifiable_prediction()
    print(f"     {fp['наблюдаемая']}: {fp['равновесие_NIST']} (NIST) → {fp['предсказание_накачка']} "
          f"(накачка n=6), разворот {fp['разворот_×']}")
    print(f"     метод: {fp['метод']}")

    print(f"\n  ★ НЕСОВМЕСТИМОСТЬ ВЕРСИЙ C_eff:")
    si = spectrum_incompatibility()
    print(f"     док-1 след={si['след_док1']} ⇒ α+β={si['α+β_док1']}; канон α+β=4.2 "
          f"(совместимо: {si['совместимо']})")
    print(f"     отрицат. −3.30 из circ невозможен (min λ=0.5>0): {negative_mode_impossible_from_circ()}")

    print(f"\n  ~ МЯГКИЙ КАНАЛ: механизм 'uᵀψ_T=0, vᵀψ_T≠0' база-зависим (не проверен здесь)")
    print("═" * 74)
    print("  Реально: ℐ≈1 не выполнено (=0.5); фальсиф. выход = разворот линий 7→3/7→2.")
    print("  Две версии C_eff несовместимы; мягкий канал — механизм, но без матрицы док-1.")
    print("═" * 74)


if __name__ == "__main__":
    print_report()
