"""
═══════════════════════════════════════════════════════════════════════════
  SQRT_CLOCK — √-часы: час n = √(n²). Радикал n² = вырождение водорода. Честно.
═══════════════════════════════════════════════════════════════════════════

Основная картинка-ключ (√-часы): на каждом часе n написано √(n²), т.е. под
корнем стоит n². 12 часов несут квадраты 1,4,9,…,144. Цифра 10 = число 10
(√100), НЕ буква. Здесь то, что связывает эти квадраты с нашей моделью водорода.

  ◇ доказано точно · ✓ установленная физика · ○ интерпретация

────────────────────────────────────────────────────────────────────────────
◇✓ ЧАС n → n² = ВЫРОЖДЕНИЕ ВОДОРОДА: n² состояний в оболочке n (2n² со спином).
   √-часы буквально показывают ёмкости оболочек: 1,4,9,16,25,36,49,64,81,100,121,144.
   Это самая сильная связь часы↔водород (n² через SO(4), см. hydrogen_relations).

◇ ЦИФРОВОЙ КОРЕНЬ n² = НАША Sum-9 ЗЕРКАЛО:
   dr(n²) = 1,4,9,7,7,9,4,1,9,1,4,9 — множество только {1,4,7,9};
   dr(n²) = dr((9−n)²) ТОЧНО для всех n (пары суммы-9: 1↔8,2↔7,3↔6,4↔5).
   {1,4,7} = φ-семья; +9. n² mod 9 ∈ {0,1,4,7}.

◇ Σ n²(1..12) = 650 = 2·5²·13 (снова 13 — как в замыкании круга 6·13).

○ «10 = число, не буква Ю»: в √-часах позиция 10 = √100 = 10. Ранее мы придавали
   вес букве Ю (деревянные часы); основной ключ — число, буква вторична.

Запуск:  python -m qmt.sqrt_clock
"""

from __future__ import annotations


def digit_root(x: int) -> int:
    """◇ цифровой корень (повторная сумма цифр)."""
    while x > 9:
        x = sum(int(d) for d in str(x))
    return x


def hour_radicand(n: int) -> int:
    """◇ на часе n написано √(n²); радикал = n²."""
    return n * n


def hydrogen_degeneracy(n: int) -> dict:
    """◇✓ n² = число состояний в оболочке n водорода; 2n² со спином."""
    return {"n": n, "n²": n * n, "2n² (со спином)": 2 * n * n}


def dr_sequence() -> list:
    """◇ цифровые корни n² для n=1..12."""
    return [digit_root(n * n) for n in range(1, 13)]


def dr_set() -> list:
    """◇ множество цифровых корней n² = {1,4,7,9}."""
    return sorted(set(dr_sequence()))


def sum9_digitroot_mirror() -> bool:
    """◇ dr(n²) = dr((9−n)²) для всех n (Sum-9 зеркало)."""
    return all(digit_root(n * n) == digit_root((9 - n) ** 2) for n in range(1, 9))


def n2_mod9() -> list:
    """◇ n² mod 9 ∈ {0,1,4,7}."""
    return [(n * n) % 9 for n in range(1, 13)]


def sum_squares() -> dict:
    """◇ Σ n²(1..12) = 650 = 2·5²·13."""
    s = sum(n * n for n in range(1, 13))
    return {"Σ": s, "=650": s == 650, "= 2·5²·13": s == 2 * 25 * 13}


def print_report() -> None:
    print("═" * 78)
    print("  √-ЧАСЫ: час n = √(n²) · радикал n² = вырождение водорода")
    print("═" * 78)
    print(f"\n  ◇✓ радикалы (n²): {[hour_radicand(n) for n in range(1, 13)]}")
    print(f"     = ёмкости оболочек водорода n² (2n² со спином)")
    print(f"\n  ◇ dr(n²): {dr_sequence()}   множество: {dr_set()} = {{1,4,7}}φ + 9")
    print(f"  ◇ Sum-9 зеркало dr(n²)=dr((9−n)²): {sum9_digitroot_mirror()}")
    print(f"  ◇ n² mod 9: {n2_mod9()}  ∈ {{0,1,4,7}}")
    print(f"\n  ◇ Σn²(1..12): {sum_squares()}")
    print("═" * 78)
    print("  √-часы = часы вырождения водорода. Цифровой корень квадратов = наша Sum-9.")
    print("  10 = число (√100), буква вторична. Самый честный мост часы↔водород. ◇✓")
    print("═" * 78)


if __name__ == "__main__":
    print_report()
