"""
═══════════════════════════════════════════════════════════════════════════
  THINNING — «утоньшение»: меньше эфф. масса → барьеры прозрачны. Честно.
═══════════════════════════════════════════════════════════════════════════

Анализ контакта 1997.03.18 («иная таблица», «утоньшиться», «диэлектрик станет
проводником»). Разделяю три слоя.

✓ НАСТОЯЩАЯ ФИЗИКА (проверяемо, и есть реальный эксперимент):
  1. Туннель ВКБ: T = exp(−2d·κ), κ = √(2·m·(V−E))/ℏ ∝ √m.
     Меньше эфф. масса → κ↓ → T↑ → барьер прозрачен. При m→0: T→1.
     Это и есть «утоньшение = снижение эфф. массы». ← falsifiable (оптич. решётки).
  2. Выше плазменной частоты ω_p=√(n e²/ε₀m): среда прозрачна (диэлектрик→проводник).
     «выше частота — нет диэлектрика» = буквально ω>ω_p. Реально.
  3. Шеннон C=B·log₂(1+SNR): выше несущая → шире полоса → больше информации
     (лазер ≫ радио). Реально.

○ МОДЕЛЬ / ИНТЕРПРЕТАЦИЯ (Q3, не выдаём за факт):
  • E=ε·c² с ε как «накопленная история/память» — переобозначение массы;
  • «7 ступеней эволюции = 7 операторов», «солнечное человечество ε→0» — аналогия;
  • π−3=0.14159 как структурная «трещина» — И это ДРУГАЯ трещина, чем Δ₇=√5−2:
    модель множит константы (две разные «трещины»), а не выводит одну.

Запуск:  python -m qmt.thinning
"""

from __future__ import annotations

import math

HBAR = 1.054571817e-34
M_E = 9.1093837015e-31
EV = 1.602176634e-19
E_CH = 1.602176634e-19
EPS0 = 8.8541878128e-12


def tunnel_transparency(m_over_me: float, d_nm: float = 1.0, VmE_eV: float = 1.0) -> float:
    """T=exp(−2d·κ), κ=√(2m(V−E))/ℏ. Меньше масса → больше прозрачность."""
    m = m_over_me * M_E
    kappa = math.sqrt(2 * m * VmE_eV * EV) / HBAR
    return math.exp(-2 * d_nm * 1e-9 * kappa)


def thinner_is_more_transparent() -> bool:
    """Ключ «утоньшения»: меньше эфф. масса → выше T (монотонно)."""
    return (tunnel_transparency(0.01) > tunnel_transparency(0.1)
            > tunnel_transparency(0.5) > tunnel_transparency(1.0))


def plasma_frequency(n: float = 1e29) -> float:
    """ω_p=√(n e²/ε₀ m). Выше ω_p среда прозрачна (диэлектрик→проводник)."""
    return math.sqrt(n * E_CH**2 / (EPS0 * M_E))


def shannon_capacity(bandwidth: float, snr: float) -> float:
    """C=B·log₂(1+SNR): выше частота → шире полоса → больше информации."""
    return bandwidth * math.log2(1 + snr)


def two_cracks_problem() -> dict:
    """Честно: π−3 и √5−2 — ДВЕ разные «трещины». Модель множит, не выводит."""
    return {"π−3": math.pi - 3, "√5−2 (Δ₇)": math.sqrt(5) - 2,
            "одна_трещина": abs((math.pi - 3) - (math.sqrt(5) - 2)) < 1e-3}


def print_report() -> None:
    print("═" * 74)
    print("  УТОНЬШЕНИЕ: меньше эфф. масса → барьеры прозрачны (честно)")
    print("═" * 74)
    print("\n  ✓ ФИЗИКА (проверяемо):")
    print("   1. туннель T(m_eff), барьер 1нм, V−E=1эВ:")
    for f in (1.0, 0.5, 0.1, 0.01):
        print(f"        m_eff={f:5}·m_e → T={tunnel_transparency(f):.3e}")
    print(f"      меньше масса — прозрачнее: {thinner_is_more_transparent()} (при m→0: T→1)")
    print(f"   2. плазменная частота ω_p={plasma_frequency():.3e} рад/с; выше ω_p — прозрачно")
    print(f"   3. Шеннон: полоса ×10 → ёмкость C×10 (лазер≫радио): "
          f"{shannon_capacity(1e9,1e3):.2e} vs {shannon_capacity(1e14,1e3):.2e} бит/с")

    print("\n  ○ МОДЕЛЬ / ИНТЕРПРЕТАЦИЯ (Q3):")
    tc = two_cracks_problem()
    print(f"      E=εc² (ε=память), 7 ступеней, «солнечное человечество ε→0» — аналогия")
    print(f"      π−3={tc['π−3']:.5f} vs Δ₇=√5−2={tc['√5−2 (Δ₇)']:.5f} — ДВЕ разные трещины "
          f"(одна? {tc['одна_трещина']}) → модель множит константы")

    print("\n  ★ РЕАЛЬНЫЙ ЭКСПЕРИМЕНТ (falsifiable):")
    print("      T(m_eff)=exp(−2d√(2m_eff(V−E))/ℏ) — управляемая эфф. масса в оптической")
    print("      решётке; проверить зависимость T от m_eff. Это стандартная, доступная физика.")
    print("═" * 74)
    print("  Реально: утоньшение = снижение эфф. массы → туннель (ВКБ). Прозрачность")
    print("  выше ω_p, ёмкость по Шеннону — тоже реальны. π−3/ε-память — интерпретация.")
    print("═" * 74)


if __name__ == "__main__":
    print_report()
