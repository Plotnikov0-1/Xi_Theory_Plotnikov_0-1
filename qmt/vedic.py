"""
═══════════════════════════════════════════════════════════════════════════
  VEDIC — индийская (ведическая) структура: ближе всего к модели, но не идеал.
═══════════════════════════════════════════════════════════════════════════

Подсказка (транскрипт «Иные», стр. 68): «Более близкое истолкование Великих
циклов — в ведической литературе… тройственность Миров: Брахма, Вишну, Шива».
И пользователь: индийская мифология подходит ближе всего, хоть и не идеально.

Что ложится ТОЧНО (реальные ведические числа ↔ структура проекта):

  ЮГИ (отношение 4:3:2:1):
    Сатья  1 728 000 лет = 12³·1000   ← наше 1728 = 12³ (three_quark, «12→1»)
    Трета  1 296 000 лет = 6⁴·1000
    Двапара  864 000 лет
    Кали     432 000 лет
    Маха-юга = сумма = 4 320 000 (10 частей); Калпа = 1000·Маха = 4.32 млрд лет.

  ТРИМУРТИ = триада с обязательным Третьим:
    Брахма (Создатель) = + полюс;  Шива (Разрушитель) = − полюс (зеркало);
    Вишну (Хранитель)  = Третий, «соединяющий противоположное И разделяющий»
                       = ось −I (узел 5, центр) / память-инвариант.
    «Необходимость Третьего» ↔ CP требует ровно 3 поколений (Кобаяши-Маскава):
    N=2 → 0 CP-фаз (нет Третьего), N=3 → 1 (есть).

Что НЕ ложится (честно, «не идеально»):
  • возраст 13.821 млрд НЕ кратен Маха-юге (3199.41, дробь 0.41);
  • это структура мифа (Q3), а не доказанная физика — переносим только форму.

Запуск:  python -m qmt.vedic
"""

from __future__ import annotations

# Реальные ведические числа (лет).
YUGAS = {"Сатья": 1_728_000, "Трета": 1_296_000,
         "Двапара": 864_000, "Кали": 432_000}
MAHA_YUGA = sum(YUGAS.values())            # 4 320 000
KALPA = 1000 * MAHA_YUGA                    # 4.32 млрд (День Брахмы)


def yuga_ratio() -> list:
    """Отношение длительностей юг = 4:3:2:1 (нисходящая лестница веков)."""
    base = YUGAS["Кали"]
    return [v // base for v in YUGAS.values()]


def satya_is_12_cubed() -> bool:
    """Сатья-юга / 1000 = 1728 = 12³ — то же, что у проекта (12 миров → 1)."""
    return YUGAS["Сатья"] // 1000 == 12**3


def trimurti() -> dict:
    """Брахма/Вишну/Шива = +/центр/− ; Вишну = Третий (связь и разделение)."""
    return {
        "Брахма (Создатель)": "+ полюс (рождение)",
        "Шива (Разрушитель)": "− полюс (зеркальный партнёр)",
        "Вишну (Хранитель)": "Третий = ось −I (центр 5) — соединяет И разделяет",
    }


def necessity_of_third() -> dict:
    """«Для равновесия нужен Третий» ↔ CP требует ровно 3 поколений."""
    return {N: (N - 1) * (N - 2) // 2 for N in (2, 3, 4)}   # CP-фазы


def fits_age(age_years: float = 13_821_456_527) -> dict:
    """Честная проверка: возраст НЕ кратен Маха-юге (фит не идеален)."""
    q = age_years / MAHA_YUGA
    return {"возраст/Маха-юга": q, "дробная_часть": abs(q - round(q)),
            "кратно": abs(q - round(q)) < 0.02}


def print_report() -> None:
    print("═" * 72)
    print("  ВЕДИЧЕСКАЯ СТРУКТУРА — ближе всего к модели (но не идеал)")
    print("═" * 72)
    print("\n  ЮГИ (отношение 4:3:2:1):")
    for n, v in YUGAS.items():
        print(f"     {n:8}: {v:>9,} лет = {v//1000}×1000")
    print(f"     Маха-юга = {MAHA_YUGA:,} (части {'+'.join(map(str, yuga_ratio()))}=10); "
          f"Калпа = {KALPA:,} (4.32 млрд)")
    print(f"     ★ Сатья/1000 = {YUGAS['Сатья']//1000} = 12³ = {12**3}  "
          f"(наше 1728): {satya_is_12_cubed()}")

    print("\n  ТРИМУРТИ = триада с обязательным Третьим:")
    for k, v in trimurti().items():
        print(f"     {k}: {v}")
    nt = necessity_of_third()
    print(f"     «нужен Третий» ↔ CP-фазы по поколениям: N=2→{nt[2]}, N=3→{nt[3]} "
          f"(тройка обязательна)")

    f = fits_age()
    print(f"\n  ЧЕСТНО (не идеально): возраст/Маха-юга = {f['возраст/Маха-юга']:.4f}, "
          f"дробь {f['дробная_часть']:.2f} → кратно: {f['кратно']}")
    print("═" * 72)
    print("  Точно: 12³=1728, отношение 4:3:2:1, троица=триада с Третьим (CP=3).")
    print("  Не идеал: возраст не на цикле; миф-структура (Q3), берём форму, не догму.")
    print("═" * 72)


if __name__ == "__main__":
    print_report()
