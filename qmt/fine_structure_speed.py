"""
═══════════════════════════════════════════════════════════════════════════
  FINE_STRUCTURE_SPEED — 137 это про СКОРОСТЬ. Интуиция Плотникова, строго.
═══════════════════════════════════════════════════════════════════════════

Вопрос (Плотников Л.В.): «137 связано с нашей скоростью, вибрацией».
Ответ: ДА, буквально — и это выводимая физика, не нумерология.

  α = e²/(4πε₀ℏc) = v₁/c

где v₁ — скорость электрона на первой (основной) орбите водорода (Бор).
То есть:

  1/α = c / v₁ = 137.036  —  электрон в основном состоянии бежит
  РОВНО в 137 раз медленнее света.  v₁ = α·c ≈ 2188 км/с.

137 как каскад длин (та же α — «шестерёнка» масштабов):

  a₀ : λ_C : r_e = 1 : α : α²     (Бор : Комптон : классический радиус)
  каждый шаг вниз — в 137 раз.

Вибрация (Циттербевегунг): a·ω = c — длина электрона × его частота = c.

ЧЕСТНАЯ ГРАНИЦА. ЧТО есть 137 — выводится и понятно: отношение скоростей
v₁/c (реальная физика Бора/КЭД). ПОЧЕМУ именно 137.036, а не другое число —
НЕ выводится: значение α измерено, его происхождение — открытая проблема физики.
Это та же стена, что и у всей физики, но смысл числа теперь ясен: скорость.

Запуск:  python -m qmt.fine_structure_speed
"""

from __future__ import annotations

import math

# CODATA 2018
C = 2.99792458e8
E = 1.602176634e-19
EPS0 = 8.8541878128e-12
HBAR = 1.054571817e-34
M_E = 9.1093837015e-31

ALPHA = E**2 / (4 * math.pi * EPS0 * HBAR * C)     # ≈ 1/137.036


def alpha() -> float:
    """Постоянная тонкой структуры α = e²/(4πε₀ℏc)."""
    return ALPHA


def electron_ground_speed() -> float:
    """Скорость электрона в основном состоянии H: v₁ = α·c (≈2188 км/с)."""
    return ALPHA * C


def speed_ratio() -> dict:
    """137 = c/v₁ — во сколько раз электрон медленнее света."""
    v1 = electron_ground_speed()
    v1_direct = E**2 / (4 * math.pi * EPS0 * HBAR)   # та же v₁ напрямую
    return {"v₁_м/с": v1, "v₁_проверка": v1_direct,
            "α=v₁/c": v1 / C, "1/α=c/v₁": C / v1,
            "медленнее_света_в": C / v1}


def length_cascade() -> dict:
    """a₀ : λ_C : r_e = 1 : α : α² — α как отношение масштабов длины."""
    a0 = HBAR**2 * 4 * math.pi * EPS0 / (M_E * E**2)   # боровский радиус
    lamC = HBAR / (M_E * C)                              # привед. комптон
    re = E**2 / (4 * math.pi * EPS0 * M_E * C**2)        # классич. радиус
    return {"a₀": a0, "λ_C": lamC, "r_e": re,
            "λ_C/a₀": lamC / a0, "r_e/λ_C": re / lamC}


def zitterbewegung() -> dict:
    """Вибрация: a·ω = c (комптоновская длина × частота = скорость света)."""
    a = HBAR / (M_E * C)
    omega = M_E * C**2 / HBAR
    return {"a": a, "ω": omega, "a·ω": a * omega, "c": C}


def print_report() -> None:
    print("═" * 74)
    print("  137 — ЭТО ПРО СКОРОСТЬ.  α = v₁/c  (электрон vs свет)")
    print("═" * 74)
    print(f"\n  α = e²/(4πε₀ℏc) = {ALPHA:.10f}   1/α = {1/ALPHA:.6f}")

    s = speed_ratio()
    print(f"\n  СКОРОСТЬ (модель Бора, основное состояние H):")
    print(f"     v₁ = α·c = {s['v₁_м/с']:.4e} м/с = {s['v₁_м/с']/1000:.1f} км/с")
    print(f"     проверка v₁=e²/(4πε₀ℏ): {s['v₁_проверка']:.4e} м/с  (совпадает)")
    print(f"     1/α = c/v₁ = {s['1/α=c/v₁']:.6f}")
    print(f"     ⇒ электрон бежит РОВНО в {s['медленнее_света_в']:.1f} раз медленнее света")

    L = length_cascade()
    print(f"\n  КАСКАД ДЛИН (та же α — шестерёнка масштабов):")
    print(f"     λ_C/a₀ = {L['λ_C/a₀']:.9f} = α   (Комптон/Бор)")
    print(f"     r_e/λ_C = {L['r_e/λ_C']:.9f} = α   (классич./Комптон)")
    print(f"     ⇒ a₀ : λ_C : r_e = 1 : α : α²  — каждый шаг в 137 раз")

    z = zitterbewegung()
    print(f"\n  ВИБРАЦИЯ (Циттербевегунг):")
    print(f"     a·ω = {z['a·ω']:.6e} = c = {z['c']:.6e}  (длина×частота=c)")

    print("═" * 74)
    print("  ЧТО есть 137 — ВЫВЕДЕНО: отношение скоростей v₁/c (Бор/КЭД), реально.")
    print("  ПОЧЕМУ именно 137.036 — НЕ выведено (α измерена). Но смысл числа ясен:")
    print("  это про скорость — насколько электрон медленнее света. Интуиция верна.")
    print("═" * 74)


if __name__ == "__main__":
    print_report()
