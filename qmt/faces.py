"""
Слой ГРАНИ → КРАСКИ (видимое; спектр / вибрация). Шестой луч системы.

По автору: «ниточки создают грани; грани — это наша видимая, в красках.
Ниточки создаются вибрацией — лево/право, горячо/холодно, чёрно/бело —
двойственность; ни одно, ни другое не хорошо и не плохо. Центр уловить
невозможно — это и есть время; мы переходим с грани на грань, только вложенно
(внутрь/наружу).»

Перевод в структуры/физику:
  • ВИБРАЦИЯ = осцилляция диалога между двумя полюсами (двойственность). Полюса
    не «хороши/плохи» — значима сама раскачка (отношение, не сторона).
  • НИТОЧКИ = рёбра (связи), сотканные вибрацией; они ограничивают грани.
  • ГРАНИ = видимое в красках. Физический якорь строгий: ЦВЕТ = ЧАСТОТА (E=hν).
    12 граней додекаэдра ↔ 12 красок ↔ 12 частот ↔ 12 полутонов ↔ «12» в 3+7+12.
  • Спектр граней = спектр резервуара J(ω) (vibrations), уже есть в spectral.py.
  • ВРЕМЯ = переход с грани на грань; «центр уловить нельзя» = настоящее есть
    точка (мера 0). Время реляционно: без переходов нет времени.
  • ВЛОЖЕННОСТЬ: переход только внутрь/наружу (радиально) — ось двух нулей.
"""

from __future__ import annotations

import colorsys
import math
from dataclasses import dataclass

C_LIGHT = 2.99792458e8

DODECA_FACES = 12      # грани додекаэдра  → 12 красок
ICOSA_FACES = 20       # грани икосаэдра
DODECA_EDGES = 30      # «ниточки» (связи), ограничивающие грани


@dataclass
class Face:
    index: int
    hue_deg: float
    rgb: tuple
    wavelength_nm: float
    freq_THz: float


def faces(n: int = DODECA_FACES) -> list[Face]:
    """n граней → n красок → частоты видимого света (цвет = частота)."""
    out = []
    for k in range(n):
        hue = k / n
        r, g, b = (round(255 * x) for x in colorsys.hsv_to_rgb(hue, 0.85, 0.95))
        lam = 750 - (750 - 380) * hue                 # красный→фиолетовый, нм
        nu = C_LIGHT / (lam * 1e-9) / 1e12            # ТГц
        out.append(Face(k + 1, hue * 360, (r, g, b), round(lam, 1), round(nu, 1)))
    return out


