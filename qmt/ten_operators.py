"""
═══════════════════════════════════════════════════════════════════════════
  TEN_OPERATORS — операторы десятки = ПЕРЕХОДЫ (не узлы). Константа на ребре.
═══════════════════════════════════════════════════════════════════════════

Просьба автора: «каждый оператор десятки должен показать своё СООТНОШЕНИЕ —
константу; не как узла, а как самого перехода от узла до узла».

Главный принцип: соотношение первично, число вторично. Константа живёт на
ПЕРЕХОДЕ (ребро узел→узел), а не на узле.

Десятка = 10 узлов на окружности (декагон). Оператор = прыжок на k узлов.
Константа перехода = длина хорды  c_k = 2·sin(k·18°).

  ◇ доказано точно (тригонометрия) · ○ привязка к «оператору сборки» (наша)

────────────────────────────────────────────────────────────────────────────
◇ КОНСТАНТЫ ПЕРЕХОДОВ:
    k=1: c₁ = 2·sin18° = φ−1 = 1/φ = 0.61803  ← аттрактор оператора T(x)=1/(1+x)
    k=2: c₂ = 2·sin36° = 1.17557
    k=3: c₃ = 2·sin54° = φ = 1.61803          ← само золотое сечение как переход
    k=4: c₄ = 2·sin72° = 1.90211
    k=5: c₅ = 2·sin90° = 2                     ← диаметр = зеркало −I (узел↔антипод)

◇ φ — ЭТО СООТНОШЕНИЕ ПЕРЕХОДОВ (не узел):
    c₄/c₂ = sin72°/sin36° = φ    (золотой экватор, H4)
    c₃/c₁ = φ/(φ−1) = φ²         (φ²=φ+1)
    R/c₁  = радиус/сторона = φ

Запуск:  python -m qmt.ten_operators
"""

from __future__ import annotations

import math

PHI = (1 + 5 ** 0.5) / 2


def transition_constant(k: int) -> float:
    """◇ константа оператора-перехода на k узлов: c_k = 2·sin(k·18°)."""
    return 2 * math.sin(math.radians(k * 18))


def operators() -> dict:
    """◇ пять операторов десятки (переходы k=1..5) и их константы."""
    ident = {1: "φ−1 = 1/φ (аттрактор T)", 3: "φ (золото)", 5: "2 (зеркало −I)"}
    return {k: {"c": transition_constant(k), "identity": ident.get(k, f"2·sin{k*18}°")}
            for k in range(1, 6)}


def golden_relations() -> dict:
    """◇ φ рождается в СООТНОШЕНИИ переходов, а не в узле."""
    c = {k: transition_constant(k) for k in range(1, 6)}
    return {
        "c4/c2 = sin72/sin36 = φ": abs(c[4] / c[2] - PHI) < 1e-12,
        "c3/c1 = φ² ": abs(c[3] / c[1] - PHI ** 2) < 1e-12,
        "R/c1 = φ (радиус/сторона)": abs(1 / c[1] - PHI) < 1e-12,
        "c1 = φ−1": abs(c[1] - (PHI - 1)) < 1e-12,
        "c3 = φ": abs(c[3] - PHI) < 1e-12,
        "c5 = 2 (диаметр)": abs(c[5] - 2) < 1e-12,
    }


def print_report() -> None:
    print("═" * 78)
    print("  ДЕСЯТКА — операторы = ПЕРЕХОДЫ; константа на ребре, не на узле")
    print("═" * 78)
    print("\n  ◇ операторы (прыжок k → константа перехода c_k = 2·sin(k·18°)):")
    for k, v in operators().items():
        print(f"     k={k}:  c_{k} = {v['c']:.5f}   = {v['identity']}")
    print("\n  ◇ φ = СООТНОШЕНИЕ переходов (не узел):")
    for name, ok in golden_relations().items():
        print(f"     {name:32}  {ok}")
    print("═" * 78)
    print("  Соотношение первично, число вторично. Оператор = переход узел→узел.")
    print("  k=1→φ−1 (сборка), k=3→φ (золото), k=5→2 (зеркало). φ = c₄/c₂ = R/сторона.")
    print("═" * 78)


if __name__ == "__main__":
    print_report()
