"""
═══════════════════════════════════════════════════════════════════════════
  CONSTRUCTION — морфология конструкции E=mc² как АЛГОРИТМА устроения.
═══════════════════════════════════════════════════════════════════════════

Идея (соотношение раньше числа): E=mc² — не формула, а КОНСТРУКЦИЯ
        [проявленное] = [носитель] × [связь, замкнутая сама на себя]
Справа стоит величина, действующая сама на себя (квадрат / произведение на
сопряжённую). Это реальный, известный математический паттерн — НЕ новое
открытие, а узнавание семейства:

  • правило Борна: наблюдаемое P = ψ·ψ* = |ψ|² (амплитуда × сопряжённая себе);
  • квадратичные формы: A=πr², E=½mv², U=½kx², E=mc², ds²=c²dt²−dx², Пифагор;
  • инварианты симметрий: ⟨χ,χ*⟩, |F|² (Фурье) — операция величины над собой.

Почему квадрат: наблюдаемое должно быть положительным и инвариантным →
самопроизведение амплитуды. Это содержание правила Борна и положительных форм.

ГРАНИЦЫ (где алгоритм «рождения» уступает место другому):
  • степень 1 (Ом, F=ma): ПЕРЕДАЧА, не рождение;
  • e^x: равно своей производной — «бесконечное самозамыкание» (все степени);
  • log (Шеннон H=−Σp·log p): информация, не квадрат;
  • [x,p]≠0: порядок самозамыкания важен (некоммутативность).

Запуск:  python -m qmt.construction
"""

from __future__ import annotations

import cmath
import math
from dataclasses import dataclass


@dataclass
class Form:
    name: str
    expr: str
    degree: object        # степень по «связи»: 2, −2, 1, "exp", "log"
    kind: str             # класс алгоритма
    real_math: str        # чем это является строго


# ── Семейство [носитель × связь²]: реальные, известные конструкции ───────────
FAMILY = [
    Form("Площадь круга", "A = π·r²", 2, "проявление", "квадратичная форма"),
    Form("Кинетическая энергия", "E = ½m·v²", 2, "проявление", "квадратичная форма"),
    Form("Энергия пружины", "U = ½k·x²", 2, "проявление", "квадратичная форма"),
    Form("Эйнштейн покоя", "E = m·c²", 2, "проявление", "квадрат по c (носитель m)"),
    Form("Правило Борна", "P = ψ·ψ* = |ψ|²", 2, "проявление", "самосопряжённое произведение"),
    Form("Спектр Фурье", "I = F·F* = |F|²", 2, "проявление", "самосопряжённое произведение"),
    Form("Интервал ОТО/СТО", "ds² = c²dt²−dx²", 2, "инвариант", "квадратичная форма (метрика)"),
    Form("Пифагор", "a²+b² = c²", 2, "равновесие", "квадратичная форма"),
    Form("Ньютон гравитация", "F = G·m₁m₂/r²", -2, "обратное проявление", "обратный квадрат"),
    Form("Кулон", "F = k·q₁q₂/r²", -2, "обратное проявление", "обратный квадрат"),
]

# ── Границы: где «рождение через квадрат» уступает другому алгоритму ──────────
BOUNDARY = [
    Form("Ом / F=ma", "V=I·R ; F=m·a", 1, "передача", "линейно — не рождение"),
    Form("Экспонента", "e^x = Σ xⁿ/n!", "exp", "бесконечное самозамыкание", "равна своей производной"),
    Form("Энтропия Шеннона", "H = −Σ p·log p", "log", "информация", "логарифм, не квадрат"),
    Form("Некоммутативность", "[x,p] = iℏ ≠ 0", "order", "порядок важен", "операторы не коммутируют"),
]


def born_observable(psi) -> list:
    """Правило Борна строго: наблюдаемое P = ψ·ψ* (= |ψ|²), вещественно и ≥0."""
    return [(c * c.conjugate()).real for c in psi]


def is_self_product_real(psi) -> bool:
    """Проверка: ψ·ψ* совпадает с |ψ|² и даёт вещественные неотрицательные числа."""
    p1 = born_observable(psi)
    p2 = [abs(c) ** 2 for c in psi]
    return all(abs(a - b) < 1e-12 and a >= -1e-12 for a, b in zip(p1, p2))


def mass_energy_dimensionless(E: float, m: float, c: float = 2.99792458e8) -> float:
    """E=mc² в безразмерной форме: E/(mc²) = 1 — тождество, одно названо дважды."""
    return E / (m * c * c)


def classify(degree) -> str:
    """Класс алгоритма по «степени самозамыкания» связи."""
    return {2: "проявление (квадрат / Борн)",
            -2: "обратное проявление (1/r²)",
            1: "передача (линейное)",
            "exp": "бесконечное самозамыкание (e^x)",
            "log": "информация (Шеннон)",
            "order": "порядок важен (некоммутативность)"}.get(degree, "?")


def print_report() -> None:
    print("═" * 76)
    print("  МОРФОЛОГИЯ КОНСТРУКЦИИ  [проявленное] = [носитель] × [связь²]")
    print("  (E=mc² как один представитель реального семейства квадратичных форм)")
    print("═" * 76)

    print("\n  СЕМЬЯ (где конструкция работает — известная математика):")
    for f in FAMILY:
        print(f"     {f.name:<22} {f.expr:<20} · {f.real_math}")

    print("\n  ЯДРО — правило Борна (наблюдаемое рождается из амплитуды):")
    psi = [1 / math.sqrt(2) + 0j, 0 + 1j / math.sqrt(2)]
    P = born_observable(psi)
    print(f"     ψ = {[f'{c:.3f}' for c in psi]}   (комплекс, ненаблюдаем)")
    print(f"     ψ·ψ* = {[round(p,3) for p in P]}  Σ={sum(P):.3f}  (вещественно, ≥0 — реально)")
    print(f"     строгая проверка ψ·ψ*≡|ψ|²: {is_self_product_real(psi)}")
    print(f"     E/(mc²) = {mass_energy_dimensionless(1.0, 1.0/2.99792458e8**2):.6f}  (тождество)")

    print("\n  ГРАНИЦЫ (где «рождение» уступает другому алгоритму):")
    for f in BOUNDARY:
        print(f"     {f.name:<20} {f.expr:<20} → {classify(f.degree)}")

    print("═" * 76)
    print("  ЧЕСТНО: это РЕАЛЬНЫЙ паттерн (квадратичные формы + правило Борна),")
    print("  а не новое открытие. Конструкция узнаётся в ~10 местах физики. Язык")
    print("  «связь, замкнутая на себя» — интерпретация этого паттерна, не вывод.")
    print("═" * 76)


if __name__ == "__main__":
    print_report()
