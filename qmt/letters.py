"""
Аллегория букв (семантический / психологический слой) — 27 букв А…Щ.

ВНИМАНИЕ — статус слоя. Это НЕ геометрия и НЕ физика. Это аллегорическое
описание букв как стадий развития («динамика в символах»). Слой искажаемый
(как и каббала), поэтому держится отдельно и помечается как интерпретационный
(Q3). Сюда нельзя переносить строгость доказанных слоёв.

Что говорит источник (docx «Структурированный … объяснения букв, А–Щ»):
буква = стадия становления, разворачивается путём от рождения. Мотивы текста
буквально совпадают с примитивами модели:
    круг / замкнут   → шар / сфера
    нить / связь     → канал (пуповина = «серебряная нить»)
    ноль             → точка-ноль S0
    зеркало          → инверсия −I
Текст сам привязывает буквы к ЦИФРАМ («аналог в цифрах»; О = «0»).

Разрыв 27 ↔ 20. Вершин додекаэдра 20, а букв описано 27. Самая резонансная
читка: 27 = 20 + 7 (20 букв-состояний на вершинах + 7 букв-переходов как
связи/рёбра). НО однозначного правила «какие именно 7» из одного текста не
выводится — поэтому split помечен как ГИПОТЕЗА, а не факт.
"""

from __future__ import annotations

from dataclasses import dataclass

# Порядок ровно как в источнике (А…Щ), 27 букв.
LETTERS = list("АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩ")

assert len(LETTERS) == 27

# Краткая суть из текста (первая содержательная мысль блока).
ESSENCE = {
    "А": "крыша/защита; «ноль — мать, несущая ребёнка» (нерождённый в оболочке)",
    "Б": "содержит слово «Бог»; круг + «серебряная нить» = связь с матерью",
    "В": "сравнение с материнской грудью (питание)",
    "Г": "часть слова «бог»; угол/опора",
    "Д": "Дом",
    "Е": "«Есть» (бытие, наличие)",
    "Ё": "ещё не исключена, но на пути к исключению (производная от Е)",
    "Ж": "две буквы «С» (зеркальная пара, удвоение)",
    "З": "похожа на «В» (отражение/повтор)",
    "И": "ищется аналог в цифрах (связь буква↔число)",
    "Й": "снова точка (И с добавленной точкой/связью)",
    "К": "сравнение с «Ж» (половина симметрии)",
    "Л": "разрыв пуповины — отделение/переход (рождение себя)",
    "М": "объединение (двойная опора)",
    "Н": "«эн» — перекладина-связь между двумя опорами",
    "О": "аналог цифры «0» — замкнутый круг (полнота/шар)",
    "П": "нет аналога в цифрах — ворота/проём",
    "Р": "вопрос об аналоге — голова на опоре (личность)",
    "С": "разница прописной/строчной — открытый полукруг (чаша/приём)",
    "Т": "Время; перекладина-крыша на опоре",
    "У": "слова о человеке на «У» — корень/спуск вниз",
    "Ф": "«мужичок, руки в бочок» — фигура с двумя кругами на оси",
    "Х": "перекрестие — пересечение/выбор",
    "Ц": "чаша грубой угловатой формы (с отростком/хвостом)",
    "Ч": "не «чаша» — опора с приёмником наверху",
    "Ш": "«Е» наоборот — три зубца (тройная опора)",
    "Щ": "«Ш» с хвостом — завершение ряда",
}

# =========================================================================
# ТРИАДА А · Д · Л — три порождающие буквы («три матери» этого слоя).
# Источник СТРОИТ их друг из друга явно (это внутренняя конструкция текста,
# а не наша подгонка):
#   А = «крыша» + перекладина-ПУПОВИНА → нерождённый, в утробе, ЗАМКНУТ (ноль);
#   Л = А с РАЗОРВАННОЙ пуповиной       → рождён, отделён, стоит на основании;
#   Д = Л + ФУНДАМЕНТ (основание)       → ДОМ, осевшая форма.
# Цитаты: «Разорвав эту пуповину… это будет буква Л»; «дом состоит из буквы А,
# только вместо перекладины нет пуповины… буква Л… имеет основание, фундамент».
#
# Это ровно генезис модели: точка/ноль → разрыв/переход → форма.
#   А ↔ S0  (точка-ноль, шар-оболочка, «крыша»)
#   Л ↔ переход/разрыв (канал, движение — «ноги»)
#   Д ↔ форма/структура (дом = ячейка, куб/жилище)
# И связь с геометрией: «крыша» А — это та самая КРЫША, что надстраивается над
# гранью куба (золотые вершины торчат на φ−1), превращая куб в додекаэдр
# (см. nested_spheres). Дом Д = куб + крыша = жилая ячейка.
TRINITY = {
    "А": "исток/ноль: крыша + пуповина, нерождённый в оболочке (S0, шар)",
    "Л": "разрыв/переход: А без пуповины, отделение, движение («ноги»)",
    "Д": "форма/дом: Л + фундамент, осевшая структура (куб+крыша=ячейка)",
}
TRINITY_GENESIS = "А --(разрыв пуповины)--> Л --(+фундамент)--> Д"


# Гипотеза 27 = 20 + 7: кандидаты в «связующие» (переходные) буквы — те, чья
# суть в тексте про связь/разрыв/переход, а не про состояние. ПОМЕЧЕНО как
# интерпретация: список можно менять, он не выводится строго.
TRANSITION_HYPOTHESIS = ["Б", "Н", "Л", "Х", "И", "Й", "У"]   # 7 «связей»


@dataclass
class LetterMap:
    states: list       # 20 букв-состояний (кандидаты на вершины)
    links: list        # 7 букв-переходов (кандидаты на рёбра/связи)
    status: str = "Q3 — интерпретация, искажаемый семантический слой"


def split_20_7(transition=None) -> LetterMap:
    """Разбиение 27 = 20 + 7 по заданному списку «связующих» букв (гипотеза)."""
    links = transition or TRANSITION_HYPOTHESIS
    states = [L for L in LETTERS if L not in links]
    return LetterMap(states=states, links=list(links))


def print_report() -> None:
    print("АЛЛЕГОРИЯ БУКВ — семантический слой (Q3, искажаем)")
    print("=" * 66)
    print(f"Всего описано букв: {len(LETTERS)}  (А…Щ)")
    print("\nТРИАДА А·Д·Л — три порождающие буквы (генезис из самого текста):")
    print(f"  {TRINITY_GENESIS}")
    for L in ("А", "Л", "Д"):
        print(f"  {L}: {TRINITY[L]}")
    print("  ↔ модель: А=точка/ноль (S0) · Л=переход/движение · Д=форма (куб+крыша)")
    m = split_20_7()
    print(f"\nГипотеза 27 = 20 + 7:")
    print(f"  20 состояний (→ вершины): {' '.join(m.states)}")
    print(f"   7 переходов  (→ связи):  {' '.join(m.links)}")
    print(f"  статус: {m.status}")
    print("\nМотивы текста ↔ примитивы модели:")
    print("  круг→шар · нить/связь→канал · ноль→S0 · зеркало→−I · буква↔цифра")
    print("\nСуть нескольких опорных букв:")
    for L in ("А", "О", "Л", "Б"):
        print(f"  {L}: {ESSENCE[L]}")
    print("=" * 66)
    print("Граница: это слой смысла, а не доказательство. Геометрия (20 вершин)")
    print("и физика остаются отдельно и строго; буквы — приглашение, не вывод.")


if __name__ == "__main__":
    print_report()
