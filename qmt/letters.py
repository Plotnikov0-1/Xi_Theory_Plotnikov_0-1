# =========================================================================
# СОЕДИНЕНИЕ С ПАМЯТЬЮ. Триада А·Д·Л — это генезис ПАМЯТИ, и текст говорит это
# буквально. «Серебряная нить» = связь; при разрыве (Л) «нить НЕ обрывается,
# складывается в клубок, остаётся в вас — это воспоминания»; «Дом вы будете
# помнить всегда… Дом — прежде всего в вас». То есть связь не исчезает при
# разрыве, а сворачивается внутрь как память.
#
# Это в ТОЧНОСТИ физика памяти модели (dephasing.py):
#   А — живая нить = связь с резервуаром (коэффициент связи α);
#   Л — разрыв = переход, на котором внешняя связь сворачивается в внутреннюю
#       историю — ядро памяти K(t) («клубок» = интеграл по прошлому = ε);
#   Д — «Дом в вас» = удержанная память = ПЛАТО когерентности c(∞)=e^(−α)>0
#       (суперомический резервуар НЕ стирает память: «нить не обрывается»).
#
# Статус: соответствие интерпретационное (Q3). Сама физика (плато, ядро) стоит
# отдельно и строго; буквы лишь ложатся на неё, не выводят её.
MEMORY_BRIDGE = {
    "А": ("живая «серебряная нить» — связь с источником",
          "связь с резервуаром, коэффициент α"),
    "Л": ("разрыв: «нить не обрывается, складывается в клубок»",
          "ядро памяти K(t) = «клубок» = ∫ по прошлому = ε"),
    "Д": ("«Дом в вас» — помнишь всегда, всю жизнь",
          "плато когерентности c(∞)=e^(−α)>0 — память не стёрта"),
}


def memory_bridge() -> dict:
    """Мост триады А·Д·Л → физика памяти, с реальным числом плато из dephasing."""
    from . import dephasing
    plateau = dephasing.plateau_T0(alpha=1.0)   # c(∞)=e^(−1)≈0.368
    out = {L: {"образ": img, "физика": phys}
           for L, (img, phys) in MEMORY_BRIDGE.items()}
    out["Д"]["плато c(∞)"] = plateau
    return out


