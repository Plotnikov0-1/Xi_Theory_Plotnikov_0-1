# ДВА НУЛЯ. Триада А·Д·Л связывает ВНЕШНИЙ 0 (целое за пределом круга) и
# ВНУТРЕННИЙ 0 (центр-точка, исток индивидуального). Радиально (nested_spheres):
#   r=0      — ВНУТРЕННИЙ 0: центр-точка (S0, чуть смещён = CP);
#   r=√3     — Л: внутренний шар (куб) = ограниченная память (граница «я»);
#   зазор    — Д: туннель-четвёрка между шарами (соединяет внутр. и внешн.);
#   r=3/φ    — А: внешний шар (додекаэдр) = всеобъемлющая память;
#   r≥3/φ    — ВНЕШНИЙ 0: целое за пределом круга.
# Туннель Д = 3/φ − √3 ≈ 0.122 (близко к эталонной точке туннеля 0.1244, ~2%).
# Путь Л→Д→А (= трещина 7→4→1) — это и есть связь внутреннего 0 с внешним 0.
def zero_axis() -> dict:
    """Радиальная ось, связывающая внутренний 0 и внешний 0 буквами А·Д·Л."""
    from . import nested_spheres as N
    inner = float(N.R_CIRC)                       # √3  — куб (Л)
    outer = float(N.outer_dodecahedron("mid"))    # 3/φ — додекаэдр (А)
    gap = outer - inner                            # туннель Д
    return {
        "внутренний 0": {"r": 0.0, "смысл": "центр-точка (S0), исток «я», смещён=CP"},
        "Л": {"r": inner, "канал": "0→7", "смысл": "внутренний шар (куб), ограниченная память"},
        "Д": {"r_зазор": gap, "канал": "0→4", "смысл": "туннель-4 между шарами (соединяет)"},
        "А": {"r": outer, "канал": "0→1", "смысл": "внешний шар (додек), всеобъемлющая память"},
        "внешний 0": {"r": outer, "смысл": "целое за пределом круга"},
        "путь_связи": "Л→Д→А (трещина 7→4→1): внутренний 0 ↔ внешний 0",
    }


