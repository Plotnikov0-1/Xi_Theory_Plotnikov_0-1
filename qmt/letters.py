# ТРИАДА А · Д · Л — три порождающие буквы («три матери» этого слоя).
# Источник СТРОИТ их друг из друга явно (это внутренняя конструкция текста,
# а не наша подгонка):
#   А = «крыша» + перекладина-ПУПОВИНА → нерождённый, в утробе, ЗАМКНУТ (ноль);
#   Л = А с РАЗОРВАННОЙ пуповиной       → рождён, отделён, стоит на основании;
#   Д = Л + ФУНДАМЕНТ (основание)       → ДОМ, осевшая форма.
# Цитаты: «Разорвав эту пуповину… это будет буква Л»; «дом состоит из буквы А,
# только вместо перекладины нет пуповины… буква Л… имеет основание, фундамент».
#
# Это ровно генезис модели: точка/ноль → разрыв/переход → форма.
#   А ↔ S0  (точка-ноль, шар-оболочка, «крыша»)
#   Л ↔ переход/разрыв (канал, движение — «ноги»)
#   Д ↔ форма/структура (дом = ячейка, куб/жилище)
# И связь с геометрией: «крыша» А — это та самая КРЫША, что надстраивается над
# гранью куба (золотые вершины торчат на φ−1), превращая куб в додекаэдр
# (см. nested_spheres). Дом Д = куб + крыша = жилая ячейка.
