# =========================================================================
# ТРИАДА А · Д · Л — три порождающие буквы («три матери» этого слоя).
# Источник СТРОИТ их друг из друга явно (это внутренняя конструкция текста,
# а не наша подгонка):
#   А = «крыша» + перекладина-ПУПОВИНА → нерождённый, в утробе, ЗАМКНУТ (ноль);
#   Л = А с РАЗОРВАННОЙ пуповиной       → рождён, отделён, стоит на основании;
#   Д = Л + ФУНДАМЕНТ (основание)       → ДОМ, осевшая форма.
# Цитаты: «Разорвав эту пуповину… это будет буква Л»; «дом состоит из буквы А,
# только вместо перекладины нет пуповины… буква Л… имеет основание, фундамент».
#
# Это ровно генезис модели: точка/ноль → разрыв/переход → форма.
#   А ↔ S0  (точка-ноль, шар-оболочка, «крыша»)
#   Л ↔ переход/разрыв (канал, движение — «ноги»)
#   Д ↔ форма/структура (дом = ячейка, куб/жилище)
# И связь с геометрией: «крыша» А — это та самая КРЫША, что надстраивается над
# гранью куба (золотые вершины торчат на φ−1), превращая куб в додекаэдр
# (см. nested_spheres). Дом Д = куб + крыша = жилая ячейка.
TRINITY = {
    "А": "исток/ноль: крыша + пуповина, нерождённый в оболочке (S0, шар)",
    "Л": "разрыв/переход: А без пуповины, отделение, движение («ноги»)",
    "Д": "форма/дом: Л + фундамент, осевшая структура (куб+крыша=ячейка)",
}
TRINITY_GENESIS = "А --(разрыв пуповины)--> Л --(+фундамент)--> Д"

# =========================================================================
# СОЕДИНЕНИЕ С ПАМЯТЬЮ. Триада А·Д·Л — это генезис ПАМЯТИ, и текст говорит это
# буквально. «Серебряная нить» = связь; при разрыве (Л) «нить НЕ обрывается,
# складывается в клубок, остаётся в вас — это воспоминания»; «Дом вы будете
# помнить всегда… Дом — прежде всего в вас». То есть связь не исчезает при
# разрыве, а сворачивается внутрь как память.
#
# Это в ТОЧНОСТИ физика памяти модели (dephasing.py):
#   А — живая нить = связь с резервуаром (коэффициент связи α);
#   Л — разрыв = переход, на котором внешняя связь сворачивается в внутреннюю
#       историю — ядро памяти K(t) («клубок» = интеграл по прошлому = ε);
#   Д — «Дом в вас» = удержанная память = ПЛАТО когерентности c(∞)=e^(−α)>0
#       (суперомический резервуар НЕ стирает память: «нить не обрывается»).
#
# Статус: соответствие интерпретационное (Q3). Сама физика (плато, ядро) стоит
# отдельно и строго; буквы лишь ложатся на неё, не выводят её.
MEMORY_BRIDGE = {
    "А": ("живая «серебряная нить» — связь с источником",
          "связь с резервуаром, коэффициент α"),
    "Л": ("разрыв: «нить не обрывается, складывается в клубок»",
          "ядро памяти K(t) = «клубок» = ∫ по прошлому = ε"),
    "Д": ("«Дом в вас» — помнишь всегда, всю жизнь",
          "плато когерентности c(∞)=e^(−α)>0 — память не стёрта"),
}


def memory_bridge() -> dict:
    """Мост триады А·Д·Л → физика памяти, с реальным числом плато из dephasing."""
    from . import dephasing
    plateau = dephasing.plateau_T0(alpha=1.0)   # c(∞)=e^(−1)≈0.368
    out = {L: {"образ": img, "физика": phys}
           for L, (img, phys) in MEMORY_BRIDGE.items()}
    out["Д"]["плато c(∞)"] = plateau
    return out


# =========================================================================
# ТРИ КАНАЛА ПАМЯТИ. Триада ложится на каналы 0→1, 0→4, 0→7 (семья 1,4,7 модели,
# scaling.py): «0,1»=канал 0→1, «0,4»=канал 0→4, «0,7»=канал 0→7. Качество
# памяти задаёт глубина охвата (3/2/1 уровня):
#   А → 0→1 : охват 3 (самый глубокий, «канал φ») — ВСЕОБЪЕМЛЮЩАЯ ЕДИНАЯ память,
#             знает прошлое-настоящее-будущее (связь с целым/источником);
#   Д → 0→4 : охват 2 — ТУННЕЛЬ/КАНАЛ («четвёрка»), соединяет с духом; информация
#             идёт «от целого числа за пределом круга», а 4 «находится здесь» и
#             соединяет внутреннее с внешним (это тоже память — связующая);
#   Л → 0→7 : охват 1 — наша ОГРАНИЧЕННАЯ память (индивидуальная, узкий охват).
# Трещина 7→4→1 (scaling.crack_path): путь Л→Д→А (ограниченная → туннель →
# единая) = возврат ограниченной памяти к всеобъемлющей через канал-четвёрку.
TRINITY_CHANNELS = {
    "А": (1, "всеобъемлющая единая память — прошлое·настоящее·будущее"),
    "Д": (4, "туннель/канал (4) — соединяет с целым за пределом круга"),
    "Л": (7, "наша ограниченная (индивидуальная) память"),
}


def trinity_memory() -> dict:
    """Триада → каналы памяти модели (с реальным охватом из scaling.py)."""
    from . import scaling
    reach = scaling.memory_channel_reach()         # {1:3, 4:2, 7:1}
    crack = scaling.crack_path()                    # (7,4,1)
    out = {}
    for L, (node, role) in TRINITY_CHANNELS.items():
        out[L] = {"канал": f"0→{node}", "узел": node,
                  "охват уровней": reach[node], "роль": role}
    out["_трещина_7→4→1"] = "Л→Д→А: ограниченная → туннель → единая память"
    return out


# Гипотеза 27 = 20 + 7: кандидаты в «связующие» (переходные) буквы — те, чья
# суть в тексте про связь/разрыв/переход, а не про состояние. ПОМЕЧЕНО как
# интерпретация: список можно менять, он не выводится строго.
TRANSITION_HYPOTHESIS = ["Б", "Н", "Л", "Х", "И", "Й", "У"]   # 7 «связей»


@dataclass
class LetterMap:
    states: list       # 20 букв-состояний (кандидаты на вершины)
    links: list        # 7 букв-переходов (кандидаты на рёбра/связи)
    status: str = "Q3 — интерпретация, искажаемый семантический слой"


def split_20_7(transition=None) -> LetterMap:
    """Разбиение 27 = 20 + 7 по заданному списку «связующих» букв (гипотеза)."""
    links = transition or TRANSITION_HYPOTHESIS
    states = [L for L in LETTERS if L not in links]
    return LetterMap(states=states, links=list(links))


