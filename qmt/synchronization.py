def corroboration(n: int) -> list[str]:
    """Где число n=3/7/12 закреплено в НЕИСКАЖАЕМЫХ (выводимых) источниках."""
    field_by_n = {3: "three", 7: "seven", 12: "twelve"}
    f = field_by_n[n]
    out = []
    for c in CANONS:
        if c.rederivable and c.distortion == "низкий" and getattr(c, f) and \
                c.name != "DIALOG QMT":
            out.append(f"{c.name}: {getattr(c, f)}")
    return out


# --------------------------------------------------------------------------
# Платоновы тела: V, E, F, теорема Эйлера.
# --------------------------------------------------------------------------
@dataclass
class Solid:
    name: str
    V: int
    E: int
    F: int

    def euler(self) -> int:
        return self.V - self.E + self.F


SOLIDS = [
    Solid("тетраэдр", 4, 6, 4),
    Solid("куб", 8, 12, 6),
    Solid("октаэдр", 6, 12, 8),
    Solid("додекаэдр", 20, 30, 12),
    Solid("икосаэдр", 12, 30, 20),
]


def euler_check() -> bool:
    return all(s.euler() == 2 for s in SOLIDS)


def print_report() -> None:
    print("СИНХРОНИЗАЦИЯ КАНОНОВ — карта 3 + 7 + 12 с защитой от искажения")
    print("=" * 72)
    print("Доверие = жёсткость × устойчивость к искажению источника.\n")
    print(f"{'Канон':<26}{'искаж.':<9}{'доверие':<11}{'3':^3}{'7':^3}{'12':^3}")
    print("-" * 72)
    for c in sorted(CANONS, key=lambda x: -x.trust()):
        m = lambda x: "✓" if x else "·"
        print(f"{c.name:<26}{c.distortion:<9}{c.grade():<11}"
              f"{m(c.three):^3}{m(c.seven):^3}{m(c.twelve):^3}")

    print("\nКлюч: КАЖДОЕ число независимо подтверждено НЕискажаемыми источниками —")
    print("если выбросить всю эзотерику, разметка 3+7+12 всё равно держится:")
    for n in (3, 7, 12):
        print(f"\n  {n}:")
        for s in corroboration(n):
            print(f"     • {s}")

    print("\nГеометрия — теорема Эйлера V−E+F=2 (Q0):", euler_check())
    print(f"{'тело':<12}{'V':>4}{'E':>4}{'F':>4}{'  V−E+F':>8}")
    for s in SOLIDS:
        print(f"{s.name:<12}{s.V:>4}{s.E:>4}{s.F:>4}{s.euler():>8}")

    print("\n" + "=" * 72)
    print("Вывод: каббала даёт ПОЛНУЮ разметку, но у неё высокий риск искажения,")
    print("поэтому она лишь ВСПОМОГАТЕЛЬНАЯ корроборация. Опора карты — выводимые")
    print("заново структуры (кристаллография даёт 7, физика и геометрия — 3 и 12).")


if __name__ == "__main__":
    print_report()
