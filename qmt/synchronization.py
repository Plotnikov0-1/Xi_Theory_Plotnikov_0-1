"""
Синхронизация канонов — картография, а не предсказание.

Жанр этого модуля иной, чем у физического слоя. Здесь задача не «предсказать
новое» (тогда работал бы критерий cherry-picking из coincidence_ledger), а
показать, что независимые канонические системы несут ОДНУ И ТУ ЖЕ структурную
разметку. Это легитимный научный жанр синтеза — как периодическая таблица
Менделеева, систематика Линнея, ADE-классификация Дынкина, теория категорий:
сила не в предсказании, а в полноте охвата и непротиворечивости связей.

КЛЮЧЕВАЯ РАЗМЕТКА:  3 + 7 + 12 = 22   (а также 3 + 7 = 10).

Чтобы синхронизация была СИЛЬНОЙ (а не подгонкой), структура-мишень должна
удовлетворять трём условиям жёсткости — их и проверяет rigidity():
  (1) НЕЗАВИСИМОСТЬ — зафиксирована до и вне DIALOG (канон, источник, теорема);
  (2) ТОЧНОСТЬ — целые числа/точное равенство, не приближение;
  (3) ПОЛНОТА — совпадает вся разметка (3 и 7 и 12), а не один выбранный кусок.

Этот модуль не «доказывает» теорию. Он строит карту узлов, на которой видны
связи между традициями, геометрией и физикой, и честно ранжирует их прочность.
"""

from __future__ import annotations

from dataclasses import dataclass, field

# --------------------------------------------------------------------------
# Канонические системы с разметкой (a=3, b=7, c=12). Все ЗАФИКСИРОВАНЫ вне
# DIALOG — это их собственная, исторически/математически данная структура.
# --------------------------------------------------------------------------
@dataclass
class Canon:
    name: str
    source: str
    three: str        # «три» (скрытые/матери/первоэлементы)
    seven: str        # «семь» (двойные/планеты/ноты)
    twelve: str       # «двенадцать» (простые/знаки/рёбра)
    independent: bool  # зафиксирована вне DIALOG?
    exact: bool        # целочисленная/точная?

    def total(self) -> int:
        return 22

    def has_full_partition(self) -> bool:
        return bool(self.three and self.seven and self.twelve)


CANONS = [
    Canon("Сефер Йецира (каббала)",
          "Книга Творения, II–VI вв.",
          "3 матери: Алеф·Мем·Шин (воздух·вода·огонь)",
          "7 двойных: Бет·Гимель·Далет·Каф·Пе·Реш·Тав",
          "12 простых букв",
          independent=True, exact=True),
    Canon("Астрология / календарь",
          "вавилонско-эллинистическая традиция",
          "3 (декады/триплицитеты как деления)",
          "7 классических планет",
          "12 знаков зодиака · 12 месяцев",
          independent=True, exact=True),
    Canon("Музыкальный строй",
          "пифагорейская традиция",
          "3 (тоника·доминанта·субдоминанта)",
          "7 ступеней диатоники",
          "12 полутонов хроматики (круг квинт)",
          independent=True, exact=True),
    Canon("Геометрия куба (O-группа)",
          "Платон / теорема Эйлера",
          "3 оси симметрии (координатные)",
          "",   # семёрки в счёте элементов куба НЕТ — честно оставляем пусто
          "12 рёбер куба",
          independent=True, exact=True),
    Canon("DIALOG QMT",
          "Плотников Л.В., Харитонов Г.М.",
          "3 скрытых нуля-оператора: S0·S4·S6",
          "7 явных Братьев: S1·S2·S3·S5·S7·S8·S9",
          "12 развёрток (рёбра куба / расширение)",
          independent=False, exact=True),
]


@dataclass
class Rigidity:
    canon: str
    independent: bool
    exact: bool
    full: bool
    score: int = field(init=False)
    grade: str = field(init=False)

    def __post_init__(self):
        self.score = int(self.independent) + int(self.exact) + int(self.full)
        self.grade = {3: "СИЛЬНАЯ", 2: "СРЕДНЯЯ", 1: "СЛАБАЯ", 0: "НЕТ"}[self.score]


def rigidity(c: Canon) -> Rigidity:
    """Оценка прочности синхронизации по трём условиям жёсткости."""
    return Rigidity(c.name, c.independent, c.exact, c.has_full_partition())


# --------------------------------------------------------------------------
# Платоновы тела: V, E, F — проверка теоремы Эйлера и поиск чисел 3/7/12.
# --------------------------------------------------------------------------
@dataclass
class Solid:
    name: str
    V: int
    E: int
    F: int

    def euler(self) -> int:
        return self.V - self.E + self.F   # должно быть 2


SOLIDS = [
    Solid("тетраэдр", 4, 6, 4),
    Solid("куб", 8, 12, 6),
    Solid("октаэдр", 6, 12, 8),
    Solid("додекаэдр", 20, 30, 12),
    Solid("икосаэдр", 12, 30, 20),
]


def euler_check() -> bool:
    """Теорема Эйлера V−E+F=2 для всех пяти тел (Q0)."""
    return all(s.euler() == 2 for s in SOLIDS)


def where_is(n: int) -> list[str]:
    """Где число n встречается среди V/E/F платоновых тел."""
    hits = []
    for s in SOLIDS:
        for label, val in (("V", s.V), ("E", s.E), ("F", s.F)):
            if val == n:
                hits.append(f"{s.name}:{label}")
    return hits


def print_report() -> None:
    print("СИНХРОНИЗАЦИЯ КАНОНОВ — карта структуры 3 + 7 + 12 = 22")
    print("=" * 70)
    print("\nЖанр: картография уже доказанного (Менделеев/Линней/ADE/категории),")
    print("а не предсказание. Сила = независимость + точность + полнота.\n")

    print(f"{'Канон':<28}{'жёсткость':<10}{'3':^3}{'7':^3}{'12':^3}")
    print("-" * 70)
    for c in CANONS:
        r = rigidity(c)
        mark = lambda x: "✓" if x else "·"
        print(f"{c.name:<28}{r.grade:<10}"
              f"{mark(c.three):^3}{mark(c.seven):^3}{mark(c.twelve):^3}")

    print("\nГеометрия — теорема Эйлера V−E+F=2:")
    print(f"  для всех 5 тел выполняется: {euler_check()}  (Q0)")
    print(f"{'тело':<12}{'V':>4}{'E':>4}{'F':>4}{'   V−E+F':>9}")
    for s in SOLIDS:
        print(f"{s.name:<12}{s.V:>4}{s.E:>4}{s.F:>4}{s.euler():>9}")

    print(f"\nЧисло 12 в геометрии: {', '.join(where_is(12))}")
    print(f"Число  3 в геометрии: {', '.join(where_is(3)) or 'нет в счёте V/E/F'}")
    print(f"Число  7 в геометрии: {', '.join(where_is(7)) or 'нет в счёте V/E/F'}")

    print("\n" + "=" * 70)
    print("Честно: 3 и 12 имеют геометрический дом (оси, рёбра/вершины/грани);")
    print("7 геометрического дома в счёте V/E/F НЕ имеет — оно приходит из слоя")
    print("«семь двойных / планеты / ступени». Поэтому каббала и DIALOG несут")
    print("ПОЛНУЮ разметку 3+7+12, а чистая геометрия — только 3 и 12.")
    print("Сильнейшая внешняя опора — Сефер Йецира (независима, точна, полна).")


if __name__ == "__main__":
    print_report()
