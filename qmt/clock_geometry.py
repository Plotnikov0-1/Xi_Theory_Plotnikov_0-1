    print(f"\n  ◇ золото на экваторе  sin72/sin36 = 2cos36 = φ РОВНО: {golden_on_equator_is_exact()}")
    print(f"\n  ◇ mod-3 раскраска циферблата = три семейства:")
    for k, v in mod3_families().items():
        print(f"       {k}: {v}")
    print(f"\n  ◇ куб по [1,1,1]: {cube_along_diagonal()}")
    print(f"\n  ◇ {{12/5}} одна ломаная (gcd=1): {star_12_5_single_polygon()}   {symmetry_counts()}")
    print(f"\n  ◇ центр-5 = седло (Ирншоу ∇²1/r=0): {center_is_saddle()}")
    print(f"\n  ★ MISREAD исправлен — 5:3 это Фибоначчи-сосед, не φ:")
    print(f"       {lissajous_ratio_is_fibonacci_not_phi()}")
    print("═" * 78)
    print("  Часы = иллюстрация (○), не источник новой математики. Реально сошлись:")
    print("  φ (72°/36°, точно), 1/3 и 109.47° (алмаз/кварк), mod-3 = три семьи, седло.")
    print("═" * 78)


