from __future__ import annotations

import math
from itertools import product

PHI = (1 + math.sqrt(5)) / 2


# ── ◇ 16:48 двойной ключ ─────────────────────────────────────────────────────
def hands_1648() -> dict:
    """◇ 4:48 → часовая 144°, минутная 288°, обе кратны 72°; между = 144°."""
    hour = (4 + 48 / 60) * 30
    minute = 48 * 6
    return {"hour": hour, "minute": minute, "hour=2·72": hour == 144,
            "minute=4·72": minute == 288, "between": minute - hour}


def one_third_is_tetrahedral() -> dict:
    """◇ 16/48 = 1/3 = cos70.53° = −cos109.47° (тетраэдр/алмаз/кварк ±1/3)."""
    return {"16/48": 1 / 3,
            "arccos(1/3)°": round(math.degrees(math.acos(1 / 3)), 2),      # 70.53
            "arccos(−1/3)°": round(math.degrees(math.acos(-1 / 3)), 2),    # 109.47
            "tetra=109.47": round(math.degrees(math.acos(-1 / 3)), 2) == 109.47}


# ── ◇ золото на экваторе: sin72/sin36 = φ РОВНО ──────────────────────────────
def golden_on_equator_is_exact() -> bool:
    """◇ sin72°/sin36° = 2·cos36° = φ точно (тождество, не совпадение)."""
    ratio = math.sin(math.radians(72)) / math.sin(math.radians(36))
    return abs(ratio - PHI) < 1e-12 and abs(2 * math.cos(math.radians(36)) - PHI) < 1e-12


# ── ◇ mod-3 раскраска циферблата = три семейства ─────────────────────────────
def mod3_families() -> dict:
    """◇ 1..12 по классам mod 3 = π-/φ-/√2-семьи; тёмные 2·5·8·11 = класс 2."""
    fam = {c: [n for n in range(1, 13) if n % 3 == c] for c in (0, 1, 2)}
    dark = [2, 5, 8, 11]
    return {"π (0 mod3)": fam[0], "φ (1 mod3)": fam[1], "√2 (2 mod3)": fam[2],
            "тёмные 2·5·8·11 = класс 2": all(n % 3 == 2 for n in dark)}


# ── ◇ куб на сфере вдоль [1,1,1] ─────────────────────────────────────────────
def cube_along_diagonal() -> dict:
    """◇ куб по [1,1,1]: 2 полюса + два кольца по 3 на широте ±arcsin(1/3)=19.47°."""
    def clamp(x):
        return max(-1.0, min(1.0, x))
    lats = {}
    for v in product([-1, 1], repeat=3):
        lat = round(math.degrees(math.asin(clamp(sum(v) / 3))), 2)  # v·[111]/(√3·√3)
        lats[lat] = lats.get(lat, 0) + 1
    return {"lats": dict(sorted(lats.items())),
            "arcsin(1/3)°": round(math.degrees(math.asin(1 / 3)), 2),
            "poles+two rings of 3": lats == {-90.0: 1, -19.47: 3, 19.47: 3, 90.0: 1}}


# ── ◇ звезда {12/5} ──────────────────────────────────────────────────────────
def star_12_5_single_polygon() -> bool:
    """◇ gcd(5,12)=1 → {12/5} одна замкнутая ломаная через все 12 точек."""
    return math.gcd(5, 12) == 1


def symmetry_counts() -> dict:
    """◇ 24 = 2 звезды {12/5}+{12/7} (повороты куба); 48 = полная группа куба."""
    return {"24=rot(cube)=2·12": 24 == 2 * 12, "48=full(cube)": 48 == 4 * 12 * 2}


# ── ★ исправленный misread: 5/3 ≠ φ (фибоначчиев сосед) ──────────────────────
def lissajous_ratio_is_fibonacci_not_phi() -> dict:
    """★ 5:3 — соседние Фибоначчи; 5/3=1.667 ≈ φ (сходится), НЕ равно φ. Ярус ≈."""
    fib = [1, 1, 2, 3, 5, 8]
    return {"5/3": round(5 / 3, 4), "φ": round(PHI, 4),
            "|5/3−φ|": round(abs(5 / 3 - PHI), 4),
            "3,5 соседи Фибоначчи": 3 in fib and 5 in fib and fib[fib.index(3) + 1] == 5,
            "равно φ": abs(5 / 3 - PHI) < 1e-9,             # False — честно
            "LCM(5,3)": math.lcm(5, 3)}                      # 15 → период 15π


# ── ◇ центр-5 = седло (Ирншоу) ───────────────────────────────────────────────
def center_is_saddle() -> bool:
    """◇ ∇²(1/r)=0 (гармонична) → нет устойчивой ямы в свободной точке → седло."""
    # аналитически: Δ(1/r)=0 при r≠0; проверим численно в точке.
    def V(x, y, z):
        return 1.0 / math.sqrt(x * x + y * y + z * z)
    h, x0, y0, z0 = 1e-4, 0.7, 0.3, 0.5
    lap = (V(x0 + h, y0, z0) + V(x0 - h, y0, z0)
           + V(x0, y0 + h, z0) + V(x0, y0 - h, z0)
           + V(x0, y0, z0 + h) + V(x0, y0, z0 - h) - 6 * V(x0, y0, z0)) / h ** 2
    return abs(lap) < 1e-2   # ≈0 → сумма кривизн = 0 → седло


def print_report() -> None:
    print("═" * 78)
    print("  ГЕОМЕТРИЯ ЧАСОВ — что легло ТОЧНО (◇), что совпадение (≈), misread (★)")
