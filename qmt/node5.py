"""
═══════════════════════════════════════════════════════════════════════════
  NODE5 — узел 5: единственная точка, где геометрия НЕ диктует движение.
═══════════════════════════════════════════════════════════════════════════

Восемь узлов автоматические, один требует АКТА ВЫБОРА. Узел 5 — центр, и он
особый сразу по нескольким строгим причинам.

✓ ФИЗИКА (проверяемо):
  1. ТОЛЬКО s-состояние касается центра: |ψ_{n,l=0}(0)|² = 1/(π n³ a₀³) ≠ 0,
     а для l≥1 ψ(0)=0. Узел 5 (l=0) — единственный, «трогающий» ядро. Отсюда
     контактное сверхтонкое взаимодействие (Ферми) — реальный эффект именно у s.
  2. БИФУРКАЦИЯ (нормальная форма вил): ẋ = μx − x³. При μ<0 центр x=0
     устойчив; при μ>0 центр НЕустойчив (седло), рождаются ±√μ. Симметричная
     точка теряет устойчивость — это механизм Хиггса (симметричный вакуум
     неустойчив → спонтанное нарушение). Центр = где нужно «выбрать» ветвь.

◇ ГЕОМЕТРИЯ (точно):
  3. САМОЗЕРКАЛЬНОСТЬ: R(5)=5 — неподвижная точка инверсии −I (в схеме n↔10−n).
     Структурная асимметрия здесь ноль (A(5)=0, см. cp_asymmetry) — «перехода нет».
  4. ТРЕТЬЯ ДОРОГА: по рёбрам куба антипод узнаётся за диаметр = 3 шага; из
     ЦЕНТРА зеркало −I даёт антипод за 1 операцию (v→−v). Центр видит обе стороны
     сразу — это различие локального шага и вариационного принципа (наименьшее
     действие: сравнить все пути разом, а не идти вслепую).

★ ПОПРАВКА (из внешнего разбора, честно принята):
  5. Если зеркальные пары (1,9)(2,8)(3,7)(4,6) и центр 5 читать БУКВАЛЬНО как
     рёбра, то это ПОЛНОЕ ПАРОСОЧЕТАНИЕ (димеры) + изолят 5 — граф РАСПАДАЕТСЯ на
     5 компонент. Тогда: спектрального смешивания нет, avoided crossing нет — зато
     чистейшая ТОПОЛОГИЯ ВОЗВРАТА. Это не связный поток, а решётка независимых
     димеров. Важно не путать «красивую пару» со «связным переходом».

Запуск:  python -m qmt.node5
"""

from __future__ import annotations

import math

A0 = 5.29177210903e-11             # боровский радиус (м)


# ── ✓ 1. s-состояние касается центра ─────────────────────────────────────────
def psi_squared_at_origin(n: int, l: int) -> float:
    """|ψ(0)|² в центре: 1/(π n³ a₀³) для l=0, иначе 0 (узел 5 = единственный контакт)."""
    if l != 0:
        return 0.0
    return 1.0 / (math.pi * n**3 * A0**3)


def only_s_touches_center(n: int = 5) -> bool:
    """✓ Только l=0 даёт ψ(0)≠0; все l≥1 зануляются в центре."""
    return psi_squared_at_origin(n, 0) > 0 and all(
        psi_squared_at_origin(n, l) == 0 for l in range(1, n))


# ── ✓ 2. Бифуркация вил: центр теряет устойчивость (Хиггс) ────────────────────
def pitchfork_fixed_points(mu: float) -> list:
    """Неподвижные точки ẋ=μx−x³: {0} при μ≤0, {0,±√μ} при μ>0."""
    if mu <= 0:
        return [0.0]
    return [0.0, math.sqrt(mu), -math.sqrt(mu)]


def center_unstable_above(mu: float) -> bool:
    """Устойчивость центра x=0: f'(0)=μ. Центр неустойчив ⇔ μ>0 (седло → выбор)."""
    return mu > 0                      # f'(0)=μ; >0 ⇒ неустойчив


def higgs_saddle_at_center(mu: float = 0.5) -> bool:
    """✓ При μ>0 (напр. μ=0.5) центр неустойчив, рождаются две ветви = Хиггс."""
    return center_unstable_above(mu) and len(pitchfork_fixed_points(mu)) == 3


# ── ◇ 3. Самозеркальность и A(5)=0 ───────────────────────────────────────────
def mirror_10(n: int) -> int:
    """Инверсия n↔10−n (центр 5). R(5)=5 — неподвижная точка."""
    return 10 - n


def is_self_mirror(n: int) -> bool:
    """◇ Узел самозеркален ⇔ R(n)=n. Единственный такой в 1..9 — это 5."""
    return mirror_10(n) == n


# ── ◇ 4. Третья дорога: центр против ребра ───────────────────────────────────
def steps_along_edges_to_antipode() -> int:
    """◇ По рёбрам куба до антипода = диаметр графа = 3 шага."""
    return 3


def ops_from_center_to_antipode() -> int:
    """◇ Из центра зеркало −I даёт антипод за 1 операцию (v→−v)."""
    return 1


def center_is_shortcut() -> bool:
    """◇ Центр видит обе стороны сразу: 1 операция < 3 шага по краю."""
    return ops_from_center_to_antipode() < steps_along_edges_to_antipode()


# ── ★ 5. Поправка: зеркальные пары = димеры (граф распадается) ────────────────
def mirror_graph_components() -> int:
    """★ Пары (1,9)(2,8)(3,7)(4,6) как рёбра + изолят 5 → число компонент."""
    parent = {n: n for n in range(1, 10)}

    def find(a):
        while parent[a] != a:
            parent[a] = parent[parent[a]]
            a = parent[a]
        return a

    def union(a, b):
        parent[find(a)] = find(b)

    for n in range(1, 10):
        m = mirror_10(n)
        if 1 <= m <= 9 and m != n:
            union(n, m)                # ребро зеркала
    return len({find(n) for n in range(1, 10)})


def is_disconnected_dimers() -> bool:
    """★ Полное паросочетание + изолят: НЕ связный поток (нет спектр. смешивания)."""
    # 4 димера {(1,9),(2,8),(3,7),(4,6)} + изолят {5} = 5 компонент
    return mirror_graph_components() == 5


def print_report() -> None:
    print("═" * 74)
    print("  УЗЕЛ 5: единственная точка, где геометрия не диктует движение")
    print("═" * 74)
    print(f"\n  ✓ 1. только s (l=0) касается центра: {only_s_touches_center()}")
    print(f"       |ψ_5s(0)|² = {psi_squared_at_origin(5,0):.3e} м⁻³ ≠ 0; l≥1 → 0")
    print(f"\n  ✓ 2. бифуркация вил ẋ=μx−x³ (Хиггс):")
    for mu in (-0.5, 0.5):
        fp = pitchfork_fixed_points(mu)
        print(f"       μ={mu:+.1f}: центр {'устойчив' if mu<=0 else 'НЕустойчив'}, "
              f"неподв.точки={[round(x,3) for x in fp]}")
    print(f"       при μ=0.5 центр — седло, две ветви (выбор): {higgs_saddle_at_center()}")
    print(f"\n  ◇ 3. самозеркальность R(5)=5 (единственная в 1..9): {is_self_mirror(5)}")
    print(f"       (структурная асимметрия A(5)=0 — перехода нет, см. cp_asymmetry)")
    print(f"\n  ◇ 4. третья дорога: центр {ops_from_center_to_antipode()} операция "
          f"< край {steps_along_edges_to_antipode()} шага (−I мгновенно): {center_is_shortcut()}")
    print(f"\n  ★ 5. поправка (внешний разбор): зеркальные пары буквально = димеры →")
    print(f"       граф распадается на {mirror_graph_components()} компонент "
          f"(4 димера + изолят 5): {is_disconnected_dimers()}")
    print(f"       ⇒ нет спектр. смешивания и avoided crossing, но чистая топология возврата")
    print("═" * 74)
    print("  Узел 5 = контакт с центром (ψ≠0) + седло Хиггса (выбор) + неподвижная")
    print("  точка зеркала. 8 узлов автоматичны, 5-й требует акта. Честно: пары=димеры.")
    print("═" * 74)


if __name__ == "__main__":
    print_report()
