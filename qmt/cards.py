def alphabet_tier_counts() -> dict:
    """Честное распределение: 24 ○ (аллегория) + 2 ✓ (реальные пороги Д, Х)."""
    out = {}
    for c in ALPHABET:
        out[c.tier] = out.get(c.tier, 0) + 1
    return out


def alphabet_real_anchors() -> list:
    """✓ Только Д (порог p→d) и Х (Z>118) имеют реальный якорь; остальное — семантика."""
    return [c.symbol for c in ALPHABET if c.tier == "✓"]


def alphabet_is_life_cycle() -> bool:
    """Закономерность алфавита: жизненный цикл (утроба→рождение→…→конец)."""
    return ALPHABET[0].symbol == "А" and "утроба" in ALPHABET[0].essence \
        and ALPHABET[-1].symbol == "Щ"


# ── Закономерность: замкнутый функциональный конвейер ────────────────────────
def pipeline_is_closed() -> bool:
    """◇ Десять карточек 0→…→9→0 — один замкнутый цикл (10 различных узлов)."""
    syms = [c.symbol for c in NUMBER_CARDS]
    return len(set(syms)) == 10 and syms == [str(i) for i in range(10)]


def center_is_choice() -> bool:
    """Узел 5 — единственная самозеркальная карточка (выбор): R(5)=5."""
    return 10 - 5 == 5


def functions() -> dict:
    """Закономерность: каждый символ → ровно одна функция."""
    return {c.symbol: c.function for c in NUMBER_CARDS}


def card(symbol: str) -> Card:
    """Достать карточку по символу."""
    for c in NUMBER_CARDS + LETTER_CARDS:
        if c.symbol == symbol:
            return c
    raise KeyError(symbol)


# ── Сверка с водородом: где карточка = реальное число, где семантика ──────────
def level_energy(n: int) -> float:
    """✓ Уровень водорода E_n = −13.6/n² (эВ). Карточка n ↔ уровень n."""
    return -R_EV / (n * n)


def transition(n: int, m: int) -> dict:
    """✓ Реальный переход n↔m: ΔE (эВ), λ (нм), T_c=ΔE/k (К)."""
    dE = R_EV * abs(1 / n**2 - 1 / m**2)
    return {"ΔE_эВ": dE, "λ_нм": HC_NM / dE, "T_c_К": dE / K_EV}


def physics_anchored() -> dict:
    """✓ Карточки 1–7 привязаны к реальным уровням водорода (n=1..7); 0=предел."""
    return {str(n): round(level_energy(n), 3) for n in range(1, 8)}


def functional_transitions() -> dict:
    """✓ «Функциональные» пары карточек = реальные переходы (посчитаны)."""
    return {"1→2 рождение→связь (Лайман-α)": transition(1, 2),
            "4↔6 измерение↔результат (шёпот)": transition(4, 6),
            "2↔7 связь↔разрыв (петля)": transition(2, 7),
            "6→7 результат→разрыв (туннель)": transition(6, 7)}


def cards_are_hydrogen_anchored() -> bool:
    """✓ Узлы 1–7 = уровни n=1..7 (реальная физика), не только семантика."""
    return all(level_energy(n) < 0 for n in range(1, 8)) and \
        abs(transition(1, 2)["λ_нм"] - 121.5) < 0.5      # Лайман-α = 121.5 нм


