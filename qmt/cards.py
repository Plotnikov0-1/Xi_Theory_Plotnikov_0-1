# ── Закономерность: замкнутый функциональный конвейер ────────────────────────
def pipeline_is_closed() -> bool:
    """◇ Десять карточек 0→…→9→0 — один замкнутый цикл (10 различных узлов)."""
    syms = [c.symbol for c in NUMBER_CARDS]
    return len(set(syms)) == 10 and syms == [str(i) for i in range(10)]


def center_is_choice() -> bool:
    """Узел 5 — единственная самозеркальная карточка (выбор): R(5)=5."""
    return 10 - 5 == 5


def functions() -> dict:
    """Закономерность: каждый символ → ровно одна функция."""
    return {c.symbol: c.function for c in NUMBER_CARDS}


def card(symbol: str) -> Card:
    """Достать карточку по символу."""
    for c in NUMBER_CARDS + LETTER_CARDS:
        if c.symbol == symbol:
            return c
    raise KeyError(symbol)


