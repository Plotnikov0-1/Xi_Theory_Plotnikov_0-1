    """Одна карточка: символ → функция, три слоя + привязки."""
    symbol: str          # 0..9 (или буква)
    op: str              # DIALOG-оператор Op_i
    hydrogen: str        # квантовый уровень/серия
    function: str        # ЗА ЧТО отвечает (одна функция)
    allegory: str        # как сказано (семантика)
    physics: str         # что значит физически
    cern: str            # стадия конвейера события
    module: str          # где проверено в qmt/
    tier: str            # ярус: ✓ / ◇ / ○


