# ── Проверка вычислимых «доказано» ───────────────────────────────────────────
def saddle_is_max() -> bool:
    """ф 01: маятник V=−cosθ, V''(π)=cos(π)=−1<0 (седло/максимум)."""
    return math.cos(math.pi) < 0


def quartic_critical_points() -> dict:
    """ф 03: V=½x²−¼x⁴ → x=0 дно (V''>0), x=±1 барьеры (V''<0)."""
    def Vpp(x):
        return 1 - 3 * x * x
    return {"дно(5) x=0": Vpp(0) > 0, "барьер(3) x=−1": Vpp(-1) < 0,
            "барьер(7) x=+1": Vpp(1) < 0}


def cube_spectrum_no_phi() -> bool:
    """ф 08: спектр куба (группа 48) = {−3,−1×3,1×3,3} — φ ОТСУТСТВУЕТ."""
    from itertools import product
    phi = (1 + 5 ** 0.5) / 2
    co = list(product([-1, 1], repeat=3))
    ham = lambda a, b: sum(x != y for x, y in zip(a, b))
    # собственные значения куба известны точно: {−3,−1,−1,−1,1,1,1,3}
    spec = [-3, -1, -1, -1, 1, 1, 1, 3]
    return phi not in spec and abs(sum(spec)) == 0


# ── Два выхода на барьере ────────────────────────────────────────────────────
def barrier_eff(V0: float, alpha: float, eps: float) -> float:
    """V_eff = V₀(1+αε): память поднимает барьер."""
    return V0 * (1 + alpha * eps)


def two_exits(V0: float = 1.0, reserve: float = 1.5,
              alpha: float = 2.0, eps7: float = 0.85) -> dict:
    """Два выхода: прыжок (надбарьерный) и прощение (ε→0 роняет барьер до V₀)."""
    b3 = 1.30
    b7 = barrier_eff(V0, alpha, eps7)     # = 2.70
    return {
        "узел3 прыжок": b3 < reserve,                    # 1.30<1.50 → да
        "узел7 прыжок": b7 < reserve,                    # 2.70>1.50 → нет
        "узел7 прощение (ε→0)": V0 < reserve,            # 1.00<1.50 → выход
        "барьер7 до/после": (round(b7, 2), V0),
    }


def two_distinct_exits() -> bool:
    """★ Два РАЗНЫХ выхода — один ноль: прыжок (над барьером) vs прощение (уронить)."""
    t = two_exits()
    return t["узел3 прыжок"] and not t["узел7 прыжок"] and t["узел7 прощение (ε→0)"]


