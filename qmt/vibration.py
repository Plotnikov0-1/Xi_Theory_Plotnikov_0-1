"""
═══════════════════════════════════════════════════════════════════════════
  VIBRATION — «всё есть вибрация»: масса = частота, время = отношение.
═══════════════════════════════════════════════════════════════════════════

Из аудио-заметки (Плотников Л.В.). Проверяемое ядро ложится в теорию отношений:

  1. ВРЕМЯ — НЕ ВЕЩЬ, А ОТНОШЕНИЕ. Замени t на x/v (твой опыт). Период t=λ/v;
     подставь в ω=2π/t → v = λ·f (волновое уравнение). Времени нет — есть
     пространство λ и скорость v. В c=1: время = длина. ✓

  2. МАССА = ВИБРАЦИЯ. m = ℏω/c²  (ω — частота Циттербевегунга, де Бройль).
     Электрон: ω = m_e c²/ℏ ≈ 7.76·10²⁰ рад/с. Тяжелее = выше частота (ω∝m);
     «лёгкая/тяжёлая — относительно» (высокая частота → большая масса). ✓

  3. ЕДИНАЯ ФОРМУЛА, к которой всё сходится:  a·ω = c.
     Длина × частота = скорость света. Масса спрятана внутри (a=ℏ/mc, ω=mc²/ℏ).
     В ОДНОМ отношении: E=mc², де Бройль, волна v=λf. Время ушло в пару (a,ω). ✓

  4. НУЛЕВАЯ ЧАСТОТА ВАКУУМА. ½ℏω на моду даже при T=0 — нулевые колебания
     (реальны: эффект Казимира). «Пустая точка, но в ней идея» = основное
     состояние поля: нет вещей, есть структура. [Q3 интерпретация]

Запуск:  python -m qmt.vibration
"""

from __future__ import annotations

import math

C = 2.99792458e8
HBAR = 1.054571817e-34
M_E = 9.1093837015e-31


# ── 1. Время как отношение (замена t → x/v) ──────────────────────────────────
def wave_relation(wavelength: float, velocity: float) -> float:
    """t=λ/v подставлено в ω=2π/t даёт v=λ·f. Возвращает частоту f=v/λ.

    Время исчезло — остались пространство (λ) и скорость (v)."""
    return velocity / wavelength


def time_is_space_over_velocity(x: float, v: float) -> float:
    """t = x/v — время есть отношение пространство:скорость (не вещь)."""
    return x / v


# ── 2. Масса как вибрация (частота) ──────────────────────────────────────────
def compton_frequency(mass: float = M_E) -> float:
    """Частота, отвечающая массе: ω = m·c²/ℏ (Циттербевегунг / де Бройль)."""
    return mass * C**2 / HBAR


def mass_from_frequency(omega: float) -> float:
    """Обратно: m = ℏω/c². Масса — это частота вибрации."""
    return HBAR * omega / C**2


def heavier_is_higher_frequency() -> bool:
    """Тяжелее = выше частота: ω(2m) = 2·ω(m)."""
    return math.isclose(compton_frequency(2 * M_E), 2 * compton_frequency(M_E), rel_tol=1e-12)


# ── 3. Единая формула a·ω = c ────────────────────────────────────────────────
def unified_a_omega_c(mass: float = M_E) -> dict:
    """a·ω = c, где a=ℏ/(mc) (длина), ω=mc²/ℏ (частота). Масса внутри."""
    a = HBAR / (mass * C)
    omega = mass * C**2 / HBAR
    return {"a (длина)": a, "ω (частота)": omega, "a·ω": a * omega, "c": C}


# ── 4. Нулевые колебания вакуума ─────────────────────────────────────────────
def zero_point_energy(omega: float) -> float:
    """Энергия нулевых колебаний моды: E₀ = ½ℏω (есть даже при T=0)."""
    return 0.5 * HBAR * omega


def print_report() -> None:
    print("═" * 74)
    print("  ВИБРАЦИЯ: масса = частота, время = отношение (всё есть колебание)")
    print("═" * 74)

    print("\n  1 · ВРЕМЯ = ОТНОШЕНИЕ (замени t на x/v):")
    print(f"     период t=λ/v → ω=2π/t даёт  v = λ·f  (волна). f(λ=1м,v=c)={wave_relation(1.0,C):.3e} Гц")
    print(f"     t = x/v — время есть пространство:скорость, не вещь (в c=1: время=длина)")

    print("\n  2 · МАССА = ВИБРАЦИЯ (m = ℏω/c²):")
    w = compton_frequency()
    print(f"     электрон: ω = m_e c²/ℏ = {w:.4e} рад/с (Циттербевегунг)")
    print(f"     обратно m = ℏω/c² = {mass_from_frequency(w):.4e} кг = m_e ✓")
    print(f"     тяжелее = выше частота (ω∝m): {heavier_is_higher_frequency()}")

    print("\n  3 · ЕДИНАЯ ФОРМУЛА a·ω = c:")
    u = unified_a_omega_c()
    print(f"     a={u['a (длина)']:.3e} м · ω={u['ω (частота)']:.3e} рад/с → a·ω={u['a·ω']:.4e} = c ✓")
    print(f"     длина × частота = скорость. E=mc², де Бройль, v=λf — одно отношение.")

    print("\n  4 · НУЛЕВАЯ ЧАСТОТА ВАКУУМА:")
    print(f"     E₀=½ℏω на моду (T=0): для ω={w:.2e} → E₀={zero_point_energy(w):.3e} Дж")
    print(f"     реально: эффект Казимира. «Пустая точка с идеей» = основное состояние поля [Q3]")

    print("═" * 74)
    print("  Всё — отношение/вибрация: время=x/v, масса=ℏω/c², и a·ω=c в основе.")
    print("  Проверяемо (✓); «идея в пустоте» — интерпретация (Q3), не подаём как факт.")
    print("═" * 74)


if __name__ == "__main__":
    print_report()
