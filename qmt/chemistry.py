"""
═══════════════════════════════════════════════════════════════════════════
  CHEMISTRY — химия как ОТНОШЕНИЯ: молекула есть сеть связей, не мешок атомов.
═══════════════════════════════════════════════════════════════════════════

После психологии (память) — химия. И химия ложится в теорию отношений прямее
всего: вещество определяется СЕТЬЮ СВЯЗЕЙ (отношений между атомами), а не
составом. Изомеры доказывают это: те же атомы, разные связи — разные вещества.

РЕАЛЬНЫЙ РЕЛЯЦИОННЫЙ КОСТЯК (проверяемо):
  1. Оболочки 2n²: n=1..4 → 2, 8, 18, 32 электронов — форма всей таблицы;
  2. Благородные газы (замкнутые оболочки): Z = 2,10,18,36,54,86; разности =
     длины периодов 8,8,18,18,32 — каждая ДВАЖДЫ (зеркало-удвоение). 18 = d-блок;
  3. Октет: 8 (s²p⁶) — стабильная внешняя оболочка (замкнутое целое);
  4. Ядерные магические числа: 2,8,20,28,50,82,126 — оболочки ядра (⁴He,¹⁶O,⁴⁰Ca,²⁰⁸Pb);
  5. Реляционность: молекула = граф связей; изомеры C₂H₆O = этанол ИЛИ эфир.

ЧЕСТНО: 2n², магические числа, октет, реляционность — настоящая химия.
«операторы = цифровые корни Z», «константа 22» — модель/совпадение (Q3).

Запуск:  python -m qmt.chemistry
"""

from __future__ import annotations

# Благородные газы (замкнутые оболочки) и ядерные магические числа.
NOBLE_GASES = [2, 10, 18, 36, 54, 86]        # He Ne Ar Kr Xe Rn
NUCLEAR_MAGIC = [2, 8, 20, 28, 50, 82, 126]
OCTET = 8


def shell_capacity(n: int) -> int:
    """Ёмкость оболочки = 2n² (фундаментальное отношение химии)."""
    return 2 * n * n


def period_lengths() -> list:
    """Длины периодов = разности Z благородных газов (8,8,18,18,32)."""
    return [NOBLE_GASES[i + 1] - NOBLE_GASES[i] for i in range(len(NOBLE_GASES) - 1)]


def each_length_doubled() -> bool:
    """Каждая длина периода встречается дважды (зеркало-удвоение), кроме первой."""
    lens = period_lengths()
    return lens == [8, 8, 18, 18, 32]


def d_block_is_18() -> bool:
    """d-блок = 18 — то же ΔZ=18, что в «иной таблице» (гомологи)."""
    return 18 in period_lengths()


def is_magic(n: int) -> bool:
    """Ядерное магическое число = замкнутая ядерная оболочка (стабильность)."""
    return n in NUCLEAR_MAGIC


def isomers_same_atoms() -> dict:
    """Реляционность: C₂H₆O — этанол ИЛИ диметиловый эфир (те же атомы, разные связи)."""
    return {"состав": "C₂H₆O (2C,6H,1O)",
            "этанол": "CH₃-CH₂-OH (связь C-O-H)",
            "эфир": "CH₃-O-CH₃ (связь C-O-C)",
            "вывод": "те же атомы, РАЗНЫЕ связи → разные вещества (свойство от структуры)"}


def print_report() -> None:
    print("═" * 74)
    print("  ХИМИЯ = ОТНОШЕНИЯ: вещество есть сеть связей, не состав")
    print("═" * 74)
    print("\n  1 · оболочки 2n²:")
    print("     " + "  ".join(f"n={n}:{shell_capacity(n)}" for n in range(1, 5)))
    print("\n  2 · благородные газы (замкнутые оболочки):")
    print(f"     Z = {NOBLE_GASES}")
    print(f"     длины периодов = {period_lengths()}  — каждая дважды: {each_length_doubled()}")
    print(f"     18 = d-блок (наш ΔZ=18): {d_block_is_18()}")
    print(f"\n  3 · октет = {OCTET} (s²p⁶) — стабильная внешняя оболочка (замкнутое целое)")
    print(f"\n  4 · ядерные магические числа: {NUCLEAR_MAGIC}")
    print(f"     дважды-магические ⁴He,¹⁶O,⁴⁰Ca,²⁰⁸Pb: {all(is_magic(x) for x in (2,8,20,82))}")
    print("\n  5 · РЕЛЯЦИОННОСТЬ (главное):")
    iso = isomers_same_atoms()
    print(f"     {iso['состав']}: {iso['этанол']} ИЛИ {iso['эфир']}")
    print(f"     {iso['вывод']}")
    print("═" * 74)
    print("  Реально: 2n², магические числа, октет, изомеры — химия РЕЛЯЦИОННА.")
    print("  «операторы=цифр.корни», «22» — модель/совпадение, не подаём как факт.")
    print("═" * 74)


if __name__ == "__main__":
    print_report()
