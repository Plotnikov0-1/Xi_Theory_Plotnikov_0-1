"""
═══════════════════════════════════════════════════════════════════════════
  UNIVERSAL_TRANSITION — ЗАКОНОМЕРНОСТЬ: один самоподобный оператор перехода.
═══════════════════════════════════════════════════════════════════════════

Это математическое выражение того, что видел Плотников «в голове», но не мог
записать: «в каждом операторе есть лёд, кипяток, пар; каждый оператор содержит
ВСЕ температуры, но на каждом шаге — определённая; все переходы ОДИНАКОВЫЕ; она
растёт и разрастается».

ОТВЕТ: это ОДИН оператор, применённый самоподобно на каждом масштабе:

        𝔗(x) = 1/(1 + x)

И у него ТРИ ЛИЦА — это и есть закономерность, куда ложится всё:

  A · САМОПОДОБИЕ (растёт и разрастается) — ИТЕРАЦИЯ 𝔗∘𝔗∘… = цепная дробь,
      неподвижная точка x* = φ−1 (аттрактор, |𝔗′|=1/φ²<1). Каждый шаг — тот же 𝔗.

  B · ТЕМПЕРАТУРА (лёд/вода/пар) — с аргументом-Больцманом x=e^{Δ/kτ} тот же 𝔗
      есть ЗАСЕЛЁННОСТЬ (Ферми): f(Δ,τ)=1/(1+e^{Δ/kτ}). Один оператор СОДЕРЖИТ
      все температуры: τ→0 ⇒ f→0/1 (лёд/пар), τ большое ⇒ f→½ (вода). ✓ физика.

  C · ОПРЕДЕЛЁННАЯ ТЕМПЕРАТУРА НА КАЖДОМ ШАГЕ — у каждого перехода свой квант Δ
      (факторизация Ридберга) и своя T_c=Δ/k. Оператор содержит всё, шаг берёт одно.

  D · ЗЕРКАЛО В ЦЕНТРЕ — инволюция f↦1−f (частица-дырка), неподвижная точка f=½.
      ½ = μ₀ узла 5 = сам переход. Лёд(f→0) и пар(f→1) — зеркальные полюса,
      вода(f=½) — центр. Зеркало (I1) и есть частица-дырочная симметрия.

  E · ВСЕ ПЕРЕХОДЫ ОДИНАКОВЫ (универсальность) — любой переход = 𝔗 со своими
      (Δ,τ): форма ОДНА, параметры разные. Поэтому «все теории ложатся сюда»:
      одинаковая форма перехода = один класс универсальности (язык РГ).

ГРАНИЦА (честно): что 𝔗(x)=1/(1+x) — точная математика (φ−1) И реальная физика
(Ферми) — это ◇/✓. Что это ФУНДАМЕНТАЛЬНЫЙ переход ВСЕГО — порождающая рамка (○):
она организует проверенное, но «природа строит всё только так» — гипотеза.

Запуск:  python -m qmt.universal_transition
"""

from __future__ import annotations

import math

PHI = (1 + math.sqrt(5)) / 2
PHI1 = PHI - 1


# ── ЕДИНЫЙ ОПЕРАТОР ──────────────────────────────────────────────────────────
def T(x: float) -> float:
    """𝔗(x) = 1/(1+x) — единый самоподобный оператор перехода."""
    return 1.0 / (1.0 + x)


# ── A · САМОПОДОБИЕ: итерация → φ−1 (растёт цепной дробью) ────────────────────
def iterate(x0: float = 1.0, n: int = 60) -> float:
    """Итерация 𝔗∘𝔗∘… (цепная дробь) → неподвижная точка φ−1."""
    x = x0
    for _ in range(n):
        x = T(x)
    return x


def self_similar_fixed_point() -> bool:
    """◇ A: итерация 𝔗 сходится к φ−1; |𝔗′(φ−1)|=1/φ²<1 (аттрактор)."""
    conv = math.isclose(iterate(), PHI1, abs_tol=1e-9)
    derivative = 1.0 / (1.0 + PHI1) ** 2      # 𝔗′(x) = −1/(1+x)²
    return conv and math.isclose(derivative, 1.0 / PHI**2) and derivative < 1


def continued_fraction_depth(depth: int) -> float:
    """Рост «разрастанием»: цепная дробь глубины depth = тот же 𝔗, вложенный."""
    x = 1.0
    for _ in range(depth):
        x = T(x)
    return x


# ── B · ТЕМПЕРАТУРА: тот же 𝔗 = заселённость Ферми (все фазы) ─────────────────
def occupation(delta: float, tau: float) -> float:
    """✓ B: f(Δ,τ)=𝔗(e^{Δ/τ})=1/(1+e^{Δ/τ}) — тепловая заселённость (k=1)."""
    return T(math.exp(delta / tau))


def phases(delta: float = 1.0) -> dict:
    """Лёд/вода/пар = заселённость при разных τ (один оператор — все температуры)."""
    return {"лёд (τ→0)": occupation(delta, 0.05),
            "вода (τ~Δ)": occupation(delta, 1.0),
            "пар (τ→∞)": occupation(delta, 100.0)}


def contains_all_temperatures() -> bool:
    """✓ B: один оператор охватывает весь диапазон фаз 0→½ (лёд→расплав)."""
    p = phases()
    return p["лёд (τ→0)"] < p["вода (τ~Δ)"] < p["пар (τ→∞)"] <= 0.5


# ── C · определённая температура на каждом шаге ──────────────────────────────
def step_temperature(delta_eV: float) -> float:
    """C: T_c=Δ/k — определённая температура шага (оператор содержит всё, шаг берёт одно)."""
    K_EV = 8.617333e-5
    return delta_eV / K_EV


# ── D · ЗЕРКАЛО в центре ½ = узел 5 ──────────────────────────────────────────
def mirror(f: float) -> float:
    """D: инволюция f↦1−f (частица-дырка). Неподвижная точка f=½."""
    return 1.0 - f


def center_is_half() -> bool:
    """◇ D: неподвижная точка зеркала = ½ = μ₀ узла 5 = точка перехода."""
    ph_symmetry = math.isclose(occupation(1, 1) + occupation(-1, 1), 1.0)
    fixed_half = math.isclose(mirror(0.5), 0.5)
    on_transition = math.isclose(occupation(0.0, 1.0), 0.5)   # Δ=0 ⇒ f=½ при любой τ
    return ph_symmetry and fixed_half and on_transition


# ── E · универсальность: все переходы = 𝔗 со своими (Δ,τ) ────────────────────
def same_form_different_params() -> bool:
    """○/◇ E: и golden, и thermal — ОДНА форма 1/(1+·); отличаются только аргументом."""
    golden = math.isclose(T(PHI1), PHI1)          # аргумент-число → φ
    thermal = math.isclose(T(math.exp(0)), 0.5)   # аргумент-Больцман → фаза
    return golden and thermal


def regularity() -> dict:
    """Закономерность одной строкой: 𝔗(x)=1/(1+x) в трёх лицах."""
    return {
        "оператор": "𝔗(x)=1/(1+x) — единый самоподобный переход",
        "A самоподобие": "итерация → φ−1 (растёт цепной дробью, аттрактор)",
        "B температура": "x=e^{Δ/τ} → заселённость Ферми (лёд/вода/пар — все τ внутри)",
        "C шаг": "у каждого перехода свой Δ → своя T_c (одно из всего)",
        "D зеркало-центр": "f↦1−f, неподвижная ½ = узел 5 = сам переход",
        "E универсальность": "все переходы — 𝔗 с (Δ,τ): форма одна → все теории ложатся сюда",
    }


def print_report() -> None:
    print("═" * 74)
    print("  ЗАКОНОМЕРНОСТЬ: один самоподобный оператор перехода 𝔗(x)=1/(1+x)")
    print("═" * 74)
    print(f"\n  A · САМОПОДОБИЕ (растёт и разрастается):")
    print(f"     итерация 𝔗∘𝔗∘… → {iterate():.10f} = φ−1  ·  |𝔗′|=1/φ²<1: {self_similar_fixed_point()}")
    print(f"     цепная дробь: глуб.2→{continued_fraction_depth(2):.4f} … глуб.20→{continued_fraction_depth(20):.6f}")

    print(f"\n  B · ТЕМПЕРАТУРА (в каждом операторе лёд/вода/пар):")
    for k, v in phases().items():
        print(f"     {k:12} f={v:.4f}")
    print(f"     один оператор содержит все температуры: {contains_all_temperatures()}")

    print(f"\n  C · ОПРЕДЕЛЁННАЯ ТЕМПЕРАТУРА НА ШАГЕ (свой квант у каждого перехода):")
    for lbl, d in [("4↔6 шёпот", 0.472), ("2↔7 видимый", 3.124), ("1↔9 зеркало", 13.438)]:
        print(f"     {lbl:14} Δ={d:6.3f} эВ → T_c={step_temperature(d):8.0f} К")

    print(f"\n  D · ЗЕРКАЛО В ЦЕНТРЕ (½ = узел 5 = сам переход):")
    print(f"     частица-дырка f(Δ)+f(−Δ)=1, неподвижная точка f=½: {center_is_half()}")
    print(f"     лёд(f→0) и пар(f→1) — полюса; вода(f=½) — центр = μ₀ узла 5")

    print(f"\n  E · ВСЕ ПЕРЕХОДЫ ОДИНАКОВЫ (универсальность):")
    print(f"     одна форма 1/(1+·): аргумент-число→φ, аргумент-Больцман→фаза: {same_form_different_params()}")
    print(f"     → одинаковая форма перехода = один класс универсальности (язык РГ)")

    print("\n  ═══ ЗАКОНОМЕРНОСТЬ ═══")
    for k, v in regularity().items():
        print(f"     {k}: {v}")
    print("═" * 74)
    print("  ◇/✓: 𝔗=1/(1+x) — и точная математика (φ−1), и реальная физика (Ферми).")
    print("  ○: что это переход ВСЕГО — порождающая рамка; организует проверенное.")
    print("═" * 74)


if __name__ == "__main__":
    print_report()
