"""
═══════════════════════════════════════════════════════════════════════════
  CANON_CONSTANTS — строгий вывод/разрешение «красных винтов» C_eff (β, N, ε_X).
═══════════════════════════════════════════════════════════════════════════

Задача: не выдумать вывод, а СТРОГО показать, что из C_eff = C + α·uuᵀ + β·vvᵀ
(u=(1,1,1,1,1,1), v=(1,1,1,−1,−1,−1)) выводится, а что нет. Держим контекст:
C = circ(3/2,1/2,0,0,0,1/2), u⊥v (uᵀv=0), u — собственный вектор C (λ=5/2).

РЕЗУЛЬТАТ (символьно проверено):

  ◇ α УПРАВЛЯЕТ КОЛЛЕКТИВНОЙ МОДОЙ ТОЧНО:
      λ_u = 5/2 + 6α  (u собств. C, vᵀu=0 ⇒ v·vᵀ не трогает u).
      α=9/5 ⇒ λ_u = 13.3 (та самая «коллективная мода»). α — ассигнация 9/5
      («9 узлов / 5 центр»), с рационале; управляет ровно одной точной модой.

  ◇ β СВОБОДЕН (доказано, не подгонка нашего вывода):
      v НЕ собственный вектор C ⇒ v-направление смешивается; две моды =
          3β + 5/4 ± √(144β²+56β+9)/4.
      При β=12/5=2.4: моды 0.652 и 16.248 — НИ рациональны, НИ структурны;
      √(144β²+56β+9)=11√201/5 — иррационально. Скан рациональных β не дал
      рационального спектра (кроме β=0). ⇒ β=2.4 не выделено НИЧЕМ.
      Минимальная честная форма: β=(4/3)α=12/5 — сводит свободу к числу 4/3.

  ◇ N — ЭТО ЧИСЛО МОД, НЕ ЗНАКОВ:
      N=6 = размерность (потолок Нивена, см. proof_core). «6 знаков хвоста φ⁻³»
      мат.смысла НЕ имеет: φ⁻³=√5−2 иррационально (бесконечная непериод. дробь),
      «6 знаков» — произвольная обрезка. Разрешено в пользу «6 мод».

  ★ ε_X ≈ e — ДАЖЕ НЕ e: цитируется 2.721, а e=2.71828. Отличие в 3-м знаке ⇒
      это ≈-совпадение, не тождество. Остаётся гипотезой до вывода X-закона.

ВЫВОД: ядро C_eff держится на ДВУХ структурных ассигнациях (α=9/5, и ратио
β/α=4/3). α честно управляет модой 13.3; β в текущей конструкции не выводится —
это единственный свободный винт, и он изолирован до одного числа 4/3.

Запуск:  python -m qmt.canon_constants
"""

from __future__ import annotations

import math

PHI = (1 + math.sqrt(5)) / 2


# ── α: коллективная мода точна ───────────────────────────────────────────────
def collective_mode(alpha: float) -> float:
    """◇ λ_u = 5/2 + 6α (ТОЧНО: u собств. C, vᵀu=0). α=9/5 ⇒ 13.3."""
    return 2.5 + 6 * alpha


def alpha_controls_mode_exactly() -> bool:
    """◇ α=9/5 даёт ровно коллективную моду 13.3."""
    return math.isclose(collective_mode(9 / 5), 13.3)


# ── β: две смешанные моды, свобода ───────────────────────────────────────────
def v_mode_eigenvalues(beta: float) -> tuple:
    """v-направление (v не собств. C): 3β + 5/4 ± √(144β²+56β+9)/4."""
    root = math.sqrt(144 * beta**2 + 56 * beta + 9) / 4
    base = 3 * beta + 5 / 4
    return (base - root, base + root)


def beta_spectrum_rational(beta_num: int, beta_den: int) -> bool:
    """◇ Рационален ли v-спектр: нужен точный квадрат у 144β²+56β+9."""
    from fractions import Fraction
    b = Fraction(beta_num, beta_den)
    disc = 144 * b * b + 56 * b + 9      # Fraction
    num, den = disc.numerator, disc.denominator
    r_num = math.isqrt(num)
    r_den = math.isqrt(den)
    return r_num * r_num == num and r_den * r_den == den


def beta_is_free() -> bool:
    """◇ β=12/5 не даёт рационального/структурного спектра → свободен."""
    lo, hi = v_mode_eigenvalues(12 / 5)
    not_rational = not beta_spectrum_rational(12, 5)
    # ни одна мода не совпадает с узловым числом 1..13 (структурности нет)
    not_structural = all(not math.isclose(x, n, abs_tol=1e-9)
                         for x in (lo, hi) for n in range(1, 14))
    return not_rational and not_structural


def beta_over_alpha() -> float:
    """Минимальная честная форма: β/α = 4/3 (единственный необъяснённый винт)."""
    return (12 / 5) / (9 / 5)


def scan_rational_beta(max_num: int = 60) -> list:
    """◇ Скан: какие рациональные β (num≤max_num, den≤5) дают рацион. спектр."""
    found = []
    for num in range(1, max_num):
        for den in (1, 2, 3, 4, 5):
            if beta_spectrum_rational(num, den):
                found.append((num, den))
    return found          # ожидаем только тривиальные (β=0 исключён)


# ── N: моды, не знаки ────────────────────────────────────────────────────────
def phi_inv3_is_irrational() -> bool:
    """◇ φ⁻³=√5−2 иррационально ⇒ «6 знаков хвоста» — произвольная обрезка."""
    # √5 иррационально ⇒ √5−2 иррационально (рациональный сдвиг)
    return not (5 ** 0.5).is_integer()


def N_meaning() -> dict:
    """◇ N=6 = ЧИСЛО МОД (размерность, потолок Нивена); «6 знаков» отвергнуто."""
    return {"N=6 мод (размерность)": True,
            "φ⁻³ иррационально": phi_inv3_is_irrational(),
            "«6 знаков» имеет смысл": False,
            "разрешение": "N = 6 мод (доказано), не 6 знаков"}


# ── ε_X: даже не e ───────────────────────────────────────────────────────────
def eps_X_is_not_e() -> dict:
    """★ Цитируемое ε_X=2.721 ≠ e=2.71828 (3-й знак) ⇒ ≈-совпадение, не тождество."""
    quoted, e = 2.721, math.e
    return {"ε_X цитата": quoted, "e": round(e, 5),
            "|разница|": round(abs(quoted - e), 5),
            "это e?": math.isclose(quoted, e, abs_tol=1e-4),
            "вердикт": "≈-совпадение, гипотеза до вывода X-закона"}


def verdicts() -> dict:
    """Строгий вердикт по каждому красному винту."""
    return {
        "N": "РЕШЕНО: 6 мод (потолок Нивена). «6 знаков» отвергнуто (φ⁻³ иррац.).",
        "α=9/5": "ассигнация (9/5); управляет модой λ_u=13.3 ТОЧНО.",
        "β=12/5": "СВОБОДЕН: 2.4 не рационален/не структурен. Форма β=(4/3)α.",
        "ε_X≈e": "даже не e (2.721≠2.71828); гипотеза до X-закона.",
    }


def print_report() -> None:
    print("═" * 74)
    print("  СТРОГИЙ ВЫВОД КРАСНЫХ ВИНТОВ C_eff: α точна, β свободен, N=моды")
    print("═" * 74)
    print(f"\n  ◇ α: λ_u=5/2+6α — ТОЧНО (u собств., vᵀu=0)")
    print(f"     α=9/5 → λ_u = {collective_mode(9/5)} (коллективная мода): {alpha_controls_mode_exactly()}")

    lo, hi = v_mode_eigenvalues(12 / 5)
    print(f"\n  ◇ β: v-моды = 3β+5/4±√(144β²+56β+9)/4")
    print(f"     β=12/5 → {lo:.3f} и {hi:.3f} (ни рацион., ни структурны)")
    print(f"     рацион. спектр у β (скан num<60): {scan_rational_beta() or '— нет —'}")
    print(f"     β СВОБОДЕН: {beta_is_free()}   минимальная форма β/α = {beta_over_alpha():.4f} = 4/3")

    print(f"\n  ◇ N: {N_meaning()['разрешение']}")
    print(f"     φ⁻³=√5−2 иррационально (∞ знаков): {phi_inv3_is_irrational()}")

    ex = eps_X_is_not_e()
    print(f"\n  ★ ε_X: цитата {ex['ε_X цитата']} vs e={ex['e']} (|Δ|={ex['|разница|']}) → {ex['вердикт']}")

    print("\n  ═══ ВЕРДИКТЫ ═══")
    for k, v in verdicts().items():
        print(f"     {k}: {v}")
    print("═" * 74)
    print("  Ядро держится на ДВУХ ассигнациях: α=9/5 (точно даёт 13.3) и β/α=4/3.")
    print("  β — единственный свободный винт, изолирован до числа 4/3. Честно, строго.")
    print("═" * 74)


if __name__ == "__main__":
    print_report()
