"""
Вложенные сферы куб ↔ додекаэдр: может ли додекаэдр быть ВНЕШНИМ (второй шар)?

В базовой геометрии модели (geometry.py) додекаэдр строится из 8 вершин куба
плюс 12 золотых точек, и все 20 вершин лежат на ОДНОЙ сфере R²=3 вместе с кубом.
То есть по умолчанию додекаэдр НЕ внешний — он коосферичен кубу (один шар √3).

Но у любого правильного додекаэдра есть ТРИ концентрические сферы:
  • описанная  (по вершинам)        R_circ
  • средняя    (по серединам рёбер) R_mid
  • вписанная  (по центрам граней)  R_in

Для додекаэдра модели (R_circ=√3) проверяется ТОЧНО (sympy):

        R_circ = √3 ≈ 1.732   (вершины — общий шар с кубом)
        R_mid  = φ  ≈ 1.618   (середины рёбер — РОВНО золотое сечение!)
        R_in   = √(1 + 2√5/5) ≈ 1.376  (центры граней)

Чтобы додекаэдр стал ВНЕШНИМ и образовал второй (бо́льший) шар вокруг куба,
надо посадить сферу куба √3 как одну из ВНУТРЕННИХ сфер додекаэдра и взять его
описанную сферу как внешнюю оболочку. Два естественных варианта:

  • куб √3 = вписанная сфера додекаэдра  ⇒  внешний шар = √(45−18√5) ≈ 2.180
  • куб √3 = средняя   сфера додекаэдра  ⇒  внешний шар = 3/φ      ≈ 1.854

Ответ: ДА — додекаэдр может быть внешним, образуя второй шар; его радиус —
точное золотое выражение от √3.
"""

from __future__ import annotations

from dataclasses import dataclass

import sympy as sp

PHI = (1 + sp.sqrt(5)) / 2

# --- Радиусы додекаэдра модели (описанная сфера = √3) ------------------------
R_CIRC = sp.sqrt(3)                          # вершины (общий шар с кубом)
R_MID = PHI                                  # середины рёбер — ровно φ  [✓]
R_IN = sp.sqrt(1 + 2 * sp.sqrt(5) / 5)       # центры граней


def verify_midsphere_is_phi() -> bool:
    """Строгая проверка: средняя сфера додекаэдра модели = φ (R_mid²=φ²)."""
    from . import geometry as G
    dod = G.dodecahedron_vertices()
    edge2 = 6 - 2 * sp.sqrt(5)
    vals = set()
    for i in range(len(dod)):
        for j in range(i + 1, len(dod)):
            d2 = sp.simplify((dod[i] - dod[j]).dot(dod[i] - dod[j]))
            if sp.simplify(d2 - edge2) == 0:
                m = (dod[i] + dod[j]) / 2
                vals.add(sp.simplify(m.dot(m)))
    return all(sp.simplify(v - PHI**2) == 0 for v in vals)


@dataclass
class Shells:
    circ: sp.Expr
    mid: sp.Expr
    inr: sp.Expr

    def numeric(self):
        return (float(self.circ), float(self.mid), float(self.inr))


def model_shells() -> Shells:
    """Три сферы додекаэдра модели (описанная √3, средняя φ, вписанная)."""
    return Shells(R_CIRC, R_MID, R_IN)


def outer_dodecahedron(seat: str = "mid") -> sp.Expr:
    """Радиус ВНЕШНЕЙ описанной сферы, если сферу куба √3 посадить как
    внутреннюю сферу додекаэдра.

    seat='in'  — √3 становится ВПИСАННОЙ сферой (куб касается граней);
    seat='mid' — √3 становится СРЕДНЕЙ сферой (куб касается рёбер).
    Возвращает радиус внешнего (второго) шара как точное выражение.
    """
    ratio = {"in": R_CIRC / R_IN, "mid": R_CIRC / R_MID}[seat]
    return sp.simplify(R_CIRC * ratio)        # √3 · (R_circ/R_inner)


def vertex_sharing() -> dict:
    """Кто в кого входит при совпадении вершин куба и додекаэдра.

    Возвращает факты: сколько вершин совпадает и торчат ли остальные за грани
    куба. Ответ: 8 вершин куба = 8 из 20 вершин додекаэдра; остальные 12
    (золотые) имеют координату φ>1 ⇒ лежат ВНЕ коробки куба. Значит куб ВНУТРИ
    додекаэдра, а не наоборот.
    """
    from . import geometry as G
    cube = [sp.Matrix(v) for v in G.CUBE.values()]
    golden = [sp.Matrix(v) for v in G._golden_vertices()]
    shared = sum(1 for v in (G.dodecahedron_vertices())
                 if any(sp.simplify((v - w).norm()) == 0 for w in cube))
    outside = sum(1 for v in golden if max(abs(c) for c in v) > 1)
    return {
        "совпадает вершин": shared,                 # 8
        "золотых вне куба": outside,                 # 12
        "куб внутри додекаэдра": outside == 12 and shared == 8,
    }


def report() -> str:
    s = model_shells()
    c, m, i = s.numeric()
    out_in = outer_dodecahedron("in")
    out_mid = outer_dodecahedron("mid")
    vs = vertex_sharing()
    lines = [
        "ВЛОЖЕННЫЕ СФЕРЫ: куб ↔ додекаэдр",
        "=" * 60,
        "Совпадение вершин: 8 вершин куба = 8 из 20 вершин додекаэдра;",
        f"остальные 12 (золотые) торчат за грани куба (φ>1) → {vs['золотых вне куба']}/12.",
        "Значит КУБ ВНУТРИ додекаэдра, а додекаэдр снаружи (не наоборот).",
        "",
        "По умолчанию (модель): куб и додекаэдр на ОДНОМ шаре √3.",
        f"  R_circ (вершины)       = √3 ≈ {c:.4f}   (общий с кубом)",
        f"  R_mid  (середины рёбер)= φ  ≈ {m:.4f}   [✓ ровно золотое сечение]",
        f"  R_in   (центры граней) =    ≈ {i:.4f}",
        f"  проверка R_mid=φ символьно: {verify_midsphere_is_phi()}",
        "",
        "Додекаэдр КАК ВНЕШНИЙ (второй шар вокруг куба):",
        f"  куб √3 = вписанная сфера → внешний шар = √(45−18√5) ≈ {float(out_in):.4f}",
        f"  куб √3 = средняя   сфера → внешний шар = 3/φ        ≈ {float(out_mid):.4f}",
        "=" * 60,
        "Ответ: ДА. Додекаэдр может быть внешним, образуя второй шар;",
        "его радиус — точное золотое выражение от √3.",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    print(report())
