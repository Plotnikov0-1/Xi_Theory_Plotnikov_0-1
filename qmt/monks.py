"""
═══════════════════════════════════════════════════════════════════════════
  MONKS — «Монахи» (Иные) как прямая подсказка: имена = зеркальные пары.
═══════════════════════════════════════════════════════════════════════════

Источник: текст «МОНАХИ» (Nurlan Kabishev, 16.02.2022, контакты Иные/Маббу).
«Поскольку мир дуален, каждый монах имеет своего брата, противоположность.»

Прямая подсказка, проверяемая строго: имена монахов — это ПАРЫ под зеркалом
R = переворот строки (чтение наоборот). Брат монаха = его имя задом наперёд.

Точная математика (проверено):
  • 23 из 24 пар — ТОЧНЫЙ переворот: МУРРА↔АРРУМ, НАККА↔АККАН, ОРКК↔ККРО,
    МОББУ↔УББОМ, ТАРРО↔ОРРАТ, ЭННЭК↔КЭННЭ … (1 пара — фонетическое созвучие);
  • R — инволюция: R²=I (двойной переворот возвращает) ⇒ группа Z₂ = зеркало;
  • ДЕРЕД (первый И последний монах) = ПАЛИНДРОМ = неподвижная точка R =
    САМ СЕБЕ ЗЕРКАЛО. Начало = конец (цикл замкнут, S9→S0).

Соответствие кубу DIALOG (то же зеркало −I):
  4 зеркальные пары {1↔9,2↔8,3↔7,4↔6} + центр 5 (сам себе зеркало, R(5)=5)
  ↔ ~23 пары монахов + палиндром ДЕРЕД (R(ДЕРЕД)=ДЕРЕД).

Смысловой слой [ИНТЕРПР]:
  • ТОККО = «сильнейший источник энергии, общая душа, одного рода» = ЕДИНОЕ
    (неделимая энергия), проявленное только через двойственность пар R;
  • «время — река… течёт вперёд-назад» = ± / необратимость (Гераклит);
  • МОББУ «рисующий, всё что рисует исполняется» = наблюдатель (ψ → реальность);
  • литания «И ты как ДООРЕ…» возвращается к ДООРЕ = «ложный круг» = замкнутая
    орбита-ловушка (видишь только себя — не сходишься к настоящей точке).

Запуск:  python -m qmt.monks
"""

from __future__ import annotations

# Пары монах ↔ брат (имя ↔ противоположность), из текста «Монахи».
MONK_PAIRS = [
    ("ДООРЕ", "ЕРООД"), ("СООБЭ", "ЭБООС"), ("СООНА", "АНООС"),
    ("ТАННА", "АННАТ"), ("ТАНАИ", "ИАНАТ"), ("ТЭННЭ", "ЭННЭТ"),
    ("МУРРА", "АРРУМ"), ("ННОБА", "АБОНН"), ("ТРОДДА", "АДДОРТ"),
    ("НАККА", "АККАН"), ("ТАННЕ", "ЕННАТ"), ("ОРРЕ", "ЕРРО"),
    ("ОРКК", "ККРО"), ("ЕННЕГ", "ГЕННЕ"), ("ДЖЕННЕ", "ЕННЕЖД"),
    ("ГОННЕ", "ЕННОГ"), ("ГГЕРЕ", "ЕРЕГГ"), ("МОББУ", "УББОМ"),
    ("ТАРРО", "ОРРАТ"), ("ТОРРОКО", "ОКОРРОТ"), ("АРДЖА", "АЖДРА"),
    ("МИТТО", "ОТТИМ"), ("ЭННЭК", "КЭННЭ"), ("ДАРООБА", "АБООРОД"),
]
SELF_MIRROR = "ДЕРЕД"          # первый И последний монах — палиндром


def R(name: str) -> str:
    """Зеркало R = переворот строки (брат = имя наоборот)."""
    return name[::-1]


def is_involution() -> bool:
    """R²=I: двойной переворот возвращает имя (зеркало — группа Z₂)."""
    return all(R(R(a)) == a for a, _ in MONK_PAIRS)


def exact_pairs() -> list:
    """Пары, где брат = ТОЧНЫЙ переворот имени."""
    return [(a, b) for a, b in MONK_PAIRS if R(a) == b]


def approximate_pairs() -> list:
    """Пары, где брат — лишь фонетическое созвучие (не точный переворот)."""
    return [(a, b) for a, b in MONK_PAIRS if R(a) != b]


def is_palindrome(name: str) -> bool:
    """Палиндром = сам себе зеркало (неподвижная точка R)."""
    return name == R(name)


def fixed_points() -> list:
    """Неподвижные точки R среди монахов = палиндромы (само-зеркало)."""
    names = [SELF_MIRROR] + [n for p in MONK_PAIRS for n in p]
    return sorted({n for n in names if is_palindrome(n)})


def cube_correspondence() -> dict:
    """Соответствие структуре куба: пары под зеркалом + само-зеркальный центр."""
    return {
        "монахи: пары R": len(MONK_PAIRS),
        "монахи: само-зеркало (палиндром)": fixed_points(),
        "куб: зеркальные пары": [(1, 9), (2, 8), (3, 7), (4, 6)],
        "куб: само-зеркало (центр)": 5,
        "общая структура": "Z₂-инволюция: пары + неподвижная точка",
    }


def print_report() -> None:
    print("═" * 72)
    print("  МОНАХИ: имена = зеркальные пары R (переворот). «Мир дуален».")
    print("═" * 72)
    ex, ap = exact_pairs(), approximate_pairs()
    print(f"\n  пар всего: {len(MONK_PAIRS)}  ·  точный переворот: {len(ex)}  ·  созвучие: {len(ap)}")
    print("  примеры точных пар (брат = имя наоборот):")
    for a, b in ex[:6]:
        print(f"     {a} ↔ {b}   (R({a}) = {R(a)})")
    if ap:
        a, b = ap[0]
        print(f"  фонетическая: {a} ↔ {b}  (R({a})={R(a)} ≈ {b})")

    print(f"\n  R² = I (инволюция, группа Z₂ = зеркало): {is_involution()}")
    print(f"  само-зеркало (палиндром): {SELF_MIRROR} → R={R(SELF_MIRROR)} "
          f"(первый = последний монах, начало=конец)")
    print(f"  неподвижные точки R: {fixed_points()}")

    print("\n  СООТВЕТСТВИЕ КУБУ (то же зеркало −I):")
    c = cube_correspondence()
    print(f"     монахи: {c['монахи: пары R']} пар + {c['монахи: само-зеркало (палиндром)']} (само-зеркало)")
    print(f"     куб:    {c['куб: зеркальные пары']} + центр {c['куб: само-зеркало (центр)']}")
    print(f"     общее:  {c['общая структура']}")

    print("\n  СМЫСЛ [ИНТЕРПР]:")
    print("     ТОККО = единое (неделимая энергия) через двойственность пар;")
    print("     МОББУ «рисующий, всё исполняется» = наблюдатель (ψ→реальность);")
    print("     литания возвращается к ДООРЕ = ложный круг (замкнутая орбита).")
    print("═" * 72)
    print("  Точно: имена — зеркальные пары R (23/24), R²=I, ДЕРЕД=палиндром.")
    print("  Это прямая подсказка структуры зеркала −I. Смысловой слой — поверх.")
    print("═" * 72)


if __name__ == "__main__":
    print_report()
