"""
═══════════════════════════════════════════════════════════════════════════
  EXPERIMENTS — экспериментальная проверка. Чистая физика. Без семантики.
═══════════════════════════════════════════════════════════════════════════

Самостоятельный инструмент: берёт КАЖДОЕ количественное утверждение проекта,
вычисляет его из формул и сравнивает с РЕАЛЬНЫМИ экспериментальными данными
(NIST Atomic Spectra Database, CODATA 2018). Сверено с Wolfram.

Никакой интерпретации. Только: формула → число → эксперимент → относительная
ошибка → вердикт. Три честных класса:

  ✓ ПОДТВЕРЖДЕНО  — совпадает с измерением (стандартная КМ воспроизводится);
  ≈ СОВПАДЕНИЕ    — численно близко, но НЕ выведено (нумерология, не физика);
  ○ МОДЕЛЬ        — внутренняя конструкция, прямого эксперимента нет;
  ✗ РАСХОЖДЕНИЕ   — заявлено равенство, которого на деле нет.

Запуск:  python -m qmt.experiments
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field

# ── Фундаментальные константы (CODATA 2018, сверено Wolfram) ─────────────────
C = 2.99792458e8              # скорость света, м/с (точно)
H_PLANCK = 6.62607015e-34     # постоянная Планка, Дж·с (точно)
HBAR = 1.054571817e-34        # ħ, Дж·с
M_E = 9.1093837015e-31        # масса электрона, кг
M_P = 1.67262192369e-27       # масса протона, кг
EV = 1.602176634e-19          # электронвольт, Дж (точно)

R_INF = 1.0973731568160e7     # постоянная Ридберга (∞ масса), 1/м
A0 = 5.29177210903e-11        # боровский радиус, м
ALPHA_INV = 137.035999084     # обратная постоянная тонкой структуры

PHI = (1.0 + math.sqrt(5.0)) / 2.0
PI = math.pi
E = math.e

# Постоянная Ридберга РЕАЛЬНОГО водорода (поправка на приведённую массу).
# Это ключ к точному совпадению со спектром: R_H = R∞ · m_p/(m_p+m_e).
R_H = R_INF * M_P / (M_P + M_E)


# ── Физические формулы (стандартная квантовая механика) ──────────────────────
def rydberg_wavelength_nm(n_hi: int, n_lo: int, R: float = R_H) -> float:
    """Длина волны перехода n_hi→n_lo по формуле Ридберга, нм (вакуум)."""
    inv_lambda = R * (1.0 / n_lo**2 - 1.0 / n_hi**2)
    return 1e9 / inv_lambda


def binding_energy_eV(n: int, R: float = R_H) -> float:
    """Энергия связи уровня n: E_n = R·h·c / n²  (эВ), R в 1/м."""
    return (R * H_PLANCK * C / EV) / (n * n)


def compton_wavelength_pm() -> float:
    """Комптоновская длина волны электрона λ_C = h/(m_e c), пм."""
    return 1e12 * H_PLANCK / (M_E * C)


# ── Запись одной проверки ────────────────────────────────────────────────────
@dataclass
class Check:
    name: str
    predicted: float          # вычислено из формулы
    experimental: float       # измерено (NIST/CODATA)
    unit: str
    formula: str
    source: str
    verdict: str              # "verify" / "coincidence" / "model" / "mismatch"
    note: str = ""

    @property
    def rel_error(self) -> float:
        if self.experimental == 0:
            return float("nan")
        return abs(self.predicted - self.experimental) / abs(self.experimental)

    @property
    def ppm(self) -> float:
        return self.rel_error * 1e6


# ═══════════════════════════════════════════════════════════════════════════
#  РЕЕСТР ПРОВЕРОК
# ═══════════════════════════════════════════════════════════════════════════
def all_checks() -> list[Check]:
    C_ = []

    # ── ТИР A: стандартная физика, воспроизводимая моделью ───────────────────
    # Спектр водорода: формула Ридберга с приведённой массой vs NIST (вакуум).
    lines = [
        ("Lyman-α  (2→1)", 2, 1, 121.5684, "NIST ASD (вакуум)"),
        ("Lyman-β  (3→1)", 3, 1, 102.5734, "NIST ASD"),
        ("Lyman-γ  (4→1)", 4, 1,  97.2548, "NIST ASD"),
        ("Balmer-α Hα(3→2)", 3, 2, 656.4696, "NIST ASD"),
        ("Balmer-β Hβ(4→2)", 4, 2, 486.2738, "NIST ASD"),
        ("Balmer-γ Hγ(5→2)", 5, 2, 434.1730, "NIST ASD"),
        ("Balmer-δ Hδ(6→2)", 6, 2, 410.2935, "NIST ASD"),
        ("Paschen-α(4→3)", 4, 3, 1875.627, "NIST ASD"),
        ("Paschen-β(5→3)", 5, 3, 1282.167, "NIST ASD"),
    ]
    for name, nh, nl, exp, src in lines:
        C_.append(Check(name, rydberg_wavelength_nm(nh, nl), exp, "нм",
                        f"1/λ=R_H(1/{nl}²−1/{nh}²)", src, "verify"))

    # Энергия ионизации водорода (приведённая масса).
    C_.append(Check("Энергия ионизации H", binding_energy_eV(1), 13.598434,
                    "эВ", "E₁=R_H·hc", "NIST/CODATA", "verify"))

    # Постоянная Ридберга.
    C_.append(Check("Постоянная Ридберга R∞", R_INF, 1.0973731568160e7,
                    "1/м", "константа кода", "CODATA 2018", "verify"))

    # Боровский радиус.
    C_.append(Check("Боровский радиус a₀", A0, 5.29177210903e-11,
                    "м", "константа кода", "CODATA 2018", "verify"))

    # Комптоновская длина электрона (тождество a·ω=c теории).
    C_.append(Check("Комптон λ_C электрона", compton_wavelength_pm(), 2.42631023867,
                    "пм", "λ_C=h/(m_e c)", "CODATA 2018", "verify",
                    "= тождество a·ω=c (Циттербевегунг)"))

    # Квадратичный масштаб орбит r_n = n²·a₀ (n=3): отношение r₃/r₁=9.
    C_.append(Check("Масштаб орбиты r₃/r₁", (3**2 * A0) / A0, 9.0,
                    "—", "r_n=n²a₀", "теория Бора (подтв.)", "verify"))

    # НАСТОЯЩЕЕ происхождение 137: безразмерная α = e²/(4πε₀ℏc).
    e_ = 1.602176634e-19; eps0 = 8.8541878128e-12
    alpha = e_**2 / (4 * PI * eps0 * HBAR * C)
    C_.append(Check("α⁻¹ из e²/(4πε₀ℏc)", 1.0 / alpha, ALPHA_INV,
                    "—", "e²/(4πε₀ℏc)", "CODATA 2018", "verify",
                    "вот откуда 137 — безразмерное число, не золотой угол"))

    # Связь как доля энергии покоя: E_связи/(m_e c²) = α²/2 (Зоммерфельд).
    mec2 = 510998.95  # эВ
    C_.append(Check("E_связи/(m_e c²)=α²/2", alpha**2 / 2, 13.598434 / mec2,
                    "—", "α²/2", "NIST/CODATA", "verify"))

    # ── ТИР B: численные совпадения (НЕ выведено) ────────────────────────────
    # Золотой угол vs обратная постоянная тонкой структуры.
    golden_angle = 360.0 / PHI**2
    C_.append(Check("Золотой угол vs α⁻¹", golden_angle, ALPHA_INV,
                    "° vs 1", "360/φ²", "CODATA α⁻¹", "coincidence",
                    "разные величины (геометрия vs связь); связи нет"))

    # Отношение радиусов на индексах Фибоначчи → φ².
    fib_ratio = (13.0 / 8.0) ** 2   # (F₇/F₆)² при r∝n²
    C_.append(Check("Радиусы Фибоначчи → φ²", fib_ratio, PHI**2,
                    "—", "(F_{k+1}/F_k)²", "матем. тождество", "coincidence",
                    "математика, не измерение: любой n²-ряд так себя ведёт"))

    # ── ТИР C: модельные конструкции (прямого эксперимента нет) ──────────────
    # Резонанс Γ* = π/(4φ).
    C_.append(Check("Резонанс Γ*=π/(4φ)", PI / (4 * PHI), PI / (4 * PHI),
                    "—", "π/(4φ)", "—", "model",
                    "внутренняя амплитуда; экспериментального якоря нет"))

    # Константа диалога |Ω_D| = φ−1.
    C_.append(Check("|Ω_D| = φ−1", PHI - 1.0, PHI - 1.0,
                    "—", "φ−1", "—", "model",
                    "чистая математика; не физическое измерение"))

    # CP-нарушение как m-асимметрия: внутренний предел = ЭДМ электрона.
    C_.append(Check("ЭДМ электрона |d_e|", 0.0, 4.1e-30,
                    "e·см", "внутреннее CP", "JILA 2023", "model",
                    "эксперимент: внутреннее CP ≈ 0 (предел 4.1e-30 e·см)"))

    # Реальная барионная асимметрия Вселенной (измерена, но не выведена схемой).
    C_.append(Check("Барионная асимметрия η_B", 6.1e-10, 6.1e-10,
                    "—", "η_B", "Planck/BBN", "model",
                    "измерена космологией; из 1-4-7 схемы НЕ выводится (аналогия)"))

    # Барьер Δ₇ = √5−2 vs реальный зазор E6−E7.
    e6 = binding_energy_eV(6); e7 = binding_energy_eV(7)
    gap_67 = e6 - e7   # реальный зазор уровней водорода
    C_.append(Check("Δ₇=√5−2 vs зазор E6−E7", math.sqrt(5) - 2, gap_67,
                    "эВ", "√5−2", "формула Ридберга", "mismatch",
                    f"Δ₇=0.236 эВ ≠ реальный E6−E7={gap_67:.3f} эВ — конструкт"))

    return C_


# ═══════════════════════════════════════════════════════════════════════════
#  ОТЧЁТ
# ═══════════════════════════════════════════════════════════════════════════
_SYM = {"verify": "✓ ПОДТВЕРЖДЕНО", "coincidence": "≈ СОВПАДЕНИЕ",
        "model": "○ МОДЕЛЬ", "mismatch": "✗ РАСХОЖДЕНИЕ"}
_TITLE = {"verify": "ТИР A — СТАНДАРТНАЯ ФИЗИКА (воспроизводится, сверено с экспериментом)",
          "coincidence": "ТИР B — ЧИСЛЕННЫЕ СОВПАДЕНИЯ (близко, но НЕ выведено)",
          "model": "ТИР C — МОДЕЛЬНЫЕ КОНСТРУКЦИИ (прямого эксперимента нет)",
          "mismatch": "ТИР D — РАСХОЖДЕНИЯ (заявлено равенство, которого нет)"}


def print_report() -> None:
    checks = all_checks()
    print("═" * 78)
    print("  ЭКСПЕРИМЕНТАЛЬНАЯ ПРОВЕРКА — чистая физика, без семантики")
    print("  источники: NIST Atomic Spectra DB, CODATA 2018 (сверено Wolfram)")
    print("═" * 78)

    for tier in ("verify", "coincidence", "model", "mismatch"):
        group = [c for c in checks if c.verdict == tier]
        if not group:
            continue
        print(f"\n{_TITLE[tier]}")
        print("─" * 78)
        for c in group:
            if tier == "verify":
                err = f"{c.ppm:8.1f} ppm" if c.ppm < 1e4 else f"{c.rel_error*100:6.3f} %"
                print(f"  {_SYM[tier]}  {c.name:<20} "
                      f"расч={c.predicted:.6g}  эксп={c.experimental:.6g} {c.unit}")
                print(f"     откл={err:>14}   [{c.formula}]  · {c.source}")
            else:
                print(f"  {_SYM[tier]}  {c.name:<22} "
                      f"= {c.predicted:.6g}  (эксп/эталон {c.experimental:.6g} {c.unit})")
                if c.verdict in ("coincidence", "mismatch"):
                    print(f"     откл={c.rel_error*100:.3f} %   {c.note}")
                else:
                    print(f"     {c.note}")

    # ── Итоговый вердикт ─────────────────────────────────────────────────────
    ver = [c for c in checks if c.verdict == "verify"]
    n_ok = sum(c.rel_error < 1e-3 for c in ver)
    worst = max(ver, key=lambda c: c.rel_error)
    print("\n" + "═" * 78)
    print("  ИТОГ")
    print("─" * 78)
    print(f"  ТИР A: {n_ok}/{len(ver)} проверок совпадают с экспериментом лучше 0.1%.")
    print(f"         худшая ошибка: {worst.name} = {worst.rel_error*100:.4f} %")
    print(f"  ТИР B: {sum(c.verdict=='coincidence' for c in checks)} численных совпадений "
          f"(нумерология, не выведено из физики).")
    print(f"  ТИР C: {sum(c.verdict=='model' for c in checks)} модельные конструкции "
          f"(без экспериментального якоря).")
    print(f"  ТИР D: {sum(c.verdict=='mismatch' for c in checks)} расхождение "
          f"(заявленное равенство ложно).")
    print("═" * 78)
    print("  ЧЕСТНО: спектр водорода воспроизводится ТОЧНО — но это стандартная КМ")
    print("  (формула Ридберга), а не новое открытие. φ-конструкции (137, Γ*, Ω_D)")
    print("  экспериментом НЕ подтверждаются: это совпадения или внутренние величины.")
    print("═" * 78)


if __name__ == "__main__":
    print_report()
