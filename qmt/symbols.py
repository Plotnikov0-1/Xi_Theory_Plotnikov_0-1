def describe_number(n: int) -> Symbol:
    """Аллегорическое значение числа n (0–9, 11)."""
    return NUMBERS[n]


def true_path() -> dict[int, str]:
    """«Верный путь»: число → имя (1 любовь … 9 жизнь, 0 доброта)."""
    return {n: s.name for n, s in sorted(NUMBERS.items()) if n <= 9 or n == 0}


def mirror_pair_meaning(n: int) -> tuple[int, str, str]:
    """Зеркало числа (сумма 10) и его значение. Напр., 5 — это 2 «в зеркале»."""
    m = 10 - n
    return m, NUMBERS.get(n, Symbol("", "", "")).name, NUMBERS.get(m, Symbol("", "", "")).name


