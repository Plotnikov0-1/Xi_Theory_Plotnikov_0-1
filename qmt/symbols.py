    print("«Верный путь» (число → имя):")
    for n, name in true_path().items():
        print(f"  {n} — {name}")
    print("\nАллегория чисел:")
    for n in range(0, 10):
        s = NUMBERS[n]
        print(f"  {n} ({s.name}): {s.meaning}")
    print("\nРимские (динамика перехода):")
    for k, s in ROMAN.items():
        print(f"  {k:<3} {s.name}: {s.meaning}")
