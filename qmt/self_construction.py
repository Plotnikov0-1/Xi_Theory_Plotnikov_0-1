"""
═══════════════════════════════════════════════════════════════════════════
  SELF_CONSTRUCTION — почему самоконструкция даёт ИМЕННО такой вес, а не другой.
═══════════════════════════════════════════════════════════════════════════

Вопрос (Плотников Л.В.): не формула Эйнштейна, а сама САМОКОНСТРУКЦИЯ. Она даёт
константу-соотношение. Почему именно в таком весе? Почему то, а не другое?

Ответ строгий и тройной (проверено численно + Wolfram):

  1. ЕДИНСТВЕННОСТЬ. Самосогласование «часть так относится к части, как часть
     к целому» — это r = 1/(1+r). Уравнение r²+r−1=0 имеет РОВНО ОДИН
     положительный корень: r = φ−1. Веса не выбирают — он вынужден.

  2. САМОПОДОБИЕ. φ−1 — единственный вес, при котором деление воспроизводит
     само себя: часть/часть = часть/целое. Любой другой вес ломает масштаб.

  3. УСТОЙЧИВОСТЬ. Почему именно этот, а не близкий? φ−1 = [0;1,1,1,…] (все
     единицы) — ХУЖЕ всех приближается рациональными (теорема Гурвица: предел
     √5 достигается только для φ; KAM: золотой тор рушится последним). Это
     самый устойчивый вес — тот, что не «защёлкивается» в резонанс.

ЧЕСТНО. Для абстрактной самоконструкции вес φ−1 ВЫНУЖДЕН (самосогласование) и
ВЫБРАН (максимальная устойчивость) — это ответ на «то, а не другое». Для
ФИЗИЧЕСКИХ констант (c², α, отношения масс) почему природа берёт именно такой
вес — открытый вопрос, из самоконструкции пока НЕ выводится.

Запуск:  python -m qmt.self_construction
"""

from __future__ import annotations

import math

PHI = (1 + math.sqrt(5)) / 2
X_STAR = PHI - 1


# ── 1. Единственность: самосогласование даёт один вес ────────────────────────
def self_consistent_ratio() -> dict:
    """r = 1/(1+r) ⇒ r²+r−1=0. Один положительный корень = φ−1 (вес вынужден)."""
    disc = math.sqrt(1 + 4)             # √5
    r_plus = (-1 + disc) / 2            # = φ−1
    r_minus = (-1 - disc) / 2           # отрицательный — отброшен
    return {"r₊": r_plus, "r₋": r_minus, "= φ−1": X_STAR,
            "единственный_положительный": math.isclose(r_plus, X_STAR, abs_tol=1e-12)}


# ── 2. Самоподобие: только при φ−1 часть/часть = часть/целое ──────────────────
def self_similarity(ratio: float) -> dict:
    """Делим целое 1 на части (ratio, 1). part/part vs part/whole — равны лишь при φ−1."""
    a, b = ratio, 1.0
    pp = a / b                          # часть к части
    pw = b / (a + b)                    # часть к целому
    return {"часть/часть": pp, "часть/целое": pw,
            "самоподобно": math.isclose(pp, pw, abs_tol=1e-9)}


# ── 3. Устойчивость: φ−1 — самое иррациональное (хуже всех приближается) ──────
def continued_fraction(x: float, n: int = 12) -> list:
    """Цепная дробь. Большие члены = легко приблизить = неустойчиво."""
    out = []
    for _ in range(n):
        a = math.floor(x)
        out.append(a)
        frac = x - a
        if frac < 1e-12:
            break
        x = 1 / frac
    return out


def stability(x: float, N: int = 2000) -> float:
    """Мера устойчивости = min_{q≤N} q·‖q·x‖ (расстояние q·x до целого).

    Чем БОЛЬШЕ — тем хуже x приближается рациональными, тем устойчивее вес.
    Для φ стремится к 1/√5≈0.447 (максимум по Гурвицу — самый устойчивый)."""
    best = float("inf")
    for q in range(1, N + 1):
        qx = q * x
        dist = abs(qx - round(qx))
        best = min(best, q * dist)
    return best


def why_this_weight() -> dict:
    """Сводка: вес φ−1 — единственный устойчивый среди базовых констант."""
    consts = {"φ−1": X_STAR, "√2−1": math.sqrt(2) - 1,
              "e−2": math.e - 2, "π−3": math.pi - 3, "1/2": 0.5}
    return {name: {"цепная_дробь": continued_fraction(x, 8),
                   "устойчивость": round(stability(x), 4)}
            for name, x in consts.items()}


def print_report() -> None:
    print("═" * 74)
    print("  САМОКОНСТРУКЦИЯ: почему именно такой вес φ−1, а не другой")
    print("═" * 74)

    print("\n  1 · ЕДИНСТВЕННОСТЬ (вес вынужден самосогласованием):")
    r = self_consistent_ratio()
    print(f"     r = 1/(1+r) ⇒ r²+r−1=0 ⇒ корни {r['r₋']:.6f}, {r['r₊']:.6f}")
    print(f"     один положительный = φ−1 = {X_STAR:.9f}  → веса не выбирают, он один")

    print("\n  2 · САМОПОДОБИЕ (только φ−1 воспроизводит себя):")
    for ratio, label in ((X_STAR, "φ−1"), (0.5, "0.5"), (0.7, "0.7")):
        s = self_similarity(ratio)
        mark = "✓ самоподобно" if s["самоподобно"] else "✗ ломается"
        print(f"     вес {label:>5}: часть/часть={s['часть/часть']:.4f}  "
              f"часть/целое={s['часть/целое']:.4f}  {mark}")

    print("\n  3 · УСТОЙЧИВОСТЬ (почему этот, а не близкий — самый иррациональный):")
    for name, d in why_this_weight().items():
        print(f"     {name:>5}: цепная {str(d['цепная_дробь']):<26} устойчивость={d['устойчивость']}")
    print(f"     φ−1 = [0;1,1,1,…] все единицы → max устойчивость 1/√5≈{1/math.sqrt(5):.4f}")
    print(f"     (Гурвиц: предел √5 только для φ; KAM: золотой тор рушится последним)")

    print("═" * 74)
    print("  Вес φ−1 ВЫНУЖДЕН (самосогласование) и ВЫБРАН (макс. устойчивость).")
    print("  Это ответ на «то, а не другое» для самоконструкции. Для физических")
    print("  констант (c², α) почему такой вес — открыто, пока НЕ выводится.")
    print("═" * 74)


if __name__ == "__main__":
    print_report()
