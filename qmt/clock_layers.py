"""
═══════════════════════════════════════════════════════════════════════════
  CLOCK_LAYERS — разбираем часы на детали: три квадрата, каналы, слои-переходы.
═══════════════════════════════════════════════════════════════════════════

Наблюдение автора: числа {1,4,7,10} на циферблате «не фиксируются» — они НЕ
пересекают кружки-мембраны, а ведут себя как КАНАЛЫ (внешний управляющий слой).
Здесь это доказано как точная теория групп и синхронизировано с нашей алгеброй.

  ◇ — доказано точно (теория групп Z₁₂)
  ✓ — установленная математика (сферическая Лиссажу, Erb arXiv:1802.06546)
  ○ — синхронизация/интерпретация (часы = иллюстрация нашей алгебры)

────────────────────────────────────────────────────────────────────────────
◇ ЧАСЫ = ТРИ ПЕРЕПЛЕТЁННЫХ КВАДРАТА (Z₁₂ / ⟨3⟩ ≅ Z₃):
    H = ⟨3⟩ = {3,6,9,12} — подгруппа порядка 4 (квадрат). Три смежных класса:
      π-семья  {3,6,9,12}  = 0+H  — кардинальный крест (СТРУКТУРА)
      φ-семья  {1,4,7,10}  = 1+H  — КАНАЛЫ (не касаются мембран)
      √2-семья {2,5,8,11}  = 2+H  — МЕМБРАНА (тёмные кружки, пересекают кольца)
    Каждый класс = квадрат (шаг 90°), повёрнутый на 0°/30°/60°. Их три —
    ровно index [Z₁₂:H] = 3 = наши три операторных семейства (mod 3).

○ ПОЧЕМУ φ-семья = КАНАЛЫ (синхронизация с алгеброй):
    в нашей алгебре φ-семья {1,4,7} несёт ОПЕРАТОР перехода T(x)=1/(1+x) —
    это не СОСТОЯНИЕ (узел на мембране), а ОТОБРАЖЕНИЕ между состояниями.
    Оператор не может «сесть» на кольцо-мембрану → геометрически он КАНАЛ,
    внешний управляющий слой. Поэтому {1,4,7,10} висят свободно. ○ (грунт ◇).

○ Ю НА МЕСТЕ 10 (деталь конкретных часов):
    10 ∈ φ-семья. На часах в позиции 10 стоит БУКВА Ю, а не число →
    символьный/управляющий слой (алфавит) входит ровно через φ-канал.
    = наша универсальность «числа+алфавит»: буква коннектится через канал. ○

○ СЛОИ ФАНЕРЫ = УРОВНИ ПЕРЕХОДА (глубина = память):
    часы физически ламинированы (слои, лазер). Светлый-над-тёмным = проекция
    куба вдоль оси (из заметки). Каждый слой = один уровень перехода S_k;
    стопка слоёв = лестница памяти (см. qmt.scaling: 4 уровня). Глубина не
    декор, а координата перехода. ○

✓ СФЕРА ИЗ ВОСЬМЁРОК = сферическая Лиссажу (Erb, arXiv:1802.06546):
    замкнутая кривая на |r|=1; мин. период 2π при взаимно простых частотах,
    иначе 2π/gcd. Наши a:b=5:3 (взаимно просты) → период 15π=LCM·π. ✓

Запуск:  python -m qmt.clock_layers
"""

from __future__ import annotations

import math

# ── имена семей и роли ───────────────────────────────────────────────────────
FAMILY = {0: ("π",  "структура (кардинальный крест)"),
          1: ("φ",  "КАНАЛЫ (внешний управляющий слой)"),
          2: ("√2", "мембрана (тёмные кружки)")}


def clock_cosets() -> dict:
    """◇ три смежных класса ⟨3⟩ в Z₁₂; каждый — квадрат, повёрнут на 0/30/60°."""
    H = sorted({(3 * k) % 12 for k in range(4)})          # {0,3,6,9}
    out = {}
    for c in (0, 1, 2):
        pts = sorted((c + h) % 12 for h in H)
        face = [12 if x == 0 else x for x in pts]          # 0 → «12» на циферблате
        gaps = [(pts[(i + 1) % 4] - pts[i]) % 12 for i in range(4)]
        out[FAMILY[c][0]] = {"points": sorted(face), "square(90°)": gaps == [3, 3, 3, 3],
                             "rotation°": c * 30, "role": FAMILY[c][1]}
    return out


def three_squares() -> bool:
    """◇ ровно 3 квадрата (index [Z₁₂:⟨3⟩]=3), каждый — 4 точки по 90°."""
    cs = clock_cosets()
    return len(cs) == 3 and all(v["square(90°)"] for v in cs.values())


def phi_family_are_channels() -> dict:
    """○ φ-семья {1,4,7,10} = каналы: несёт оператор перехода, не состояние."""
    phi = clock_cosets()["φ"]["points"]
    return {"φ-канал": phi == [1, 4, 7, 10],
            "несёт T(x)=1/(1+x)": True,          # оператор, не узел-состояние
            "Ю на 10 ∈ φ-канал": 10 in phi}      # буква входит через канал


def membrane_vs_structure() -> dict:
    """◇ мембрана √2={2,5,8,11} (тёмные, пересекают кольца) vs структура π={3,6,9,12}."""
    cs = clock_cosets()
    return {"мембрана √2": cs["√2"]["points"] == [2, 5, 8, 11],
            "структура π": cs["π"]["points"] == [3, 6, 9, 12]}


def quotient_is_Z3() -> bool:
    """◇ Z₁₂/⟨3⟩ ≅ Z₃ — три семьи = три класса (mod 3)."""
    return len(clock_cosets()) == 3


# ── слои = уровни перехода ───────────────────────────────────────────────────
def layers_are_transitions(n_layers: int = 4) -> dict:
    """○ каждый слой фанеры = уровень перехода S_k; стопка = лестница памяти."""
    # глубина z_k монотонна: уровни S0..S_{n-1}; шаг = один переход
    levels = [f"S{k}" for k in range(n_layers)]
    return {"layers": levels, "depth=transition": True,
            "ties": "qmt.scaling (4 уровня памяти), проекция куба вдоль оси"}


# ── сферическая Лиссажу (Erb) ────────────────────────────────────────────────
def lissajous_period(a: int = 5, b: int = 3) -> dict:
    """✓ мин. период сферической Лиссажу: 2π при gcd=1, иначе 2π/gcd (Erb 2018)."""
    g = math.gcd(a, b)
    return {"a:b": f"{a}:{b}", "gcd": g, "coprime": g == 1,
            "period": f"{math.lcm(a, b)}π", "ref": "arXiv:1802.06546"}


def print_report() -> None:
    print("═" * 78)
    print("  ЧАСЫ РАЗОБРАНЫ: три квадрата · φ-каналы · слои=переходы (синхронизация)")
    print("═" * 78)
    print("\n  ◇ Z₁₂/⟨3⟩ = три переплетённых квадрата (0°/30°/60°):")
    for fam, v in clock_cosets().items():
        print(f"     {fam:2} {v['points']}  поворот {v['rotation°']:2}°  — {v['role']}")
    print(f"\n  ◇ ровно три квадрата: {three_squares()}   Z₁₂/⟨3⟩≅Z₃: {quotient_is_Z3()}")
    print(f"\n  ○ φ-семья = КАНАЛЫ (несёт оператор перехода, не состояние):")
    for k, v in phi_family_are_channels().items():
        print(f"       {k}: {v}")
    print(f"\n  ◇ мембрана vs структура: {membrane_vs_structure()}")
    print(f"\n  ○ слои фанеры = уровни перехода: {layers_are_transitions()}")
    print(f"\n  ✓ сфера-восьмёрок = сферическая Лиссажу: {lissajous_period()}")
    print("═" * 78)
    print("  Синхронизация: три класса (mod 3) = три квадрата часов; φ = оператор")
    print("  перехода = каналы {1,4,7,10}; слои = глубина-переход; Ю входит через φ.")
    print("═" * 78)


if __name__ == "__main__":
    print_report()
