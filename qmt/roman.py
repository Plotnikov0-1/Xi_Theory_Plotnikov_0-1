"""
Римские числа — строгий факт «триединства» + привязка к узлам модели.

Источник (аллегория римских цифр): «любые числа состоят не более чем из трёх…
а вы говорили о триединстве». Это РЕАЛЬНОЕ правило римской записи, и оно
проверяемо/выводимо заново (низкий риск искажения):

    в стандартной (вычитательной) записи символ не повторяется больше ТРЁХ раз
    (IIII → IV, XXXX → XL, …). Максимум подряд одинаковых = 3.

То есть «3» сидит в самой НОТАЦИИ чисел — ещё один независимый, неискажаемый
источник тройки (ср. 3 цвета SU(3), триада А·Д·Л, «3» в 3+7+12).

Привязка ключевых цифр к узлам модели (интерпретация, Q3):
    I  = 1  начало (узел S1)
    IV = 4  «начало оценки», I перед V (вычитание) → Д/туннель (узел S4)
    V  = 5  чаша-оценка, ЦЕНТР (sync.CENTER=5), точка выбора
    VI = 6  «число Дьявола» — мнимое всезнание (узел S6)
    X  = 10 крест — «пригвоздил себя ко времени»
    L  = 50 разбитая чаша — открытый путь
    XL = 40 ЦЕЛЬ — выход за пределы эго (ср. «40 = выход за эго»)
"""

from __future__ import annotations

import re

_VALS = [(1000, "M"), (900, "CM"), (500, "D"), (400, "CD"), (100, "C"),
         (90, "XC"), (50, "L"), (40, "XL"), (10, "X"), (9, "IX"),
         (5, "V"), (4, "IV"), (1, "I")]


def to_roman(n: int) -> str:
    """Целое 1..3999 → стандартная (вычитательная) римская запись."""
    if not 1 <= n <= 3999:
        raise ValueError("диапазон 1..3999")
    out = ""
    for v, sym in _VALS:
        while n >= v:
            out += sym
            n -= v
    return out


def max_repetition(n: int) -> int:
    """Макс. число одинаковых символов подряд в записи n."""
    r = to_roman(n)
    return max(len(m.group()) for m in re.finditer(r"(.)\1*", r))


def verify_max_three(upto: int = 3999) -> dict:
    """Строгая проверка правила «не более трёх» на 1..upto (Q0)."""
    worst_n, worst = 0, 0
    for n in range(1, upto + 1):
        m = max_repetition(n)
        if m > worst:
            worst, worst_n = m, n
    return {"макс_повтор": worst, "при_числе": worst_n,
            "правило_трёх": worst == 3}


# Привязка цифр к узлам/смыслам (Q3, интерпретация).
ROMAN_NODES = {
    "I":  (1,  "начало"),
    "IV": (4,  "начало оценки (I перед V) → Д/туннель"),
    "V":  (5,  "чаша-оценка, ЦЕНТР, точка выбора"),
    "VI": (6,  "«число Дьявола» — мнимое всезнание"),
    "X":  (10, "крест — пригвождение ко времени"),
    "L":  (50, "разбитая чаша — открытый путь"),
    "XL": (40, "ЦЕЛЬ — выход за пределы эго"),
}


def digit_root(n: int) -> int:
    """Цифровой корень (повторная сумма цифр)."""
    while n > 9:
        n = sum(int(d) for d in str(n))
    return n


def xl_forty() -> dict:
    """XL = 40 — «цель / выход за пределы эго». Структурный разбор.

    Главное: цифровой корень 40 = 4 ⇒ выход идёт ЧЕРЕЗ четвёрку (Д, туннель).
    Вычитательно XL = L − X = 50 − 10 = «открытый путь минус крест-эго».
    Путь выхода = трещина 7→4→1→0: ограниченная память (эго) сквозь туннель-4
    к единой памяти и за круг (внешний 0).
    """
    return {
        "запись": "XL = L − X = 50 − 10 (открытый путь минус крест-эго)",
        "цифровой_корень": digit_root(40),                 # = 4 (Д/туннель)
        "разложения": ["4×10 = туннель(Д)×крест(X)",
                        "8×5 = ∞(лежачая 8)×центр(5)"],
        "путь_выхода": "7(эго,Л) → 4(туннель,Д) → 1(единая,А) → 0 внешний",
        "смысл": "выход за круг идёт через четвёрку (цифр.корень 4 = Д)",
    }


def print_report() -> None:
    v = verify_max_three()
    print("РИМСКИЕ ЧИСЛА — «не более трёх» = триединство")
    print("=" * 60)
    print(f"макс. одинаковых символов подряд на 1..3999 = {v['макс_повтор']} "
          f"(при {v['при_числе']} = {to_roman(v['при_числе'])})")
    print(f"правило трёх выполняется: {v['правило_трёх']}  (Q0, выводимо заново)")
    print("\n«3» в самой нотации чисел — независимый неискажаемый источник тройки")
    print("(ср. 3 цвета SU(3), триада А·Д·Л, «3» в 3+7+12).\n")
    print("Привязка к узлам (Q3):")
    for sym, (node, sense) in ROMAN_NODES.items():
        print(f"  {sym:>2} = {node:>2}  {sense}")
    print("=" * 60)
    print("Особо: V=5=ЦЕНТР (sync.CENTER=5), IV=4=туннель(Д), XL=40=цель/выход.")
    xl = xl_forty()
    print(f"\nXL=40 (цель/выход за эго): {xl['запись']}")
    print(f"  цифровой корень 40 = {xl['цифровой_корень']} ⇒ выход ЧЕРЕЗ четвёрку (Д)")
    print(f"  путь: {xl['путь_выхода']}")


if __name__ == "__main__":
    print_report()
