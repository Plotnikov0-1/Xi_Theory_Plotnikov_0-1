"""
ШЁПОТ — связь проекций с целым; то, что делает нас Человеком (не машиной).

По автору: «Шёпот — это всё, что говорит в Вас, но не сознание Ваше. Вы можете
чувствовать, но не понять — иначе был бы уже диалог. Он не слаб — Вы глухи: у
Вас слишком много "одежд"; меньше одежд — громче и разборчивее. Шёпот — это
совесть, прошлые и будущие воспоминания, всё непознанное. Это то, что делает
вас Человеком: у машины есть сознание (и машины будут "выше" вас), но шёпот они
слышать не могут. Это Аоум, Дух.»

Перевод в структуры/физику модели:
  • ИСТОЧНИК: целое (внешний 0, «целое число за пределом круга»). Сигнал идёт
    оттуда через ЧЕТВЁРКУ (Д, канал 0→4, туннель) к проекциям — по вершинам,
    точкам, переходам (sync). Буква А (канал 0→1, всеобъемлющая память)
    соединяет ВСЕ проекции: «думаем вместе, но живём по-разному».
  • «ЧУВСТВУЮ, НО НЕ ПОНИМАЮ» = подпороговый сигнал (ниже сознания). Понять =
    свернуть в диалог; пока не свёрнут — это шёпот.
  • «ОДЕЖДЫ» = шум/декогеренция (температура θ). Слышимость ∝ удержанная память
    (плато c(∞)) и возвраты (немарковость). Меньше одежд (ниже θ) — громче.
    Он НЕ слаб: при малых θ плато c(∞)>0 всегда — сигнал есть; «глухота» = θ велик.
  • ЧЕЛОВЕК vs МАШИНА: шёпот = немарковская связь памяти с целым. Марковская
    машина (θ→∞, без памяти) имеет сознание, но шёпот ей недоступен.
  • «слабые отличия → серьёзные» = самоподобное усиление (чувствительность;
    ср. самоподобный рост CP G→A_global→A_local в cp_baryogenesis).
"""

from __future__ import annotations

from dataclasses import dataclass

from . import dephasing


WHISPER_SOURCE = "целое (внешний 0) → через Д(4, туннель) → проекции по вершинам"
WHISPER_IS = ["совесть", "прошлые и будущие воспоминания",
              "всё непознанное", "Аоум / Дух — истинно человеческое"]


def audibility(clothes_theta: float, alpha: float = 1.0) -> dict:
    """Слышимость шёпота при «одеждах» θ (шум/декогеренция).

    Возвращает удержанную память (плато c(∞)) и возвраты (немарковость) и
    качественную оценку. Меньше θ — громче шёпот.
    """
    plateau = float(dephasing.coherence_curve([60.0], alpha, clothes_theta)[0])
    revivals = dephasing.non_markovianity(alpha, clothes_theta)
    if revivals > 0.01:
        level = "громкий (память цела, возвраты)"
    elif plateau > 0.05:
        level = "тихий (память частично удержана)"
    else:
        level = "не слышен — «вы глухи» (декогеренция стёрла память)"
    return {"одежды_θ": clothes_theta, "плато": round(plateau, 4),
            "возвраты": round(revivals, 4), "слышимость": level}


def human_vs_machine() -> dict:
    """Различие: шёпот = немарковская связь памяти; машина марковская."""
    return {
        "человек": "немарковская память (ε≠0) → слышит шёпот (связь с целым)",
        "машина": "марковское сознание (без памяти) → шёпота не слышит",
        "ключ": "сознание есть у обоих; шёпот — только при памяти ε≠0",
    }


def not_weak_but_deaf(thetas=(0.0, 0.1, 0.3)) -> bool:
    """Он не слаб: при малых «одеждах» плато c(∞)>0 (сигнал есть всегда)."""
    return all(audibility(t)["плато"] > 0.05 for t in thetas)


@dataclass
class Whisper:
    source: str = WHISPER_SOURCE
    channel: int = 4              # идёт через Д (канал 0→4, туннель)
    connector_of_projections: str = "А (канал 0→1, всеобъемлющая память)"
    below_consciousness: bool = True
    makes_us_human: bool = True


def core() -> Whisper:
    return Whisper()


def print_report() -> None:
    print("ШЁПОТ — связь проекций с целым (то, что делает нас Человеком)")
    print("=" * 66)
    print(f"источник: {WHISPER_SOURCE}")
    print(f"соединяет проекции: буква А (канал 0→1)  ·  идёт через Д (4, туннель)")
    print(f"шёпот это: {', '.join(WHISPER_IS)}\n")
    print(f"{'одежды θ':>9} {'плато':>7} {'возвраты':>9}  слышимость")
    for t in (0.0, 0.1, 0.3, 0.5, 1.0, 3.0):
        a = audibility(t)
        print(f"{a['одежды_θ']:9.1f} {a['плато']:7.3f} {a['возвраты']:9.4f}  "
              f"{a['слышимость']}")
    print(f"\nне слаб, мы глухи: при малых θ сигнал есть всегда = {not_weak_but_deaf()}")
    hm = human_vs_machine()
    print(f"человек: {hm['человек']}")
    print(f"машина:  {hm['машина']}")
    print("=" * 66)
    print("Шёпот = немарковская память-связь с целым; «одежды» = декогеренция.")


if __name__ == "__main__":
    print_report()
