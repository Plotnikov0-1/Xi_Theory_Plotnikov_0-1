"""
Физические и модельные константы теории DIALOG QMT v11.0.

Источник: «DIALOG QMT — Quantum Memory Transition Theory, Развёрнутая
архитектура, Версия 11.0» (Плотников Л.В., Харитонов Г.М.).

Все фундаментальные константы взяты из CODATA. Производные величины
вычисляются из формул теории (а не подставляются вручную), чтобы код
сам служил проверкой числовых результатов документа.
"""

from __future__ import annotations

import math

# --- Фундаментальные физические константы (CODATA) ---------------------------
C = 2.99792458e8           # скорость света, м/с
HBAR_J = 1.054571817e-34   # приведённая постоянная Планка, Дж·с
HBAR_EV = 6.582119569e-16  # та же постоянная в эВ·с
M_E = 9.1093837015e-31     # масса электрона, кг
EV = 1.602176634e-19       # 1 электронвольт, Дж
A0 = 5.29177210903e-11     # боровский радиус, м
RYDBERG_EV = 13.605693122   # энергия Ридберга, эВ
R_INF = 1.0973731568160e7  # постоянная Ридберга, 1/м

# --- Математические константы ------------------------------------------------
PHI = (1.0 + math.sqrt(5.0)) / 2.0   # золотое сечение, 1.6180339887...
E = math.e                           # 2.718281828...
PI = math.pi                         # 3.141592653...

# --- §1.1  Центральное тождество a·omega = c ---------------------------------
# Комптоновская длина и частота Циттербевегунга электрона.
COMPTON_LENGTH = HBAR_J / (M_E * C)        # a = hbar/(m c), м
ZITTER_FREQ = (M_E * C**2) / HBAR_J        # omega = m c^2 / hbar, рад/с
OMEGA_C = ZITTER_FREQ                       # верхний обрез резервуара ωc

# --- §1.4  Стационарная точка (φ-аттрактор) ----------------------------------
# Из условия φ² = φ + 1 следует X* = φ − 1 = 1/φ.
X_STAR = PHI - 1.0                          # 0.6180339887...

# --- §1.5  Туннельный барьер S6 → S7 -----------------------------------------
DELTA_7 = math.sqrt(5.0) - 2.0              # высота барьера, эВ (0.2360679...)
TAU_BRIDGE = HBAR_EV / DELTA_7              # время жизни моста, с (≈2.79 фс)

# --- §3.2  Структурные параметры топологии Sum-9 -----------------------------
LAMBDA_0 = 9.0 / 5.0   # = 1.8  (9 узлов S1–S9 / 5 резонансных пар)
MU_0 = 1.0 / 2.0       # = 0.5  (2 реальных из 4 компонент биспинора)
X_C = LAMBDA_0 / MU_0  # = 3.6  (нормировочный масштаб нагрузки)
MU_CRIT = MU_0         # бифуркационное значение проводимости

# --- §13  Туннель: высота барьера и масштаб системы --------------------------
DELTA_E_67 = 0.100     # E6 − E7 водорода, эВ (высота прямоугольного барьера)
OMEGA_SYS = DELTA_E_67 * EV / HBAR_J        # Ω_sys = ΔE67/ℏ, с^-1 (≈1.52e14)
GAMMA_DECO = 1.0 / TAU_BRIDGE               # скорость декогеренции, с^-1


def resonance_amplitude(x: float = X_STAR) -> float:
    """§3.3  Безразмерная резонансная амплитуда Γ = λ₀·μ₀·(X/Xc)·π.

    При X = X* = φ−1 даёт Γ* ≈ 0.485.
    """
    return LAMBDA_0 * MU_0 * (x / X_C) * PI


# Эталонное значение Γ* для X = X*.
GAMMA_STAR = resonance_amplitude(X_STAR)


if __name__ == "__main__":  # быстрая самопроверка ключевых чисел
    print(f"a·ω = {COMPTON_LENGTH * ZITTER_FREQ:.6e}  (должно быть c = {C:.6e})")
    print(f"a (комптон)   = {COMPTON_LENGTH:.4e} м")
    print(f"ωc            = {OMEGA_C:.4e} рад/с")
    print(f"X* = φ−1      = {X_STAR:.6f}")
    print(f"Δ7 = √5−2     = {DELTA_7:.6f} эВ")
    print(f"τ_bridge      = {TAU_BRIDGE * 1e15:.3f} фс")
    print(f"λ0, μ0, Xc    = {LAMBDA_0}, {MU_0}, {X_C}")
    print(f"Γ*            = {GAMMA_STAR:.4f}")
