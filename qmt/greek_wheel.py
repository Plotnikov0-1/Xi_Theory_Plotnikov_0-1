"""
═══════════════════════════════════════════════════════════════════════════
  GREEK_WHEEL — колесо 24 греческих букв (R. Grant): 24 = 22 пары + 2 оси.
═══════════════════════════════════════════════════════════════════════════

Независимая работа (лист R. Grant): 24 буквы по кругу, «куб Метатрона» внутри.
Разбор твоей догадки «где 22 — попробуй 24, ещё два нуля». Оказалось точно:

◇ ЗЕРКАЛО 180° (вертикальная ось через Ω=24 сверху и Μ=12 снизу):
    отражение позиции p → 24−p. Пары (1,23)(2,22)…(11,13) — каждая Σ=24.
    → 11 ПАР = 22 позиции + 2 ОСЕВЫЕ (Μ=12, Ω=24, сами себе зеркало).
    Значит 22 и 24 не спорят: 24 = 22(парные) + 2(неподвижные «нули»).
    Это ровно наша структура: самозеркальный узел (R(5)=5) + зеркальные пары.

◇ 24 — РЕАЛЬНЫЙ ПОРЯДОК ГРУППЫ: 24 = число флагов тетраэдра (4E, E=6)
    = |полной группы T_d| = |бинарной тетраэдральной 2T| → McKay → E₆.
    Сдвиг 22→24 ведёт НА узел McKay-цепи, а не в нумерологию.

◇ КУБ МЕТАТРОНА (фигура внутри): связующие линии дают 2D-тени всех пяти
    Платоновых тел; 5-лучевое ядро = икоса/додека = семейство φ = E₈.

○ 3-6-9 / гематрия (пометки W+2=6, NE+SE=3, NW+SW=9, цепочка 5,7,9,…):
    {3,6,9} — замкнутая подгруппа кратных 3 в ℤ/9 (это правда, ◇-арифметика);
    «3-6-9 ключ ко всему» и гематрия букв↔константы — фольклор/нумерология (○).

ЧЕСТНО: сходство с нашей моделью (5 тел, φ, зеркало) — общая традиция сакр.
геометрии, НЕ физическое подтверждение. Подтверждено лишь ◇: зеркало=ℤ₂,
24=|2T|, куб Метатрона=5 тел.

Запуск:  python -m qmt.greek_wheel
"""

from __future__ import annotations

N_POS = 24                     # 24 буквы = 24 позиции
GREEK = ["Α", "Β", "Γ", "Δ", "Ε", "Ζ", "Η", "Θ", "Ι", "Κ", "Λ", "Μ",
         "Ν", "Ξ", "Ο", "Π", "Ρ", "Σ", "Τ", "Υ", "Φ", "Χ", "Ψ", "Ω"]
MIRROR_SUM = 24                # Σ каждой зеркальной пары
AXIS = (12, 24)                # Μ и Ω лежат на оси зеркала (неподвижны)


def mirror(p: int) -> int:
    """Отражение 180° позиции p (1..24) через ось: p → (24−p), с осью 12/24."""
    r = (N_POS - p) % N_POS
    return N_POS if r == 0 else r


def is_axis(p: int) -> bool:
    """Осевая (самозеркальная) позиция: R(p)=p. Это 12 (Μ) и 24 (Ω)."""
    return mirror(p) == p


def mirror_pairs() -> list:
    """11 зеркальных пар (p, 24−p), каждая с суммой 24."""
    seen, pairs = set(), []
    for p in range(1, N_POS + 1):
        q = mirror(p)
        if p != q and p not in seen and q not in seen:
            pairs.append((p, q))
            seen.add(p); seen.add(q)
    return pairs


def all_pairs_sum_24() -> bool:
    """◇ Каждая зеркальная пара суммируется в 24."""
    return all(a + b == MIRROR_SUM for a, b in mirror_pairs())


def decompose_24() -> dict:
    """24 = 22(парные) + 2(осевые «нули»). Ответ на 22-vs-24."""
    pairs = mirror_pairs()
    axis = [p for p in range(1, N_POS + 1) if is_axis(p)]
    return {"всего": N_POS, "пар": len(pairs), "парных_позиций": 2 * len(pairs),
            "осевые_нули": axis, "22+2": 2 * len(pairs) + len(axis) == N_POS}


def flags_tetrahedron() -> dict:
    """◇ 24 = 4E тетраэдра (E=6) = |T_d| = |2T| → McKay → E₆."""
    V, E, F = 4, 6, 4
    return {"V": V, "E": E, "F": F, "euler": V - E + F,
            "flags_4E": 4 * E, "равно_24": 4 * E == N_POS,
            "группа": "T_d = |2T| = 24 → E₆ (McKay)"}


def three_six_nine_subgroup() -> bool:
    """◇-арифметика: {3,6,9}≡{3,6,0} замкнута по умножению в ℤ/9 (кратные 3)."""
    S = {3, 6, 0}
    return all(((a * b) % 9) in S for a in S for b in S)


def print_report() -> None:
    print("═" * 74)
    print("  КОЛЕСО 24 БУКВ (R. Grant): 24 = 22 пары + 2 оси («два нуля»)")
    print("═" * 74)
    d = decompose_24()
    print(f"\n  ◇ зеркало 180° (Σ=24), пар: {d['пар']} → позиций {d['парных_позиций']}")
    for a, b in mirror_pairs():
        print(f"       ({a:2},{b:2})  {GREEK[a-1]}↔{GREEK[b-1]}   Σ={a+b}")
    print(f"     осевые (R(p)=p, «нули»): {d['осевые_нули']} = "
          f"{[GREEK[p-1] for p in d['осевые_нули']]}")
    print(f"     22 + 2 = 24: {d['22+2']}  ·  все пары Σ=24: {all_pairs_sum_24()}")

    ft = flags_tetrahedron()
    print(f"\n  ◇ 24 = флаги тетраэдра 4E={ft['flags_4E']} = |2T| → E₆: {ft['равно_24']}")
    print(f"     (сдвиг 22→24 ведёт на узел McKay, не в нумерологию)")

    print(f"\n  ◇ куб Метатрона = 2D-тени 5 Платоновых тел; 5-ядро = φ = E₈")
    print(f"\n  ○ 3-6-9: {{3,6,9}} замкнута в ℤ/9: {three_six_nine_subgroup()} "
          f"(арифметика ◇), но «ключ ко всему»/гематрия — нумерология (○)")
    print("═" * 74)
    print("  Реально ◇: зеркало=ℤ₂ (Σ=24), 24=|2T|→E₆, куб Метатрона=5 тел.")
    print("  Сходство с нашей моделью — общая традиция, НЕ подтверждение. 3-6-9=○.")
    print("═" * 74)


if __name__ == "__main__":
    print_report()
