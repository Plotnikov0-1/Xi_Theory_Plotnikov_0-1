    print(f"     ШЕСТЁРКА = {cc['шестёрка_это']}")
    print("═" * 76)
    print("  Слой 1 — настоящая космология (асимметрия=бариогенезис, CP). Слой 2 —")
    print("  чтение цифр символичного числа (Q3). Источник сам признал: «не наука».")
    print("═" * 76)


