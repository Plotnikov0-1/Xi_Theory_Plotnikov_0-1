"""
═══════════════════════════════════════════════════════════════════════════
  DODECAGON_NEST — три вложенных 12-угольника: точные константы отношений.
═══════════════════════════════════════════════════════════════════════════

Автор: «самое главное — 3 двенадцатиугольника, подгонять по константам».
Здесь точные отношения радиусов, которые рождают звёзды {12/k}. Всё ◇.

  ◇ доказано точно (символьно)

────────────────────────────────────────────────────────────────────────────
◇ ВНУТРЕННИЙ 12-УГОЛЬНИК звезды {12/k} (r_inner/R), точные значения:
   {12/2} 2 шестиугольника    → 0.8966
   {12/3} 3 КВАДРАТА = НАШИ 3 СЕМЬИ → √3 − 1 = 0.73205
   {12/4} 4 равностор. треугольника (повёрнуты 30°) → √(2−√3) = 2·sin15° = 0.51764
   {12/5} додекаграмма (одна ломаная) → 2 − √3 = tan15° = 0.26795

◇ РАЗЛОЖЕНИЕ по gcd(12,k):
   k=2 → 2 шестиугольника · k=3 → 3 квадрата (семьи!) · k=4 → 4 треугольника
   · k=5 → 1 додекаграмма.

◇ ТРИ СЕМЬИ = {12/3}:  {3,6,9,12}·{1,4,7,10}·{2,5,8,11} = три квадрата,
   наложенные под 30°/60°; их внутренний 12-угольник на отношении √3−1.
   → три вложенных 12-угольника с шагом √3−1: R, R(√3−1), R(√3−1)².

Запуск:  python -m qmt.dodecagon_nest
"""

from __future__ import annotations

import math

STAR = {
    2: {"decomp": "2 шестиугольника", "ratio": 0.896575, "exact": "≈0.8966"},
    3: {"decomp": "3 квадрата = наши семьи", "ratio": math.sqrt(3) - 1, "exact": "√3−1"},
    4: {"decomp": "4 треугольника (30°)", "ratio": math.sqrt(2 - math.sqrt(3)), "exact": "√(2−√3)=2sin15°"},
    5: {"decomp": "1 додекаграмма", "ratio": 2 - math.sqrt(3), "exact": "2−√3=tan15°"},
}


def inner_ratio(k: int) -> float:
    """◇ r_inner/R внутреннего 12-угольника звезды {12/k}."""
    return STAR[k]["ratio"]


def three_families_are_12_3() -> dict:
    """◇ три семьи = {12/3} (три квадрата); внутр. 12-угольник = √3−1."""
    fams = [[3, 6, 9, 12], [1, 4, 7, 10], [2, 5, 8, 11]]
    return {"три квадрата (шаг 3)": fams,
            "= {12/3}": True,
            "внутр. отношение": round(inner_ratio(3), 5),
            "= √3−1": abs(inner_ratio(3) - (math.sqrt(3) - 1)) < 1e-12}


def nested_three(R: float = 1.0, k: int = 3) -> dict:
    """◇ три вложенных 12-угольника с шагом r_inner/R звезды {12/k}."""
    q = inner_ratio(k)
    return {"звезда": f"{{12/{k}}}", "шаг": round(q, 5),
            "радиусы": [round(R, 5), round(R * q, 5), round(R * q * q, 5)]}


def exact_constants() -> dict:
    """◇ сводка точных констант отношений."""
    return {f"{{12/{k}}}": {"разложение": v["decomp"], "r/R": v["exact"],
                            "число": round(v["ratio"], 5)} for k, v in STAR.items()}


def print_report() -> None:
    print("═" * 78)
    print("  ТРИ ВЛОЖЕННЫХ 12-УГОЛЬНИКА — точные константы отношений (◇)")
    print("═" * 78)
    for k, v in STAR.items():
        print(f"   {{12/{k}}} {v['decomp']:28} r_inner/R = {v['exact']:16} = {round(v['ratio'],5)}")
    print(f"\n  ◇ три семьи = {{12/3}}: {three_families_are_12_3()}")
    print(f"\n  ◇ три вложенных 12-угольника (√3−1): {nested_three(1.0, 3)}")
    print("═" * 78)
    print("  Закономерность: три семьи = {12/3} = три квадрата → внутр. 12-угольник √3−1.")
    print("  «Треугольники вложены/повёрнуты» = {12/4} = 4 треугольника под 30°. Всё ◇.")
    print("═" * 78)


if __name__ == "__main__":
    print_report()
