"""
═══════════════════════════════════════════════════════════════════════════
  PERIODIC_MEMORY — «Иная таблица»: упорядочить элементы по ОТНОШЕНИЮ, не по Z.
═══════════════════════════════════════════════════════════════════════════

Документ «Иная таблица Менделеева» (DIALOG, 2026) предлагает упорядочить элементы
не по числу протонов Z (счёт), а по энергии связи на нуклон E_bind/A (ОТНОШЕНИЕ).
Это прямо ложится в теорию отношений: порядок по связи-на-вещь, а не по счёту.

ЧЕСТНОЕ РАЗДЕЛЕНИЕ ТРЁХ СЛОЁВ:

  ✓ НАСТОЯЩАЯ ФИЗИКА:
    • E_bind/A (Бете-Вайцзеккер): пик у Fe-56/Ni-62 ≈ 8.7–8.8 МэВ/нуклон;
      Fe — ЦЕНТР: до Fe синтез даёт энергию, после — поглощает (астрофизика);
    • ΔZ=18 = ширина d-блока: гомологи (Ti↔Zr, V↔Nb…) различаются на 18 —
      реальная химическая периодичность.

  ≈ СОВПАДЕНИЯ (не доказательство):
    • σ(K)/σ(Mg)=0.609 ≈ φ−1=0.618 — но разброс σ в справочниках 1–6% (сам
      документ признаёт) → внутри разброса, не находка;
    • σ(Ti)/σ(V)=0.5 — σ округлены до 1 знака, тривиально.

  ○ МОДЕЛЬ / НУМЕРОЛОГИЯ:
    • «режимная масса» m*=E_ion·Z — не стандартная физика, конструкт;
    • цифровые корни Z как «операторы», «константа 22» (алфавит, 14806, Fr T½) —
      кросс-доменные совпадения, не выводятся.

Запуск:  python -m qmt.periodic_memory
"""

from __future__ import annotations

import math

# Коэффициенты формулы Бете-Вайцзеккера (МэВ).
A_V, A_S, A_C, A_A, A_P = 15.835, 18.33, 0.714, 23.2, 11.2


def binding_per_nucleon(Z: int, A: int) -> float:
    """E_bind/A по Бете-Вайцзеккеру (МэВ/нуклон) — отношение связь:нуклон."""
    if Z % 2 == 0 and (A - Z) % 2 == 0:
        delta = A_P / math.sqrt(A)
    elif Z % 2 == 1 and (A - Z) % 2 == 1:
        delta = -A_P / math.sqrt(A)
    else:
        delta = 0.0
    E = (A_V * A - A_S * A**(2/3) - A_C * Z**2 / A**(1/3)
         - A_A * (A - 2*Z)**2 / A + delta)
    return E / A


def fe_is_peak() -> bool:
    """Fe-56/Ni-62 — максимум E_bind/A (центр «иной таблицы»)."""
    fe = binding_per_nucleon(26, 56)
    return (fe > binding_per_nucleon(6, 12) and fe > binding_per_nucleon(92, 238)
            and fe > binding_per_nucleon(2, 4))


def fusion_releases_energy(Z: int) -> bool:
    """До Fe (Z<26) синтез даёт энергию; после (Z>26) — поглощает."""
    return Z < 26


def digit_root(n: int) -> int:
    """Цифровой корень (= оператор DIALOG): сохраняется при добавлении 9 или 18."""
    return (n - 1) % 9 + 1


def homologous_pair(Z1: int, Z2: int) -> bool:
    """ΔZ=18 и общий цифровой корень → одна группа (реальная периодичность)."""
    return abs(Z2 - Z1) == 18 and digit_root(Z1) == digit_root(Z2)


def claim_tiers() -> dict:
    """Честный ярус каждого утверждения документа."""
    phi1 = (5**0.5 - 1) / 2
    return {
        "✓ Fe — пик E_bind/A (центр)": fe_is_peak(),
        "✓ ΔZ=18 = d-блок (Ti↔Zr…)": homologous_pair(22, 40),
        "≈ σ(K)/σ(Mg)=0.609≈φ−1": f"{1.4/2.3:.3f} vs {phi1:.3f} (внутри разброса σ 1-6% → совпадение)",
        "≈ σ(Ti)/σ(V)=0.5": "σ округлены до 1 знака → тривиально",
        "○ режимная масса m*=E_ion·Z": "конструкт, не стандартная физика",
        "○ «константа 22» / цифр.корни": "кросс-доменная нумерология, не выводится",
    }


def print_report() -> None:
    print("═" * 74)
    print("  ИНАЯ ТАБЛИЦА: порядок по ОТНОШЕНИЮ E_bind/A, а не по счёту Z")
    print("═" * 74)
    print("\n  ✓ НАСТОЯЩАЯ ФИЗИКА:")
    for n, (Z, A) in {"H-1": (1, 1), "He-4": (2, 4), "C-12": (6, 12),
                       "Fe-56": (26, 56), "Ni-62": (28, 62), "U-238": (92, 238)}.items():
        bar = "█" * int(binding_per_nucleon(Z, A) * 3)
        print(f"     {n:6} E_bind/A={binding_per_nucleon(Z,A):5.2f} {bar}")
    print(f"     Fe — пик (центр): {fe_is_peak()}  ·  до Fe синтез даёт энергию, после поглощает")
    print(f"     ΔZ=18 (d-блок): Ti↔Zr {homologous_pair(22,40)}, V↔Nb {homologous_pair(23,41)}")

    print("\n  ЧЕСТНЫЙ ЯРУС утверждений документа:")
    for k, v in claim_tiers().items():
        print(f"     {k}: {v}")
    print("═" * 74)
    print("  Реально: Fe=пик связи (центр), ΔZ=18=d-блок. Это и есть теория отношений")
    print("  в химии: порядок по связи-на-вещь, не по счёту. φ/22 — совпадения, не ключ.")
    print("═" * 74)


if __name__ == "__main__":
    print_report()
