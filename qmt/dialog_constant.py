"""
КОНСТАНТА ДИАЛОГА Ω_D — единый инвариант из трёх фундаментальных φ, e, π.

Задача: «одна математическая константа — расстояние между аспектами», но это
КОМБИНАЦИЯ φ, e, π (диалог генеративен — рождает миры). Принципиальный вывод:
свести три режима в ОДНО комплексное число.

        Ω_D = (φ−1) · e^{ i·2π/φ² }

где каждый фундаментальный играет свою роль (выведено, не подогнано):
    φ → МОДУЛЬ |Ω_D| = φ−1 = X*  — «расстояние между аспектами» (аттрактор);
    π → ФАЗА arg = золотой угол 2π/φ² ≈ 137.508°  — поворот, рождающий миры;
    e → НОСИТЕЛЬ: комплексная экспонента (Эйлер) — здесь e входит ТОЧНО
        (как основание), а не приближённо (ε_X≈e).

Свойства (проверено Wolfram/символьно):
  • |Ω_D| = φ−1 < 1  ⇒ итерация СХОДИТСЯ: аспекты не важны, инвариант один;
  • каждый шаг = поворот на золотой угол + сжатие φ−1 = золотая спираль «детей»
    (порождение миров-проекций);
  • особый случай фазы π: e^{iπ} = −1 = зеркало −I (рождение мира-двойника);
  • золотой угол 2π/φ² = 137.508° — угол филлотаксиса, рядом с α⁻¹≈137.

Точная опора (φ·π): резонанс модели Γ* = π/(4φ) = π(√5−1)/8 ≈ 0.4854 — реальная
константа, чистая комбинация π и φ (см. constants.GAMMA_STAR).
"""

from __future__ import annotations

import cmath
import math

PHI = (1 + math.sqrt(5)) / 2
E = math.e
PI = math.pi

GOLDEN_ANGLE = 2 * PI / PHI**2            # ≈ 2.39996 рад = 137.508°
OMEGA_D = (PHI - 1) * cmath.exp(1j * GOLDEN_ANGLE)


def modulus() -> float:
    """|Ω_D| = φ−1 = X* — единственная «дистанция» между аспектами."""
    return abs(OMEGA_D)


def phase_deg() -> float:
    """arg(Ω_D) = золотой угол 2π/φ² в градусах ≈ 137.508."""
    return math.degrees(cmath.phase(OMEGA_D))


def gamma_star_exact() -> float:
    """Резонанс Γ* = π/(4φ) — точная комбинация π·φ (опора с e отдельно)."""
    return PI / (4 * PHI)


def converges() -> bool:
    """Итерация Ω_D сходится (модуль<1): аспекты не важны, инвариант один."""
    return modulus() < 1.0


def child_worlds(n: int = 12) -> list[complex]:
    """n «детей»-миров: точки золотой спирали z_{k+1}=Ω_D·z_k (рождение миров)."""
    z = 1 + 0j
    out = []
    for _ in range(n):
        z = OMEGA_D * z
        out.append(z)
    return out


def roles() -> dict:
    return {
        "φ → модуль": f"|Ω_D| = φ−1 = {modulus():.6f}  (расстояние/аттрактор)",
        "π → фаза": f"золотой угол = {phase_deg():.3f}°  (поворот, рождение миров)",
        "e → носитель": "комплексная экспонента e^{i·} — e входит ТОЧНО",
        "зеркало": "фаза π ⇒ e^{iπ}=−1 = −I (особый случай)",
        "Γ* (φ·π, точно)": f"π/(4φ) = {gamma_star_exact():.6f}",
        "связь": f"золотой угол {phase_deg():.1f}° ≈ α⁻¹ 137 (филлотаксис)",
    }


def print_report() -> None:
    print("КОНСТАНТА ДИАЛОГА Ω_D = (φ−1)·e^{i·2π/φ²}")
    print("=" * 64)
    print(f"Ω_D = {OMEGA_D:.6f}")
    print(f"  |Ω_D| = φ−1 = {modulus():.10f}   (одна дистанция между аспектами)")
    print(f"  arg   = {phase_deg():.6f}°        (золотой угол 2π/φ²)")
    print(f"  сходится (|Ω_D|<1): {converges()}  ⇒ аспекты не важны, φ инвариант")
    print("\nроли трёх фундаментальных:")
    for k, v in roles().items():
        print(f"  {k}: {v}")
    print("=" * 64)
    print("φ — модуль (расстояние), π — фаза (поворот/рождение), e — носитель.")
    print("Статус: φπ-структура точна (Q1/Q2); это как ЕДИНАЯ константа — "
          "принципиальное предложение (Q2/Q3).")


if __name__ == "__main__":
    print_report()
