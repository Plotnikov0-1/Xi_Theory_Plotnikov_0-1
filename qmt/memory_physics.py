"""
═══════════════════════════════════════════════════════════════════════════
  MEMORY_PHYSICS — «Составитель карточек» (память) и «Мабу» (EP) как физика.
═══════════════════════════════════════════════════════════════════════════

Источник: сессия «Иные» 1996.06.11-1 «Мабу, Составитель карточек» + письмо RST
о памяти. Память и переход стоят в одном дне не случайно — у них общая физика.

Три слоя, от измеренного к выводимому:

  1. ПАМЯТЬ ЧЕЛОВЕКА (измеренная психология):
     • ёмкость кратковременной памяти 7±2 (Миллер 1956);
     • время удержания ~15–30 с (Петерсон 1959);
     • кривая забывания Эббингауза R(t)=e^{−t/τ};
     • эффект распределения (spacing): RST 14→4→8 повторений — минимум при
       оптимальном интервале (письмо RST: 30 с→14, 10 мин→4, 48 ч→8).

  2. ПАМЯТЬ КАК ε (карта с памятью): M_ε(x)=(1−ε)/(1+x)+ε·x — доля удержанного
     прошлого; неподвижная точка φ−1 при ЛЮБОМ ε (структура, не содержание).

  3. ПАМЯТЬ У EXCEPTIONAL POINT (Мабу): неэрмитова 2-уровневая система
     H=[[iΓ/2,λ],[λ,−iΓ/2]]. Время памяти (период возврата населённости)
            T(λ) = π/√(λ²−(Γ/2)²)
     РАСХОДИТСЯ при λ→Γ/2 (EP). У точки Мабу память становится ВЕЧНОЙ —
     вот почему составитель карточек и Мабу в одной сессии. (Реальный факт:
     немарковость максимальна у EP, arXiv:2406.18362.)

ЧЕСТНО. Слой 1 — измеренная психология; слой 3 — выводимая физика (проверено).
Отождествление «память человека = динамика у EP» — модельная аналогия, не вывод.

Запуск:  python -m qmt.memory_physics
"""

from __future__ import annotations

import cmath
import math

import numpy as np

# ── 1. Память человека (измеренная психология) ───────────────────────────────
MILLER_CAPACITY = 7          # 7±2 «кусков» (Miller 1956)
STM_SECONDS = 20             # удержание ~15–30 с (Peterson 1959)

# Письмо RST: число повторений в зависимости от интервала (эффект распределения).
RST_REPETITIONS = {"30 сек": 14, "10 мин": 4, "48 ч": 8}


def forgetting(t: float, tau: float = 1.0) -> float:
    """Кривая забывания Эббингауза: доля удержанного R(t)=e^{−t/τ}."""
    return math.exp(-t / tau)


def spacing_optimum() -> dict:
    """Эффект распределения: минимум повторений при оптимальном интервале."""
    best = min(RST_REPETITIONS, key=RST_REPETITIONS.get)
    return {"повторения": RST_REPETITIONS, "оптимум": best,
            "минимум": RST_REPETITIONS[best]}


# ── 2. Память как ε (карта с памятью) ────────────────────────────────────────
PHI = (1 + math.sqrt(5)) / 2


def memory_map(x: float, eps: float) -> float:
    """M_ε(x)=(1−ε)/(1+x)+ε·x — доля удержанного прошлого ε."""
    return (1 - eps) * (1.0 / (1.0 + x)) + eps * x


def memory_fixed_point(eps: float, x0: float = 0.3, n: int = 200) -> float:
    """Неподвижная точка φ−1 при ЛЮБОМ ε (память = структура, не содержание)."""
    x = float(x0)
    for _ in range(n):
        x = memory_map(x, eps)
    return x


# ── 3. Память у exceptional point (Мабу) ─────────────────────────────────────
def ep_lambda(Gamma: float = 1.0) -> float:
    """Положение EP (точка Мабу): λ = Γ/2."""
    return Gamma / 2


def memory_time(lam: float, Gamma: float = 1.0) -> float:
    """Время памяти = период возврата населённости T=π/√(λ²−(Γ/2)²).

    Определено в PT-симметричной фазе (λ>Γ/2); →∞ при λ→Γ/2 (EP)."""
    disc = lam**2 - (Gamma / 2) ** 2
    if disc <= 0:
        return math.inf            # на/под EP памяти-периода нет (или ∞)
    return math.pi / math.sqrt(disc)


def population(lam: float, t: float, Gamma: float = 1.0) -> float:
    """Населённость P(t)=|⟨1|ψ(t)⟩|² (нормир.) — осцилляции = возврат памяти."""
    H = np.array([[0.5j * Gamma, lam], [lam, -0.5j * Gamma]])
    w, V = np.linalg.eig(H)
    prop = V @ np.diag(np.exp(-1j * w * t)) @ np.linalg.inv(V)
    psi = prop @ np.array([1.0, 0.0], dtype=complex)
    psi = psi / np.linalg.norm(psi)
    return float(abs(psi[0]) ** 2)


def memory_diverges_at_ep(Gamma: float = 1.0) -> bool:
    """Проверка: при λ→EP+ время памяти растёт неограниченно."""
    lep = ep_lambda(Gamma)
    return memory_time(lep + 0.05, Gamma) > memory_time(lep + 0.5, Gamma) > \
        memory_time(lep + 2.0, Gamma)


def print_report() -> None:
    print("═" * 74)
    print("  ПАМЯТЬ: Составитель карточек + Мабу (EP) — одна физика")
    print("═" * 74)

    print("\n  1 · ПАМЯТЬ ЧЕЛОВЕКА (измеренная психология):")
    print(f"     ёмкость 7±2 (Миллер), удержание ~{STM_SECONDS} с (Петерсон)")
    sp = spacing_optimum()
    print(f"     повторения RST {sp['повторения']} → минимум {sp['минимум']} при «{sp['оптимум']}»")
    print(f"     забывание Эббингауза: R(1τ)={forgetting(1):.3f}, R(2τ)={forgetting(2):.3f}")

    print("\n  2 · ПАМЯТЬ КАК ε (структура, не содержание):")
    for eps in (0.0, 0.3, 0.9):
        print(f"     ε={eps}: неподвижная точка = {memory_fixed_point(eps):.6f} = φ−1")

    print("\n  3 · ПАМЯТЬ У EXCEPTIONAL POINT (Мабу), Γ=1, EP при λ=0.5:")
    for lam in (0.55, 0.75, 1.0, 2.0):
        print(f"     λ={lam:4}: время памяти T={memory_time(lam):.3f}")
    print(f"     λ→0.5 (EP): T→∞  — у точки Мабу память ВЕЧНА")
    print(f"     осцилляция (возврат памяти) P(t), λ=0.75: "
          f"{[round(population(0.75,t),2) for t in (0,2,4,6)]}")
    print(f"     память расходится у EP: {memory_diverges_at_ep()}")

    print("═" * 74)
    print("  Слой 1 — измеренная психология; слой 3 — выводимая физика (EP).")
    print("  «Память человека = динамика у EP» — модельная аналогия, не вывод.")
    print("  Но факт точен: у exceptional point время памяти расходится.")
    print("═" * 74)


if __name__ == "__main__":
    print_report()
