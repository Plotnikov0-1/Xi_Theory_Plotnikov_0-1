"""
═══════════════════════════════════════════════════════════════════════════
  RELATIONS — ГЛАВНАЯ ТЕОРИЯ: реальность несут ОТНОШЕНИЯ, а не вещи.
═══════════════════════════════════════════════════════════════════════════

Центральный принцип (соотношение раньше числа):

  Содержание физической системы = множество её БЕЗРАЗМЕРНЫХ ОТНОШЕНИЙ.
  Сменишь единицы — отношения не меняются. Сменишь масштаб — инвариант тот же.
  «Вещи» (переменные с единицами) — конвенция; ИНВАРИАНТНЫ только отношения.

Это не «теория всего», а строгая опора: теорема Бакингема-Пи (1914, доказана) +
структурный реализм (реальность = связи, не релята). Все остальные модули
пакета — частные случаи этого: они вычисляют конкретные отношения.

ЧЕТЫРЕ операции над отношениями (из них растёт всё):
  1. ОТНОШЕНИЕ a:b          — базовая связь (число = след отношения);
  2. ЗЕРКАЛО R: r ↦ 1/r     — инверсия −I; пары r и 1/r; R²=I (группа Z₂);
  3. САМОПРОИЗВЕДЕНИЕ r·r*   — связь, замкнутая на себя → наблюдаемое (Борн, E=mc²);
  4. НЕПОДВИЖНАЯ ТОЧКА       — отношение, воспроизводящее себя: x*=1/(1+x*)=φ−1.

Запуск:  python -m qmt.relations
"""

from __future__ import annotations

import math
from dataclasses import dataclass

PHI = (1 + math.sqrt(5)) / 2

# ── Базовые величины (CODATA) для вычисления отношений ───────────────────────
C = 2.99792458e8; E_CH = 1.602176634e-19; EPS0 = 8.8541878128e-12
HBAR = 1.054571817e-34; M_E = 9.1093837015e-31
ALPHA = E_CH**2 / (4 * math.pi * EPS0 * HBAR * C)


@dataclass
class Relation:
    name: str
    value: float
    relates: str          # что к чему
    status: str           # ✓ эксперимент / ◇ точная математика / ≈ данные / ○ модель


# ── КАТАЛОГ настоящих отношений (всё, что мы нашли — это отношения) ───────────
def catalog() -> list[Relation]:
    return [
        Relation("α = v₁/c", ALPHA, "скорость электрона / скорость света = 1/137.036", "✓"),
        Relation("E/(mc²) = 1", 1.0, "энергия / (масса·c²) — тождество", "✓"),
        Relation("E_св/(m_e c²)", ALPHA**2 / 2, "связь H / энергия покоя = α²/2", "✓"),
        Relation("λ_C/a₀ = α", ALPHA, "Комптон / Бор — каскад масштабов", "✓"),
        Relation("x* = φ−1", PHI - 1, "неподвижная точка 1/(1+x): самосогласование", "◇"),
        Relation("Op_4 = T_вх/T_вых", (4 / PHI) / (1 / PHI), "трещина-вход / выход = 4", "◇"),
        Relation("2cos(π/5) = φ", 2 * math.cos(math.pi / 5), "φ↔π (Coldea, E₈)", "✓"),
        Relation("Солнце: 4/12 = 1/3", 4 / 12, "возраст системы / жизнь Солнца", "≈"),
        Relation("|Ω_D| = φ−1", PHI - 1, "модуль константы диалога", "○"),
    ]


# ── Четыре операции над отношениями ──────────────────────────────────────────
def ratio(a: float, b: float) -> float:
    """1. Отношение a:b — базовая связь."""
    return a / b


def mirror(r: float) -> float:
    """2. Зеркало R: r ↦ 1/r (инверсия −I)."""
    return 1.0 / r


def mirror_is_involution(r: float = 2.5) -> bool:
    """R²=I: двойное зеркало возвращает (группа Z₂)."""
    return math.isclose(mirror(mirror(r)), r, rel_tol=1e-12)


def self_product(z: complex) -> float:
    """3. Самопроизведение z·z* → вещественное наблюдаемое (Борн, квадрат)."""
    return (z * z.conjugate()).real


def fixed_point() -> float:
    """4. Неподвижная точка отношения x=1/(1+x): воспроизводит себя = φ−1."""
    x = 0.5
    for _ in range(60):
        x = 1.0 / (1.0 + x)
    return x


def is_dimensionless_invariant(value: float, unit_change: float) -> bool:
    """Главное свойство: отношение НЕ меняется при смене единиц (×масштаб)."""
    # величины a,b → a·k, b·k; отношение a/b неизменно
    a, b = value, 1.0
    return math.isclose((a * unit_change) / (b * unit_change), a / b, rel_tol=1e-12)


def print_report() -> None:
    print("═" * 76)
    print("  ТЕОРИЯ ОТНОШЕНИЙ — реальность несут связи, а не вещи")
    print("  (Бакингем-Пи + структурный реализм; соотношение раньше числа)")
    print("═" * 76)

    print("\n  ЧЕТЫРЕ ОПЕРАЦИИ над отношениями:")
    print(f"     1. отношение a:b      — напр. 4:12 = {ratio(4,12):.4f} = 1/3")
    print(f"     2. зеркало R: r↦1/r   — R²=I (Z₂): {mirror_is_involution()}")
    print(f"     3. самопроизв. z·z*   — |1/√2+i/√2|² = {self_product(1/math.sqrt(2)+1j/math.sqrt(2)):.3f} (наблюдаемое)")
    print(f"     4. неподвижная точка  — x=1/(1+x) → {fixed_point():.6f} = φ−1")
    print(f"     инвариантность к единицам (×1e9): {is_dimensionless_invariant(ALPHA,1e9)}")

    print("\n  КАТАЛОГ настоящих отношений (всё найденное — это ОТНОШЕНИЯ):")
    print("     ✓ эксперимент · ◇ точная математика · ≈ данные · ○ модель")
    for r in catalog():
        print(f"     [{r.status}] {r.name:20} = {r.value:.6g}   ({r.relates})")

    print("═" * 76)
    print("  Числа — следы отношений. Меняешь единицы/масштаб — отношение то же.")
    print("  Это не «теория всего», а принцип чтения: инвариант = связь, не вещь.")
    print("═" * 76)


if __name__ == "__main__":
    print_report()
