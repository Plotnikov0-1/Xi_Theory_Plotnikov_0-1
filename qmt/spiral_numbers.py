"""
═══════════════════════════════════════════════════════════════════════════
  SPIRAL_NUMBERS — числа как СПИРАЛЬ: стрела времени всегда вперёд. Честно.
═══════════════════════════════════════════════════════════════════════════

Идея автора (вариант B, уточнённый): старт с 10 = «1:0» — из ЦЕНТРА-ИСТОКА,
где 0 — исток, а 1 рождается ЗА нулём (старая геометрия: всё из центра).
Числа наматываются как винт: позиция на круге возвращается, само число — нет.

  ◇ доказано точно (арифметика) · ○ чтение старой геометрии (центр-исток, 1 за 0)

────────────────────────────────────────────────────────────────────────────
○ СТАРТ С 10 = «1:0»: пара (1,0). 0 — центр/исток, 1 — «за нулём» (рождается из
  центра). Порядок рождения: 0 → 1 → 2 → … (единица позади нуля, не перед ним).

◇ ТРИ ЗЕРО (triad_zeros): {1,4,7}+10 · {2,5,8}+11 · {3,6,9}+12 → 10, 11, 12.

◇ 40 — ПОЛНАЯ МЕРА: 40 = 120/3 (группа икосаэдра ÷ 3 семьи) = 4·10 (кольцо-шестерня).

◇ СТРЕЛА ВРЕМЕНИ: число n растёт МОНОТОННО (всегда вперёд); позиция на круге
  = ((n−1) mod 12)+1 — повторяется. «Даже если отходим назад» — назад по позиции,
  но число не убывает. Это спираль (винт), а не круг.

Запуск:  python -m qmt.spiral_numbers
"""

from __future__ import annotations

ZEROS = [10, 11, 12]          # три зеро (triad_zeros)


def center_start() -> dict:
    """○ старт с 10 = «1:0»: 0 исток/центр, 1 рождается ЗА нулём (0→1→2…)."""
    return {"старт": 10, "как пара": "1:0", "0": "исток/центр",
            "1": "за нулём (рождается из центра)", "порядок": "0 → 1 → 2 → …"}


def three_zeros() -> list:
    """◇ три зеро из triad_zeros: 10, 11, 12."""
    return list(ZEROS)


def forty_full_measure() -> dict:
    """◇ 40 = 120/3 = 4·10 — полная мера (икосаэдр÷3 семьи; кольцо-шестерня)."""
    return {"40": 40, "=120/3": 120 // 3 == 40, "=4·10": 4 * 10 == 40,
            "смысл": "полный оборот меры / кольцо"}


def spiral_position(n: int, base: int = 12) -> int:
    """◇ позиция числа n на круге (циклится); само n — монотонно вперёд."""
    return ((n - 1) % base) + 1


def arrow_always_forward(seq_len: int = 24, base: int = 12) -> dict:
    """◇ число всегда растёт, позиция повторяется — спираль, не круг."""
    nums = list(range(1, seq_len + 1))
    positions = [spiral_position(n, base) for n in nums]
    monotone = all(nums[i] < nums[i + 1] for i in range(len(nums) - 1))
    repeats = len(set(positions)) < len(positions)     # позиции повторяются
    return {"числа монотонны (вперёд)": monotone,
            "позиции повторяются (круг)": repeats,
            "спираль (винт), не круг": monotone and repeats}


def print_report() -> None:
    print("═" * 78)
    print("  ЧИСЛА КАК СПИРАЛЬ — стрела времени вперёд; старт из центра (10=1:0)")
    print("═" * 78)
    print(f"\n  ○ старт-центр: {center_start()}")
    print(f"\n  ◇ три зеро: {three_zeros()}")
    print(f"\n  ◇ 40 полная мера: {forty_full_measure()}")
    print(f"\n  ◇ стрела вперёд (спираль): {arrow_always_forward()}")
    print("\n  спираль позиций (n → позиция), число не повторяется:")
    for n in range(1, 25):
        z = "  ← зеро" if spiral_position(n) in (10, 11, 12) else ""
        if spiral_position(n) in (10, 11, 12) or n in (1, 24):
            print(f"     n={n:2} → поз {spiral_position(n):2}{z}")
    print("═" * 78)
    print("  Старт с 10=«1:0» (0 исток, 1 за нулём). Три зеро 10,11,12. 40=120/3=4·10.")
    print("  Число всегда вперёд, позиция циклится — винт, не круг. ◇ / ○ (центр-исток).")
    print("═" * 78)


if __name__ == "__main__":
    print_report()
