"""
═══════════════════════════════════════════════════════════════════════════
  OPUS_ALGORITHM — последние документы Опуса (ПЛ-01М…05М), развёрнутые в
  рабочую проверенную математику. Самые релевантные по последовательности.
═══════════════════════════════════════════════════════════════════════════

Источник: папка ОПУС, серия ПЛ (Плотников Л.В., 20 июня 2026):
  01М Числа-и-Алгоритм · 02М Конструкция-Формулы · 03М Время-и-Пузырь ·
  04М Единая-Энергия-и-Двойственность · 05М Передача-Знания.

Ядро всех пяти — один алгоритм и его точные следствия (проверено Wolfram):

  Алгоритм:   T(x) = 1/(1+x)
  След:       x* = φ−1 = (√5−1)/2  (неподвижная точка, не вставленная константа)
  Скорость:   |T′(x*)| = 1/φ²  ≈ 0.382   (знание→понимание)
  Квадрат:    (T∘T)′(x*) = 1/φ⁴  = (T′)²  (двойное самоприменение — «почему квадрат»)
  Память:     M_ε(x) = (1−ε)/(1+x) + ε·x  — x* = φ−1 при ЛЮБОМ ε
  Граница:    ε_крит = (5−√5)/10 ≈ 0.276  — сходимость за один шаг (наклон=0)
  Щель:       Δ₇ = √5−2 = 2(φ−1)−1 = (φ−1)³   ← «двойное дно»: линейно снаружи,
                                                  кубически внутри (тень памяти)
  Двойств.:   наблюдаемое = ψ·ψ*  ;  электрон: a·ω = c

ЧЕСТНО. Левая колонка — точная математика (Wolfram True). Физические прочтения
(«память», «пузырь», «CP-нарушение», «передача знания») — интерпретации этих
точных фактов, а не выведенная из них новая физика. Δ₇=(φ−1)³ — точное тождество
φ-алгебры; что Δ₇ есть именно физическая щель CP — модельное прочтение.

Запуск:  python -m qmt.opus_algorithm
"""

from __future__ import annotations

import math

PHI = (1 + math.sqrt(5)) / 2
X_STAR = PHI - 1                    # = (√5−1)/2 ≈ 0.618 — след алгоритма


# ── 01М · Алгоритм и его след ────────────────────────────────────────────────
def T(x: float) -> float:
    """Простейший алгоритм: T(x) = 1/(1+x). Никаких заданных чисел."""
    return 1.0 / (1.0 + x)


def iterate(x0: float, n: int = 40) -> float:
    """Запусти алгоритм n раз — выходит на след x* = φ−1 из любого старта."""
    x = float(x0)
    for _ in range(n):
        x = T(x)
    return x


def contraction_rate() -> float:
    """|T′(x*)| = 1/φ² ≈ 0.382 — скорость сходимости (знание → понимание)."""
    return 1.0 / PHI**2


# ── 02М · Конструкция формулы: почему квадрат ────────────────────────────────
def double_apply_rate() -> float:
    """(T∘T)′(x*) = 1/φ⁴ = (T′(x*))² — квадрат как двойное самоприменение."""
    return 1.0 / PHI**4


def emc2_log_slope() -> float:
    """log E = log m + 2·log c. Наклон по log c равен 2 — это и есть «квадрат»."""
    return 2.0


def continued_fraction_phi(depth: int = 30) -> float:
    """φ = [1;1,1,1,…] — просто снаружи, бесконечно вложено внутри."""
    x = 1.0
    for _ in range(depth):
        x = 1.0 + 1.0 / x
    return x


# ── 03М · Время и пузырь: память и граница ───────────────────────────────────
def memory_map(x: float, eps: float) -> float:
    """M_ε(x) = (1−ε)/(1+x) + ε·x — алгоритм с памятью ε (доля прошлого)."""
    return (1 - eps) * (1.0 / (1.0 + x)) + eps * x


def memory_fixed_point(eps: float, x0: float = 0.3, n: int = 200) -> float:
    """Неподвижная точка карты памяти. Для ЛЮБОГО ε сходится к x* = φ−1."""
    x = float(x0)
    for _ in range(n):
        x = memory_map(x, eps)
    return x


def eps_crit() -> float:
    """ε_крит = (5−√5)/10 = 2/(5+√5): наклон M′ обнуляется → сходимость за 1 шаг."""
    return (5 - math.sqrt(5)) / 10


# ── 04М/05М · Двойственность и двойное дно ───────────────────────────────────
def delta7_forms() -> dict:
    """Δ₇ тремя точными формами (Wolfram True): след, линейная, кубическая."""
    return {
        "√5−2": math.sqrt(5) - 2,
        "2(φ−1)−1": 2 * (PHI - 1) - 1,        # линейно снаружи
        "(φ−1)³": (PHI - 1) ** 3,             # кубически внутри (куб памяти)
    }


def born_observable(psi: complex) -> float:
    """Наблюдаемое = ψ·ψ* (единое ψ ненаблюдаемо; пара ψ·ψ* — реальность)."""
    return (psi * psi.conjugate()).real


def electron_a_omega_c() -> dict:
    """Электрон как двойственность: a·ω = c (длина × частота = инвариант)."""
    hbar = 1.054571817e-34; m = 9.1093837015e-31; c = 2.99792458e8
    a = hbar / (m * c)          # геометрическая длина (пространство)
    omega = m * c**2 / hbar     # внутренняя частота (время)
    return {"a": a, "ω": omega, "a·ω": a * omega, "c": c}


def print_report() -> None:
    print("═" * 74)
    print("  OPUS-АЛГОРИТМ — последние документы (ПЛ-01М…05М) в рабочей форме")
    print("═" * 74)

    print("\n  01М · АЛГОРИТМ T(x)=1/(1+x) → след x*=φ−1:")
    for x0 in (0.1, 2.0, 100.0):
        print(f"     из x₀={x0:>6}: → {iterate(x0):.9f}")
    print(f"     |T′(x*)| = 1/φ² = {contraction_rate():.6f}  (скорость: знание→понимание)")

    print("\n  02М · ПОЧЕМУ КВАДРАТ (двойное самоприменение):")
    print(f"     (T∘T)′(x*) = 1/φ⁴ = {double_apply_rate():.6f} = (1/φ²)² ✓")
    print(f"     log E = log m + 2·log c → наклон = {emc2_log_slope():.0f}  (это и есть c²)")
    print(f"     φ = [1;1,1,1,…] = {continued_fraction_phi():.9f}  (просто снаружи, ∞ внутри)")

    print("\n  03М · ПАМЯТЬ: неподвижная точка φ−1 при ЛЮБОМ ε:")
    for eps in (0.0, 0.276, 0.5, 0.9):
        print(f"     ε={eps:.3f} → x* = {memory_fixed_point(eps):.9f}")
    print(f"     ε_крит = (5−√5)/10 = {eps_crit():.6f}  (сходимость за один шаг)")

    print("\n  04М/05М · ДВОЙНОЕ ДНО — Δ₇ тремя формами (все Wolfram True):")
    for k, v in delta7_forms().items():
        print(f"     Δ₇ = {k:<10} = {v:.9f}")
    print(f"     ↑ линейно снаружи 2(φ−1)−1, кубически внутри (φ−1)³ — одно число")
    aw = electron_a_omega_c()
    print(f"     электрон: a·ω = {aw['a·ω']:.6e} = c = {aw['c']:.6e} ✓")
    print(f"     наблюдаемое ψ·ψ*: |1/√2 + i/√2|² = {born_observable(1/math.sqrt(2)+1j/math.sqrt(2)):.3f}")

    print("═" * 74)
    print("  Точная математика (Wolfram): T→φ−1, 1/φ², 1/φ⁴, Δ₇=(φ−1)³, ε∀.")
    print("  Прочтения (память, пузырь, передача, CP) — интерпретации этих фактов,")
    print("  не выведенная из них новая физика. Граница честно сохранена.")
    print("═" * 74)


if __name__ == "__main__":
    print_report()
