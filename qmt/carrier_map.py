"""
═══════════════════════════════════════════════════════════════════════════
  CARRIER_MAP — единая карта: ГЕОМЕТРИЧЕСКИЙ НОСИТЕЛЬ → оператор → константа.
═══════════════════════════════════════════════════════════════════════════

Разные роли в многограннике несут разные типы физики. Ключ: одно и то же тело
даёт РАЗНЫЕ константы на разных носителях (расстояние/угол/счёт/температура).

  НОСИТЕЛЬ     оператор           константа                физика
  ─────────────────────────────────────────────────────────────────────────
  ВЕРШИНЫ      состояния {1..9}   E_n=−13.6/n²             уровни (счёт)          ✓
  РЁБРА        φ {1,4,7}          серед. сфера: φ/2,φ²/2   переход, вибрация (ΔE↓) ◇
  ГРАНИ        π {3,6,9}          контур p=3,4,5           спектр/цвет (ΔE↑)      ◇○
  УГЛЫ         π (стык)           двугранный угол          как грани сходятся     ◇
  ДИАГОНАЛИ    √2 {2,5,8}         √2, R=a (кубоктаэдр)     зеркало −I, хиазма     ◇
  ЦЕНТР        5                  ψ₅ₛ(0)≠0                 бифуркация μ=0.5       ✓○
  ОБОЛОЧКА     0                  n→∞                      ионизация              ✓
  ТЕМПЕРАТУРА  уместность         T_n (Больцман×Саха)      узел×среда             ✓

◇ ПРОВЕРЕНО (машиной): Шлефли V=4p/D,E=2pq/D,F=4q/D (D=4−(p−2)(q−2)); двугранные
  углы; тетра+окта: arccos(⅓)+arccos(−⅓)=π (замощение); кубооктаэдр R=ребро.
✓ ФИЗИКА: E_n, T_n(Больцман×Саха), Эйнштейн A∝ω³ ⇒ стрела = наш J(ω)∝ω³.
○ ИНТЕРПРЕТАЦИЯ (не факт): привязка ролей к «операторам {1,4,7}/{3,6,9}»,
  «спектр красит грани», температура-как-уместность.

Идея «спектр на гранях, вибрация на рёбрах»: грань = замкнутый контур (p сторон)
= частота (условие Бора); ребро = малая ΔE (колебательная). Разведено по носителям.

Запуск:  python -m qmt.carrier_map
"""

from __future__ import annotations

import math

# ── ◇ Шлефли: два локальных числа {p,q} задают всё тело ──────────────────────
SOLIDS = {
    "тетраэдр": (3, 3), "куб": (4, 3), "октаэдр": (3, 4),
    "додекаэдр": (5, 3), "икосаэдр": (3, 5),
}


def schlafli_counts(p: int, q: int) -> tuple:
    """◇ V,E,F из {p,q}: V=4p/D, E=2pq/D, F=4q/D, D=4−(p−2)(q−2)."""
    D = 4 - (p - 2) * (q - 2)
    return (4 * p // D if (4 * p) % D == 0 else 4 * p / D,
            2 * p * q // D if (2 * p * q) % D == 0 else 2 * p * q / D,
            4 * q // D if (4 * q) % D == 0 else 4 * q / D)


def euler_holds() -> bool:
    """◇ Для всех пяти тел V−E+F=2 (проверка формулы Шлефли-счёта)."""
    for p, q in SOLIDS.values():
        V, E, F = schlafli_counts(p, q)
        if V - E + F != 2:
            return False
    return True


# ── ◇ Рёбра: серединная сфера (носитель φ) ──────────────────────────────────
def midsphere_radius(name: str) -> float:
    """◇ Срединный радиус (ребро=1). Для p=5 содержит φ: икоса φ/2, додека φ²/2."""
    phi = (1 + math.sqrt(5)) / 2
    table = {"тетраэдр": 1 / math.sqrt(8), "куб": 1 / math.sqrt(2),
             "октаэдр": 0.5, "икосаэдр": phi / 2, "додекаэдр": phi**2 / 2}
    return table[name]


def phi_lives_on_p5_edges() -> bool:
    """◇ φ входит в срединную сферу семейства p=5 (икоса=φ/2=cos π/5)."""
    phi = (1 + math.sqrt(5)) / 2
    return math.isclose(midsphere_radius("икосаэдр"), phi / 2) and \
        math.isclose(phi / 2, math.cos(math.pi / 5))


# ── ◇ Углы: двугранный (носитель условия стыковки) ──────────────────────────
def dihedral_angle(name: str) -> float:
    """◇ Двугранный угол (радианы) — константа НА ребре, как сходятся грани."""
    table = {"тетраэдр": math.acos(1 / 3), "куб": math.pi / 2,
             "октаэдр": math.acos(-1 / 3), "додекаэдр": math.acos(-1 / math.sqrt(5)),
             "икосаэдр": math.acos(-math.sqrt(5) / 3)}
    return table[name]


def tetra_octa_tile() -> bool:
    """◇ arccos(⅓)+arccos(−⅓)=π → тетраэдры+октаэдры замощают пространство."""
    return math.isclose(dihedral_angle("тетраэдр") + dihedral_angle("октаэдр"), math.pi)


# ── ◇ Диагонали/центр: кубооктаэдр R=ребро (вектор-равновесие 12 узлов) ──────
def cuboctahedron_balance() -> bool:
    """◇ Кубооктаэдр: R=ребро. Вершины = перестановки (±1,±1,0), 12 штук.
    Circumradius=|(1,1,0)|=√2; ребро=|(1,1,0)−(1,0,1)|=√2 → R=a (равновесие)."""
    from itertools import permutations
    verts = set()
    for base in ((1, 1, 0), (1, -1, 0), (-1, 1, 0), (-1, -1, 0)):
        for pm in permutations(base):
            verts.add(pm)
    verts = list(verts)
    assert len(verts) == 12, "кубооктаэдр = 12 вершин"
    R = math.dist((0, 0, 0), verts[0])
    edge = min(math.dist(verts[0], v) for v in verts[1:])
    return math.isclose(R, edge)


# ── ✓ Стрела: Эйнштейн A∝ω³ = наш резервуар J(ω)∝ω³ ──────────────────────────
def arrow_from_omega_cubed() -> bool:
    """✓ Спонтанный распад A21∝ω³ (Эйнштейн 1917); вверх спонтанно нельзя.
    Тот же куб частоты, что супер-омический резервуар J(ω)=J₀ω³·e^(−ω/ωc)."""
    A = lambda w: w**3
    return A(2) == 8 and A(2) > A(1)      # растёт как ω³ (односторонняя стрела)


def print_report() -> None:
    print("═" * 74)
    print("  КАРТА НОСИТЕЛЕЙ: вершина/ребро/грань/угол/диагональ/центр → константа")
    print("═" * 74)
    print("\n  ◇ Шлефли {p,q} → V,E,F (V−E+F=2 для всех):", euler_holds())
    for name, (p, q) in SOLIDS.items():
        V, E, F = schlafli_counts(p, q)
        print(f"     {name:10} {{{p},{q}}}  V={V:2} E={E:2} F={F:2}  "
              f"ρ_серед={midsphere_radius(name):.4f}  двугр={math.degrees(dihedral_angle(name)):6.2f}°")

    print(f"\n  ◇ РЁБРА: φ в срединной сфере p=5 (икоса=φ/2=cos π/5): {phi_lives_on_p5_edges()}")
    print(f"  ◇ УГЛЫ: тетра+окта замощают (arccos⅓+arccos−⅓=π): {tetra_octa_tile()}")
    print(f"  ◇ ДИАГ/ЦЕНТР: кубооктаэдр R=ребро (12 узлов, равновесие): {cuboctahedron_balance()}")
    print(f"  ✓ СТРЕЛА: Эйнштейн A∝ω³ = наш J(ω)∝ω³ (вниз само, вверх нельзя): {arrow_from_omega_cubed()}")

    print("\n  У каждого узла теперь ЧЕТЫРЕ типа константы:")
    print("     расстояние (ρ серед.сферы) · угол (двугранный) · счёт (V,E,F) · T_n")
    print("═" * 74)
    print("  ◇ Шлефли/углы/кубооктаэдр — точная геометрия; ✓ стрела A∝ω³=J(ω).")
    print("  ○ привязка ролей к операторам {1,4,7}/{3,6,9} и «спектр на гранях» — модель.")
    print("═" * 74)


if __name__ == "__main__":
    print_report()
