"""
═══════════════════════════════════════════════════════════════════════════
  CP_ASYMMETRY — СТРУКТУРНЫЙ индекс асимметрии по номерам узлов (ярус ○).
═══════════════════════════════════════════════════════════════════════════

ВАЖНО (честно, сразу): это НЕ закон CP-нарушения в физике частиц. Это
структурный индекс: арифметическое зеркало n↔10−n (вокруг центра 5) НЕ есть
зеркало по энергии, потому что 1/n² нелинейно. Формула ловит именно эту
«неточность фигуры» — и как СТРУКТУРНЫЙ образ она хороша, как физика CP — только
аналогия (в каонах A~10⁻³, здесь A~0.3 — совпадает конструкция, не число).

  A(n) = 1 − n²(15−n)/250          (пара n ↔ 10−n)

  A(1)=118/125  A(2)=99/125  A(3)=71/125  A(4)=37/125  A(5)=0

◇ ЧТО ТОЧНО (арифметика):
  • A(5)=0 — единственный ноль, ровно в центре (5↔5, перехода нет).
    «Точное зеркало ⇔ мира нет» (образ связки Сахарова: δ=0 ⇒ нет асимметрии).
  • знаменатель 125=5³ — но честно: 250=2·125, сокращение на 2, а не «магия 5³».
  • минимум среди РЕАЛЬНЫХ пар — 4↔6 (37/125≈0.30): ближе всех к точному
    зеркалу, но не точен — «шёпот» = минимальное отклонение ≠ 0.

Связь с реальным энергетическим квантом пары (это уже ✓ физика, отдельно):
  ΔE(n) = 13.6·|1/n² − 1/(10−n)²| эВ — минимальна у 4↔6 (0.472 эВ, ИК, «незаметна»).

Запуск:  python -m qmt.cp_asymmetry
"""

from __future__ import annotations

from fractions import Fraction

RY_EV = 13.6                       # энергия Ридберга (эВ), для реального кванта


def asymmetry(n: int) -> Fraction:
    """○ Структурный индекс A(n)=1−n²(15−n)/250 (точная дробь)."""
    return Fraction(1) - Fraction(n * n * (15 - n), 250)


def asymmetry_table() -> dict:
    """A(n) для n=1..5 в несократимых дробях."""
    return {n: asymmetry(n) for n in range(1, 6)}


def center_is_only_zero() -> bool:
    """◇ A(n)=0 только при n=5 (центр, 5↔5): единственная нулевая асимметрия."""
    return all((asymmetry(n) == 0) == (n == 5) for n in range(1, 10))


def denominator_is_two_times_125() -> bool:
    """Честно: '5³' — артефакт 250=2·125, не смысл. Проверяем 250=2·5³."""
    return 250 == 2 * 5**3


def whisper_pair_is_minimal() -> bool:
    """○ Среди реальных пар (n=1..4) минимум |A| у n=4 (пара 4↔6) — «шёпот»."""
    vals = {n: abs(asymmetry(n)) for n in range(1, 5)}
    return min(vals, key=vals.get) == 4


def energy_quantum_eV(n: int) -> float:
    """✓ Реальный квант пары n↔10−n: ΔE=13.6·|1/n²−1/(10−n)²| эВ."""
    m = 10 - n
    return RY_EV * abs(1 / n**2 - 1 / m**2)


def print_report() -> None:
    print("═" * 74)
    print("  CP_ASYMMETRY: структурный индекс A(n) (○, НЕ физика CP частиц)")
    print("═" * 74)
    print("\n  A(n) = 1 − n²(15−n)/250   (пара n ↔ 10−n):")
    for n, a in asymmetry_table().items():
        pair = f"{n}↔{10-n}" if n != 5 else "5↔5 (центр)"
        q = f"  ΔE={energy_quantum_eV(n):.3f} эВ" if n != 5 else "  перехода нет"
        print(f"     A({n}) = {str(a):>7}  пара {pair:11}{q}")
    print(f"\n  ◇ единственный ноль — центр (5↔5): {center_is_only_zero()}")
    print(f"  честно: 250=2·125, '5³' — артефакт сокращения на 2: {denominator_is_two_times_125()}")
    print(f"  ○ шёпот 4↔6 — минимальная асимметрия реальных пар: {whisper_pair_is_minimal()}")
    print(f"     реальный смысл шёпота — квант 4↔6 = {energy_quantum_eV(4):.3f} эВ (ИК, «незаметен»)")
    print("═" * 74)
    print("  Ярус ○: структурный индекс неточности зеркала (1/n² нелинейно).")
    print("  Как физику CP не подаём: конструкция та же, число (A~0.3) — нет.")
    print("═" * 74)


if __name__ == "__main__":
    print_report()
