    for k, v in verify().items():
        print(f"  [{'✓' if v else '✗'}] {k}")
    print("=" * 60)
    print("Физика (Q0/Q1): тройка вынуждена SU(3). Резонанс 27=3³ с числом букв и")
    print("связь Б↔барион↔начало вещества (cp_baryogenesis) — интерпретация (Q3).")


