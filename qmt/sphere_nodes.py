"""
═══════════════════════════════════════════════════════════════════════════
  SPHERE_NODES — счёт узлов и операторов перехода на сфере-восьмёрок (5:3).
═══════════════════════════════════════════════════════════════════════════

Просьба автора: «у нас есть операторы перехода, они связаны с переходами —
посчитать их количество». Здесь точный счёт того, что считается точно (◇),
и один численный результат (≈).

  ◇ — доказано точно (арифметика частот)
  ≈ — численный счёт (самопересечения)
  ○ — интерпретация (шестерни = операторы)

────────────────────────────────────────────────────────────────────────────
◇ ДВЕ ЧАСТОТЫ = ДВА «ЗУБЧАТЫХ КОЛЕСА» (операторы перехода):
    a=5 — вертикальный оператор (касания полюса), b=3 — оборот по долготе.
    5 и 3 — СОСЕДНИЕ Фибоначчи; их отношение — золотая передача (→ φ).
    Сцепление колёс: LCM(5,3)=15 (в Wolfram период 15π = меш-число).

◇ ТОЧНЫЕ СЧЁТЫ за минимальный период 2π (gcd(5,3)=1 ⇒ период 2π, Erb):
    пересечений экватора (z=sin(5t)=0):  2a = 10;
    проходов через полюса (z=±1):        a=5 северных + a=5 южных → 2 точки (ось 1–9);
    оборотов по долготе:                 b = 3.

≈ САМОПЕРЕСЕЧЕНИЯ (узлы кривой), численно: ~35 обычных двойных + 2 полюса
    (каждый полюс кратности 5). Это «места встречи» ветвей = где переход
    «сшивает» разные участки. Точная формула — Erb (arXiv:1802.06546).

○ ШЕСТЕРНИ В ЦЕНТРЕ ЧАСОВ = операторы перехода (гипотеза, проверяемо):
    зубья колёс = частоты. Если счёт зубьев даёт Фибоначчи-соседей (3,5,8,13)
    или отношение ≈ φ — это буквально наши операторы. ТРЕБУЕТСЯ: сосчитать зубья.

Запуск:  python -m qmt.sphere_nodes
"""

from __future__ import annotations

import math

A, B = 5, 3   # частоты: вертикаль (полюс) и долгота


def gears() -> dict:
    """◇ две частоты = два колеса; 5,3 соседи Фибоначчи; отношение → φ."""
    fib = [1, 1, 2, 3, 5, 8, 13]
    return {"колесо-верт a": A, "колесо-долгота b": B,
            "соседи Фибоначчи": A in fib and B in fib and fib[fib.index(B) + 1] == A,
            "передаточное a/b": round(A / B, 4), "φ": round((1 + 5 ** 0.5) / 2, 4),
            "LCM (меш)": math.lcm(A, B)}


def exact_counts() -> dict:
    """◇ точные счёты за период 2π: экватор 2a, полюса a+a, долгота b."""
    return {"период (gcd=1)": "2π",
            "пересечений экватора": 2 * A,           # 10
            "проходов полюса N": A, "проходов полюса S": A,  # 5+5
            "оборотов долготы": B,                    # 3
            "LCM(a,b)": math.lcm(A, B)}               # 15


def equator_crossings_count() -> int:
    """◇ число нулей z=sin(a t) на [0,2π) = 2a (проверка перебором корней)."""
    roots = [k * math.pi / A for k in range(2 * A)]      # t = kπ/a, k=0..2a-1
    return sum(1 for t in roots if abs(math.sin(A * t)) < 1e-9)


def self_intersections_numeric(samples: int = 40000) -> dict:
    """≈ численный счёт самопересечений (узлов) кривой 5:3 за период 2π."""
    from collections import defaultdict
    def P(t):
        ca, sa, cb, sb = (math.cos(A * t), math.sin(A * t),
                          math.cos(B * t), math.sin(B * t))
        return (sb * ca, cb * ca, sa)
    g = defaultdict(list)
    for i in range(samples):
        key = tuple(round(c, 3) for c in P(2 * math.pi * i / samples))
        g[key].append(i)
    nodes = poles = 0
    for key, idxs in g.items():
        if len(idxs) < 2:
            continue
        idxs = sorted(idxs)
        branches, cur = [], [idxs[0]]
        for x in idxs[1:]:
            (cur.append(x) if x - cur[-1] <= 3 else (branches.append(cur), cur.__setitem__(slice(None), [x])))
        branches.append(cur)
        if len(branches) > 1 and idxs[0] <= 3 and (samples - 1 - idxs[-1]) <= 3:
            branches[0] = branches[-1] + branches[0]
            branches.pop()
        if len(branches) >= 2:
            nodes += 1
            if abs(abs(key[2]) - 1.0) < 1e-2:
                poles += 1
    return {"узлов (~)": nodes, "из них полюса": poles}


def print_report() -> None:
    print("═" * 78)
    print("  УЗЛЫ И ОПЕРАТОРЫ ПЕРЕХОДА на сфере-восьмёрок 5:3")
    print("═" * 78)
    print(f"\n  ◇ два колеса-оператора: {gears()}")
    print(f"\n  ◇ точные счёты (период 2π): {exact_counts()}")
    print(f"     пересечений экватора (перебор) = {equator_crossings_count()} (= 2·{A})")
    si = self_intersections_numeric()
    print(f"\n  ≈ самопересечений численно: {si}")
    print("═" * 78)
    print("  Операторов перехода — ДВА колеса (a=5, b=3), сцеплены LCM=15, передача → φ.")
    print("  Точно: экватор 2a=10, полюса a+a, долгота b=3. Узлов ~35 + 2 полюса. Шестерни")
    print("  часов — гипотеза-оператор (○): нужно сосчитать зубья (Фибоначчи/φ?).")
    print("═" * 78)


if __name__ == "__main__":
    print_report()
